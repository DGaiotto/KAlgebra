def test_no_single_generator_perturbation_of_S_satisfies_the_constraint():
    """Uniqueness of `S`, tested one generator at a time.

    `S·E^{(s;r)}_\\fq(X_γ)^{±1}` violates the flavoured BPS quiver constraint —
    either a non-positive power of `\\fq` appears away from the identity, or the
    `\\fq^1` coefficient stops matching the leading data — for every generator
    in the window.  That is the decidable, local form of *"there is a unique
    element of `\\cE_G` satisfying the constraint"*; it does not by itself
    settle the global statement.
    """
    Q = FlavouredQuiver([[0, 1], [-1, 0]], [2, 1])
    eng = FlavouredFactorSpectrum(Q, 4)
    eng.run()
    assert eng.constraint_violations() == []
    acc = eng._S
    reps = [Q.flavour.trivial_irrep(), Q.flavour.fundamental(0), ((2,), ())]
    checked = 0
    for k in ((1, 0), (0, 1), (1, 1), (2, 1)):
        for rep in reps:
            for two_s in (0, 1, 2):
                for exponent in (1, -1):
                    S2 = eng.times_generator(acc, k, rep, two_s, exponent)
                    assert eng.constraint_violations(S2), (k, rep, two_s, exponent)
                    checked += 1
    assert checked == 72, checked


