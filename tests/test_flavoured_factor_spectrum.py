def test_trivial_flavour_reproduces_the_unflavoured_engine_bit_for_bit():
    """`G` trivial ⇒ `\\cE_G = \\cE` and the flavoured `S` IS the unflavoured one.

    The positive control (the design notes, "Positive controls before trusting any
    scan"): the flavoured recursion must degenerate exactly, not approximately.
    """
    for B, D in (([[0, 1], [-1, 0]], 4),
                 ([[0, 2], [-2, 0]], 4),
                 ([[0, 1, -1], [-1, 0, 1], [1, -1, 0]], 3)):
        n = len(B)
        Q = FlavouredQuiver(B, [1] * n)
        eng = FlavouredFactorSpectrum(Q, D)
        eng.run()
        flat = {k: v for (k, w), v in eng.spectrum_generator().items()}
        charges = [tuple(1 if j == i else 0 for j in range(n)) for i in range(n)]
        ref = BPSFactorSpectrum(B, charges, D, order="lex")
        ref.run()
        assert flat == ref.spectrum_generator(), B
        # The only irrep of a trivial `G` is the trivial one, so `Ω(γ, r)`
        # collapses onto the unflavoured `Ω(γ)`.
        triv = Q.flavour.trivial_irrep()
        assert eng.multiplicities() == \
            {k: {triv: om} for k, om in ref.multiplicities().items()}, B


