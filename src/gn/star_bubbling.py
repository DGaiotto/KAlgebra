def _gcd(xs) -> int:
    from math import gcd
    g = 0
    for x in xs:
        g = gcd(g, abs(int(x)))
    return g


def _normal_to(vecs, d):
    """An integer normal to the span of `vecs` (`|vecs| = d−1`), or None.

    Only `d ≤ 3` is implemented; rank ≥ 4 honest-fails rather than guessing a
    facet structure."""
    if d == 1:
        return (1,)
    if d == 2:
        (a, b), = vecs
        n = (-b, a)
        g = _gcd(n)
        return tuple(x // g for x in n) if g else None
    if d == 3:
        (a, b) = vecs
        n = (a[1] * b[2] - a[2] * b[1],
             a[2] * b[0] - a[0] * b[2],
             a[0] * b[1] - a[1] * b[0])
        g = _gcd(n)
        return tuple(x // g for x in n) if g else None
    raise NotImplementedError(
        f"star_bubbling: facet normals in rank {d} are not implemented "
        "(the (★) route reaches rank <= 3)")


def _in_coroot_lattice(diff, simple_coroots, d) -> bool:
    """Is `diff` an integer combination of the simple coroots?  Exact solve."""
    n = len(simple_coroots)
    A = [[Fraction(simple_coroots[j][i]) for j in range(n)] + [Fraction(diff[i])]
         for i in range(d)]
    piv_cols, r = [], 0
    for c in range(n):
        pr = next((rr for rr in range(r, d) if A[rr][c] != 0), None)
        if pr is None:
            continue
        A[r], A[pr] = A[pr], A[r]
        pv = A[r][c]
        A[r] = [x / pv for x in A[r]]
        for rr in range(d):
            if rr != r and A[rr][c] != 0:
                f = A[rr][c]
                A[rr] = [x - f * y for x, y in zip(A[rr], A[r])]
        piv_cols.append(c)
        r += 1
    for rr in range(r, d):
        if A[rr][n] != 0:
            return False
    sol = [Fraction(0)] * n
    for idx, c in enumerate(piv_cols):
        sol[c] = A[idx][n]
    return all(x.denominator == 1 for x in sol)


def _simple_coroot_coeffs(datum, v):
    """Coefficients of `v` in the simple coroots (exact, over `Q`), or `None`
    if `v` is not in their span."""
    d = datum.dim
    cor = [tuple(c) for c in datum.simple_coroots]
    n = len(cor)
    A = [[Fraction(cor[j][i]) for j in range(n)] + [Fraction(v[i])]
         for i in range(d)]
    piv_cols, r = [], 0
    for c in range(n):
        pr = next((rr for rr in range(r, d) if A[rr][c] != 0), None)
        if pr is None:
            continue
        A[r], A[pr] = A[pr], A[r]
        pv = A[r][c]
        A[r] = [x / pv for x in A[r]]
        for rr in range(d):
            if rr != r and A[rr][c] != 0:
                f = A[rr][c]
                A[rr] = [x - f * y for x, y in zip(A[rr], A[r])]
        piv_cols.append(c)
        r += 1
    for rr in range(r, d):
        if A[rr][n] != 0:
            return None                     # not in the span of the coroots
    sol = [Fraction(0)] * n
    for idx, c in enumerate(piv_cols):
        sol[c] = A[idx][n]
    return sol


def tropical_support(datum, m) -> list:
    """Lattice points of `conv(W·m)` in the coset `m + Q^∨` — the doubly-tropical
    interval, datum-general (at rank 1 it is `{|n| ≤ m}`).  Verified against the
    `PureSUNKAlgebra` ground truth at SU(3) (a class since retired) before being
    relied on.

    Membership is decided by the **dominance order**, not by enumerating facet
    normals: for cocharacters in a common `Q^∨`-coset,

        p ∈ conv(W·m)   ⟺   m − dom(p)  is a NON-NEGATIVE integer combination
                             of the simple coroots,

    the classical characterization of the weight polytope.  This is what makes
    rank ≥ 4 reachable at all: the old route took facet normals over every pair
    of orbit points, i.e. `C(|W·m|, 2)` directions chosen `d−1` at a time —
    already ~10¹⁰ combinations at rank 4 — and needed a dimension-specific
    cross-product (`_normal_to`, implemented only to dim 3).  The dominance test
    is exact, needs no normals, and is uniform in the rank."""
    orbit = sorted({tuple(datum.act_cochar(w, m)) for w in datum.weyl_elements()})
    d = datum.dim
    simple_coroots = [tuple(c) for c in datum.simple_coroots]
    lo = [min(p[i] for p in orbit) for i in range(d)]
    hi = [max(p[i] for p in orbit) for i in range(d)]
    m = tuple(m)
    # `conv(W·m)` is Weyl-invariant in `m`, so the dominance comparison must be
    # made against `m`'s DOMINANT representative — otherwise a non-dominant
    # input (SU(3) at the anti-dominant `(−1,−1)`, G₂ at `(1,0)`) compares
    # against the wrong apex and the support collapses.  `leading_orbit` is
    # likewise Weyl-invariant in `m`, so this keeps the two in step.
    m_dom = tuple(datum.dominant_cochar_rep(m))
    out = []
    # Enumerate on the coset `m + Z^d`, not on the absolute integer grid.  For an
    # integral `m` these coincide, so the simply-connected behaviour is unchanged;
    # for a **fractional coweight** (a non-simply-connected global form) the
    # support lives on `m + Q^∨` and the absolute grid would miss it entirely —
    # and `range()` would reject the `Fraction` bounds outright.  The `diff ∈ Q^∨`
    # filter immediately below is exactly the condition this enumeration respects,
    # so shifting the grid to `m` is the honest reading of the existing intent.
    import math as _math
    offsets = [range(_math.ceil(lo[i] - m[i]), _math.floor(hi[i] - m[i]) + 1)
               for i in range(d)]
    for k in itertools.product(*offsets):
        p = tuple(m[i] + k[i] for i in range(d))
        diff = tuple(p[i] - m[i] for i in range(d))
        if not _in_coroot_lattice(diff, simple_coroots, d):
            continue
        dom = tuple(datum.dominant_cochar_rep(p))
        gap = tuple(m_dom[i] - dom[i] for i in range(d))
        coeffs = _simple_coroot_coeffs(datum, gap)
        if coeffs is None or any(c < 0 for c in coeffs):
            continue
        out.append(tuple(p))
    return sorted(out)


def _bezout_functional(alpha0, d):
    """Integer `u` with `u·α₀ = 1` (so `λ ↦ u·λ` is the `α₀`-coordinate)."""
    idx = [i for i, a in enumerate(alpha0) if a != 0]
    if not idx:
        raise ValueError("zero root direction")

    def ext(a, b):
        if b == 0:
            return (abs(a), 1 if a > 0 else -1, 0)
        g0, x, y = ext(b, a % b)
        return (g0, y, x - (a // b) * y)

    u = [0] * d
    cur_g = abs(alpha0[idx[0]])
    u[idx[0]] = 1 if alpha0[idx[0]] > 0 else -1
    for i in idx[1:]:
        g0, s, t = ext(cur_g, alpha0[i])
        for j in range(d):
            u[j] = u[j] * s
        u[i] += t
        cur_g = g0
    if sum(u[i] * alpha0[i] for i in range(d)) != 1:
        raise ValueError(f"{alpha0} is not primitive")
    return u


def wall_is_probed(datum, alpha, k, e, admits_e, pad=1, span=4) -> bool:
    """Does **(★) for the form** see the wall `v^α = 𝖖^{−k}` at all?

    Derived, not guessed.  Multiplying by `χ_e` changes a numerator but **not** the
    denominators, so the residue of `x·χ_e` on a wall is `Res_wall(x)·χ_e|_wall`.
    Hence the wall imposes a condition iff **some admitted `χ_e` is non-zero on it**;
    a wall where every admitted character vanishes imposes nothing, and its equation
    is not part of `Λ_H`-preservation.

    Restricting a character to the wall is exactly what `wall_restrict` does to a
    numerator, so that is what is reused here: `χ_e` is built with `wrq_torus.wilson`
    and restricted; the wall is "probed" as soon as one admitted `e` leaves a
    non-zero component.

    `e` is the label's own electric charge (always in the test set — the identity of
    `Λ_H` is `χ_0` and `e` itself must be admitted for the label to be a line at
    all); `span` bounds the extra admitted weights swept.  Conservative by
    construction: if nothing can be shown to vanish, the wall is kept.

    ⚠ **MEASURED INERT (2026-08-25): this returns `True` for every real form, so
    the `dropped_walls` branch in `joint_solve` is unreachable.**  The reason is
    the sentence above taken seriously — `χ_0 = 1` is the identity of `Λ_H`, it is
    admitted by *every* form, it is always in `tests`, and the constant `1`
    vanishes on no wall.  So the sweep always finds a survivor on the first
    character it tries.  `False` is obtainable only from a predicate admitting
    **nothing**, which is not a form.  Measured: 0 walls dropped at PSU(3),
    SO(5), Sp(2)/Z₂ and SO(3).

    This is not a bug in the predicate — it is the correct answer, and it says
    something about (★) worth keeping: **the residue-cancellation half of (★) is
    form-independent.**  The wall condition `Res_n + Res_p = 0` IS the `χ_0`
    member of the family, so the cover's extra characters impose nothing beyond
    it, and restricting to `Λ_H ⊊ R(G̃)` removes nothing.  Which is exactly what
    `preserves_neumann_module` says below — the electric half of the form has to
    be asked of the module, not of the walls.  Kept rather than deleted because
    the derivation is the load-bearing part; the plumbing in `joint_solve` is
    harmless and documents the same conclusion at its call site."""
    import itertools as _it
    d = datum.dim
    tests = [tuple(e)]
    for c in _it.product(range(0, span + 1), repeat=d):
        w = tuple(c)
        if w not in tests and admits_e(w):
            tests.append(w)
    zero = (0,) * d
    for mu in tests:
        if not admits_e(tuple(mu)):
            continue
        # `wilson` returns a WRQTorus ELEMENT; its magnetic-0 residual carries the
        # character as a TorusRational, whose `.num` is what `wall_restrict` takes.
        chi = W.wilson(datum, tuple(mu))
        res = chi.residual(zero)
        if res is None:
            continue
        res = res.simplify()
        comps = wall_restrict(res.num, alpha, k, d)
        for comp in comps.values():
            for v in comp.values():
                if not v.is_zero():
                    return True                 # this admitted χ_e survives
    return False


def wall_restrict(num: TorusLaurent, alpha, k, d) -> dict:
    """Restrict a numerator to the wall `v^α = 𝖖^{−k}`, split into the `Z/g`
    isotypic components (`α = g·α₀`).

    The torsion split is essential and invisible in type A: `v^{α₀}` is only
    determined up to a `g`-th root of unity, so the restriction splits into `g`
    components each of which must vanish **separately**.  At SU(2) (`α = (2)`,
    `g = 2`) this is the even/odd split; at SU(3) every root is primitive
    (`g = 1`) so it never shows; at B₂/G₂ both cases occur."""
    g = _gcd(alpha)
    alpha0 = tuple(x // g for x in alpha)
    u = _bezout_functional(alpha0, d)
    if (k % g) != 0:
        raise NotImplementedError(f"wall shift {k} not divisible by g={g}")
    kk = k // g
    out: dict = {}
    for lam, coef in num.terms.items():
        if coef.is_zero():
            continue
        c = sum(u[i] * lam[i] for i in range(d))
        rest = tuple(lam[i] - c * alpha0[i] for i in range(d))
        comp = out.setdefault(c % g, {})
        comp[rest] = comp.get(rest, LaurentPoly.zero()) + coef * LaurentPoly.q(-kk * c)
    return {cc: {r: v for r, v in comp.items() if not v.is_zero()}
            for cc, comp in out.items()}


