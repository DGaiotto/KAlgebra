"""`S` for a BPS quiver with a non-Abelian flavour group `G` — the flavoured
`\\cE_G` construction.

**Provisional module / class name.**  `flavoured_factor_spectrum` /
`FlavouredFactorSpectrum` were chosen to sit beside `bps_factor_spectrum` /
`BPSFactorSpectrum`, whose construction this generalises.  Module and class
names are the author's call (the design notes, contract surface); both rename in one
command if a better one is ruled.

The unflavoured axioms
----------------------

From the paper (`\\cG`, `\\cE`, `E^{(s)}_\\fq` are the paper's own symbols):

* `\\cG` is the pro-nilpotent group of elements `1 + Σ_{γ∈Γ_+} g_γ(\\fq) X_γ`
  with `g_γ ∈ Z[\\fq, \\fq^{-1}, (1-\\fq^{2n})^{-1}]` — the Habiro-type ring
  carried here by `habiro.HabiroElement`;
* `E_\\fq(x) = (-\\fq x; \\fq^2)_∞^{-1}` and, for `s ∈ ½N`,

      E^{(s)}_\\fq(x) = ∏_{j=-s}^{s} E_\\fq((-1)^{2s} \\fq^{2j} x)^{(-1)^{2s}} ;

* `\\cE ⊂ \\cG` is the subgroup generated by `E^{(s)}_\\fq(X_γ)^{±1}`,
  `γ ∈ Γ_+`;
* the **BPS quiver constraint** is `S = 1 - \\fq Σ_i X_{γ_i} + O(\\fq^2)`, and
  `S` is conjecturally the unique element of `\\cE` satisfying it;
* **PBW factorization**: every `g ∈ \\cE` factors as
  `∏_{γ,s} E^{(s)}_\\fq(X_γ)^{Ω(γ,s)}` in any total order on `Γ_+ × ½N`, with
  integral exponents.

`bps_factor_spectrum.BPSFactorSpectrum` implements exactly this.  In its code
the multiplet is spelled `m_s(γ)`; that spelling is code-local and the
documents say `E^{(s)}_\\fq(X_γ)`.

The flavoured axioms
--------------------

Let `G` be a flavour group — in practice `G = ∏_a SU(N_a)`, with node `a`
carrying the `N_a`-dimensional irrep.  Write `μ^w` for the
character of the maximal torus at the weight `w`; the `μ` are **central** and
carry `\\fq`-degree zero.  Then for an irrep `r` of `G`

    E^{(s;r)}_\\fq(X_γ)  :=  ∏_{w ∈ r} E^{(s)}_\\fq(μ^w X_γ)

(the product over the weights of `r` **with multiplicity**), and `\\cE_G` is
the subgroup of the flavoured `\\cG` generated by the
`E^{(s;r)}_\\fq(X_γ)^{±1}` for `γ ∈ Γ_+`, `s ∈ ½N` and `r` an irrep of `G`.
The **flavoured BPS quiver constraint** is

    S  =  1  -  \\fq Σ_a χ_{r_a}(μ) X_{γ_a}  +  O(\\fq^2) ,

i.e. the node charge monomials `X_{γ_a}` of the unflavoured constraint are
replaced by the sequences `μ^w X_{γ_a}`, `w ∈ r_a`.  The flavoured PBW
factorization reads `g = ∏_{γ,s,r} E^{(s;r)}_\\fq(X_γ)^{Ω(γ,s,r)}`, so the
multiplicity `Ω(γ)` is valued in `R(G) ⊗ P` rather than in `P` alone
(`P` = palindromic `Z[\\fq^{±1}]`, `Z`-basis the `χ_s`) — a flavour-rep times
spin-rep multiplicity, which is what a BPS multiplicity physically is.

Why this is well defined, and what it costs
-------------------------------------------

`μ^w X_γ` is `X_{γ+w}` in the lattice enlarged by the flavour weights, and the
enlarged charges `γ + w`, `w ∈ r`, all pair to zero with one another (the
flavour directions are central and the gauge charge is shared).  So every
generator of `\\cE_G` is an ordinary product of commuting `E^{(s)}` factors in
the enlarged lattice, `\\cE_G ⊆ \\cE_enlarged`, and the flavoured constraint is
*literally* the enlarged one, since `χ_{r_a}(μ) X_{γ_a} = Σ_{w∈r_a} X_{γ_a+w}`.

Two consequences worth stating because they are easy to get wrong:

1. **Flavoured uniqueness is inherited**, not new.  What is substantive is
   `S_enlarged ∈ \\cE_G` — that the enlarged `S`'s PBW multiplicities, grouped
   by gauge charge, assemble into honest `G`-characters.  That is the claim
   this module's battery tests, against the enlarged engine as an independent
   ground truth.
2. **This is not a cost win by itself.**  The reduced cone is smaller, but the
   flavour weights return as fibres over each reduced cone point and the total
   accumulator size is unchanged.  The gains are that `Ω` is a `G`-character
   (the reps are the natural labels), that the dictionary key becomes the
   quiver-with-`G`-data rather than the unfolded quiver, and that node data
   with a repeated weight is expressible at all.  A `|W|`-fold saving is
   available by solving one `Ω` per Weyl orbit; it is **not** taken here, so
   that `Ω`'s Weyl invariance stays an *output* of the recursion and therefore
   evidence, rather than being imposed (the audit, enforced vs emergent).

Node reps with a repeated weight
--------------------------------

A rep whose weight multiplicities exceed one cannot be unfolded into a BPS
quiver — two nodes would carry the same charge.  The author's ruling
(2026-09-13) is that this *"will never effectively happen as the node irreps
are fundamentals of `SU(N_a)` in reality"*, and the battery follows that: every
tested node datum unfolds, which is what gives the tests their ground truth.
The implementation nevertheless accepts an arbitrary irrep at a node, because
it costs nothing — and because repeated weights do occur in the **derived**
`Ω` at composite charges, which is where the `R(G)` bookkeeping earns its keep.

Exactness
---------

Coefficients are `HabiroElement` throughout and the only truncation is along
the reduced positive cone; no `\\fq`-truncation is ever taken (the design notes,
"Exact arithmetic until the very end").
"""

