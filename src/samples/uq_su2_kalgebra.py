class UqSU2KAlgebra(KAlgebra):
    """The `U_𝖖(sl_2)` quantum group as an SU(2)-flavoured `K_𝖖`-algebra —
    the draft's Definition (`sec:uqsl2`), implemented directly.  See the module
    docstring for the definition, the labels and the ring."""

    def __init__(self, ring: ZPlusRing | None = None) -> None:
        if ring is None:
            ring = SUNZPlusRing(2)
        if isinstance(ring, SUNZPlusRing):
            if ring.N != 2:
                raise ValueError(
                    f"UqSU2KAlgebra: the flavour ring is R(SU(2)); got {ring!r}")
        elif not isinstance(ring, SU2ZPlusRing):
            raise TypeError(
                "UqSU2KAlgebra: ring must be SUNZPlusRing(2) or SU2ZPlusRing, "
                f"got {ring!r}")
        self._R = ring
        self._chi1 = self.chi(1)
        self._engine = _Engine(ring, self._chi1)
        self._trace_table: dict[int, dict[int, dict]] = {}   # K → cartan_traces(K)
        self._tr_cache: dict[tuple[int, int], RPowerSeries] = {}

    # ----- ring keys ---------------------------------------------------
    def chi(self, k: int):
        """The coefficient-ring key of the character `χ_k` (spin `k/2`,
        dimension `k + 1`); `chi(0)` is the identity, `chi(1)` the fundamental."""
        if k < 0:
            raise ValueError(f"chi(k): k ≥ 0 required, got {k}")
        if isinstance(self._R, SUNZPlusRing):
            return () if k == 0 else (k,)
        return k

    def spin2(self, w) -> int:
        """Inverse of `chi`: the highest weight `k` of the ring key `w`."""
        if isinstance(self._R, SUNZPlusRing):
            w = tuple(w)
            return 0 if not w else int(w[0])
        return int(w)

    # ----- label constructors -------------------------------------------
    def K(self, n: int = 1, k: int = 0):
        """The label of `χ_k · K^n`."""
        return (('K', int(n)), self.chi(k))

    def E(self, a: int = 1, b: int = 0, k: int = 0):
        """The label of `χ_k · E_{a,b}`, `E_{a,b} = 𝖖^{−ab} E^a K^b` (`a ≥ 1`)."""
        if a < 1:
            raise ValueError(f"E_{{a,b}} needs a ≥ 1, got a={a}")
        return (('E', int(a), int(b)), self.chi(k))

    def F(self, a: int = 1, b: int = 0, k: int = 0):
        """The label of `χ_k · F_{a,b}`, `F_{a,b} = 𝖖^{ab} F^a K^b` (`a ≥ 1`)."""
        if a < 1:
            raise ValueError(f"F_{{a,b}} needs a ≥ 1, got a={a}")
        return (('F', int(a), int(b)), self.chi(k))

    @staticmethod
    def _check(label) -> tuple:
        try:
            sector, w = label
            kind = sector[0]
        except (TypeError, ValueError):
            raise ValueError(f"UqSU2KAlgebra: malformed label {label!r}")
        if kind == 'K':
            _, n = sector
            return (('K', int(n)), w)
        if kind in ('E', 'F'):
            _, a, b = sector
            if a < 1:
                raise ValueError(f"UqSU2KAlgebra: {kind}_{{a,b}} needs a ≥ 1: {label!r}")
            return ((kind, int(a), int(b)), w)
        raise ValueError(f"UqSU2KAlgebra: unknown sector {kind!r} in {label!r}")

    # ----- canonical ↔ internal ----------------------------------------
    @staticmethod
    def _to_internal(label):
        """canonical label ↦ (internal monomial key, internal coefficient):
        `E_{a,b} = 𝖖^{ab} K^b E^a`, `F_{a,b} = 𝖖^{ab} F^a K^b`."""
        (sector, w) = label
        kind = sector[0]
        if kind == 'K':
            return ('K', 0, sector[1], w), LaurentPoly.one()
        _, a, b = sector
        return (kind, a, b, w), _q(a * b)

    @staticmethod
    def _to_canonical(X: dict) -> dict:
        """internal `{(side, p, k, w): LaurentPoly}` ↦ `{canonical label: LaurentPoly}`
        (the E/F sides pick up `𝖖^{−pk}`)."""
        out: dict = {}
        for (side, p, k, w), c in X.items():
            if side == 'K':
                _add(out, (('K', k), w), c)
            else:
                _add(out, ((side, p, k), w), _q(-p * k) * c)
        return out

    # ----- the six primitives ------------------------------------------
    def coefficient_ring(self) -> ZPlusRing:
        return self._R

    def identity(self):
        return (('K', 0), self._R.one_basis())

    def multiply(self, a, b) -> Element:
        a, b = self._check(a), self._check(b)
        ma, ca = self._to_internal(a)
        mb, cb = self._to_internal(b)
        return Element(self._to_canonical(self._engine.mono_mult(ma, ca, mb, cb)))

    def rho(self, a):
        (sector, w) = self._check(a)
        ws = self._R.star_basis(w)               # the identity on SU(2)
        kind = sector[0]
        if kind == 'K':
            return (('K', -sector[1]), ws)
        _, p, k = sector
        if kind == 'E':
            return (('F', p, -p - k), ws)        # ρ(E_{a,b}) = F_{a,−a−b}
        return (('E', p, p - k), ws)             # ρ(F_{a,b}) = E_{a,a−b}

    def rho_inverse(self, a):
        (sector, w) = self._check(a)
        ws = self._R.star_basis(w)
        kind = sector[0]
        if kind == 'K':
            return (('K', -sector[1]), ws)
        _, p, k = sector
        if kind == 'F':
            return (('E', p, -p - k), ws)        # ρ⁻¹(F_{a,c}) = E_{a,−a−c}
        return (('F', p, p - k), ws)             # ρ⁻¹(E_{a,c}) = F_{a,a−c}

    def trace(self, a, K: int = 20) -> RPowerSeries:
        (sector, w) = self._check(a)
        if sector[0] != 'K':
            return RPowerSeries.zero(self._R, K)
        tr = self.trace_K(sector[1], K)
        if w == self._R.one_basis():
            return tr
        return tr * self._R.basis_element(w)

    # ----- the Cartan-sector trace ---------------------------------------
    def trace_K(self, n: int, K: int = 20) -> RPowerSeries:
        """`Tr(K^n) = [x^n] G(x, μ)` through `𝖖^K`, as an `RPowerSeries` over
        the flavour ring (the μ-Laurent polynomial at each order un-branched
        into characters through `from_abelian`, virtual characters allowed —
        Wilson-line indices are signed)."""
        n = int(n)
        key = (abs(n), K)                        # Tr K^{−n} = Tr K^n (x ↔ x⁻¹)
        got = self._tr_cache.get(key)
        if got is not None:
            return got
        table = self._trace_table.get(K)
        if table is None:
            table = cartan_traces(K)
            self._trace_table[K] = table
        poly = table.get(abs(n), {})
        by_q: dict[int, dict] = {}
        for (e, j), c in poly.items():
            by_q.setdefault(e, {})[(j,)] = c
        U1 = AbelianZPlusRing(rank=1)
        coeffs: dict[int, RElement] = {}
        for e, mu in by_q.items():
            r = self._R.from_abelian(RElement(U1, mu), allow_virtual=True)
            if not r.is_zero():
                coeffs[e] = r
        got = RPowerSeries(self._R, coeffs, K)
        self._tr_cache[key] = got
        return got

    # ----- the flavour-lift coordinate ---------------------------------
    def r_label_decompose(self, label):
        (sector, w) = self._check(label)
        return (sector, self._R.one_basis()), w

    def r_label_compose(self, section, r_basis_label):
        (sector, _one) = section
        return (sector, r_basis_label)

    def embed_R(self, r: RElement) -> Element:
        """`ι : R(SU(2)) ↪ A`, `χ_k ↦ χ_k · 1 = (('K', 0), χ_k)`."""
        if not isinstance(r, RElement) or r.ring != self._R:
            raise TypeError(
                "UqSU2KAlgebra.embed_R: argument must be an RElement over "
                "coefficient_ring()")
        out = Element.zero()
        for w, c in r.terms.items():
            if c:
                out = out + Element.basis((('K', 0), w)) * c
        return out

    # ----- conveniences --------------------------------------------------
    def basis_iter(self, max_a: int = 2, max_b: int = 2, max_k: int = 1):
        """Labels with `1 ≤ a ≤ max_a`, `|b| ≤ max_b` (E and F sectors), Cartan
        powers `|n| ≤ max_b`, characters `χ_k` with `k ≤ max_k`."""
        for k in range(max_k + 1):
            for n in range(-max_b, max_b + 1):
                yield self.K(n, k)
            for a in range(1, max_a + 1):
                for b in range(-max_b, max_b + 1):
                    yield self.E(a, b, k)
                    yield self.F(a, b, k)

    def __repr__(self) -> str:
        return f"UqSU2KAlgebra(ring={self._R!r})"


