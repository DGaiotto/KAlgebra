class U1A1AoddKAlg(ConeKAlgebra):
    """u(1)-gauged [A_1, A_{2k+1}] AD theory for any k ≥ 1.
    Bootstraps chord_charges and MULT_TABLE from BPS at __init__."""

    def __init__(self, k: int):
        self.k = k
        self.H = 2 * k + 4
        self._R = TrivialZPlusRing()
        chord_charges, E_charge, mult_table = generate_mult_table(k)
        self.chord_charges = chord_charges
        self.E_charge = E_charge
        self._mult_table = mult_table
        self._cone_data = U1A1AoddConeData(
            k, chord_charges, E_charge, mult_table, mult_table.family_periods,
        )

    def coefficient_ring(self): return self._R
    def identity(self): return ((), 0)

    def cone_data(self):
        return self._cone_data

    # `multiply` inherited from ConeKAlgebra.

    def rho(self, label):
        """ρ on a cone label `(factors, e_E)`: shift each chord
        `(a, i) → (a, i+1 mod P_a)`, accumulate the wrap E-drift at the
        last orbit element, and negate the E-power (`ρ(E)=E⁻¹`).

        The wrap drift + E-inversion are essential: without them ρ drops the
        periodicity μ/E-pickup and disagrees with BPS on the wrap letters and
        on every `e_E≠0` label (it then fails `verify_rho_is_automorphism` and
        corrupts the multi-letter trace — the same long-chord ρ/trace defect
        fixed in `U1HexagonKAlg`).  Matches the good-branch
        `u1a1aodd_kalg._rho_label_cone`; validated 0-mismatch vs BPS."""
        per = self._mult_table.family_periods
        eps = self._mult_table.eps_wrap
        new_factors = []
        drift = 0
        for (a, i, e) in label[0]:
            if i == per[a] - 1:
                drift += e * eps[a]
            new_factors.append((a, (i + 1) % per[a], e))
        return (tuple(sorted(new_factors)), -label[1] + drift)

    def rho_inverse(self, label):
        """Inverse of `rho`: shift `i → i-1 mod P_a`, accumulate the wrap drift
        when leaving the first orbit element, and invert the E-power."""
        per = self._mult_table.family_periods
        eps = self._mult_table.eps_wrap
        new_factors = []
        drift = 0
        for (a, i, e) in label[0]:
            if i == 0:
                drift += e * eps[a]
            new_factors.append((a, (i - 1) % per[a], e))
        return (tuple(sorted(new_factors)), -(label[1] - drift))

    def _mag_charge(self, label):
        factors, _ = label
        return sum(self._cone_data.MU_LETTER_QPOWER[(a, i)] * e
                   for (a, i, e) in factors)

    def trace_layer1(self, label):
        if self._mag_charge(label) != 0:
            return {}
        factors, e_E = label
        letters = [(a, i) for (a, i, exp) in factors for _ in range(exp)]
        gens_set = set(letters)
        cones = self._cone_data.cones()
        is_cone_mono = any(gens_set <= set(c) for c in cones) if gens_set else True
        if not is_cone_mono:
            half = len(letters) // 2
            def to_label(lst, e_E_local):
                from collections import Counter
                ctr = Counter(lst)
                f = tuple(sorted((a, i, e) for (a, i), e in ctr.items()))
                return (f, e_E_local)
            prod = self._cone_data.derived_multiply(
                to_label(letters[:half], e_E), to_label(letters[half:], 0))
            out = {}
            for sub_lbl, sub_coef in prod.terms.items():
                sub_trace = self.trace_layer1(sub_lbl)
                for ky, v in sub_trace.items():
                    contribution = sub_coef * v
                    out[ky] = out.get(ky, LaurentPoly({})) + contribution
            return {ky: v for ky, v in out.items() if not v.is_zero()}
        simplified = self._cone_data.simplify_trace_via_cone_data(self, label)
        return {ky: v for ky, v in simplified.terms.items() if not v.is_zero()}

    def trace(self, label, K=20):
        return self.trace_layer1(label)

    # ----- KAlgebra._canonical_rho2_orbit_rep override -------------------

    def _canonical_rho2_orbit_rep(self, label):
        """Closed-form ρ²-orbit representative (drift quotient).

        With the wrap-pickup-correct ρ (`ρ(E)=E⁻¹` + wrap E-drift), ρ² is
        **not** finite-order on a single chord: it shifts position
        `i → i+2 (mod P)` AND drifts the E-power by the accumulated wrap
        pickup, so the orbit runs off to `e = ±∞` (the default orbit walk
        would not terminate).  Per the `ConeKAlgebra` contract a closed-form
        canonical rep is required (cf. `U1SquareKAlg` / the good-branch
        `u1a1aodd_kalg`).  E-powers are ρ²-fixed (`ρ²(E)=E`); a single chord
        reduces by the drift quotient; multi-gen seeds are left as-is (their
        trace is read by charge, which is ρ²-invariant, so the final linear
        `Σ c_seed·Tr(seed)` is unaffected)."""
        factors, e = label
        if len(factors) == 0:
            return ((), e)                                  # E^e: ρ²-fixed
        if len(factors) == 1 and factors[0][2] == 1:
            from math import gcd
            a = factors[0][0]
            s = self._mult_table.family_periods[a]
            P = s // gcd(s, 2)                              # ρ²-period in position
            members, cur = [], label
            for _ in range(P):
                members.append(cur)
                cur = self.rho(self.rho(cur))               # ρ²
            D = cur[1] - e                                  # E-drift over one period
            if D == 0:                                      # finite orbit
                return min(members, key=lambda m: (m[0][0][1], m[1]))
            istar = min(m[0][0][1] for m in members)        # canonical position
            estar = next(m[1] for m in members if m[0][0][1] == istar)
            return (((a, istar, 1),), estar % abs(D))       # drift quotient
        return label                                        # multi-gen: leave as-is

