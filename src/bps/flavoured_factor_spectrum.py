class FlavouredQuiver:
    """A BPS quiver whose nodes carry irreps of a flavour group `G`.

    `S` depends only on the quiver (the paper's `S[Q]`), so the datum here is
    the exchange matrix together with the flavour assignment, and the node
    charges are the standard basis of `Γ`.  The datum is hashable and has a
    canonical form up to relabelling of the nodes, so that it can serve as a
    dictionary key the way the bare exchange matrix does in
    `quiver_enumeration`.

    Parameters
    ----------
    pairing
        The `g x g` antisymmetric exchange matrix of the **reduced** quiver —
        one node per flavoured node.
    flavour
        A `FlavourSpace`, or the sequence of `N_i` defining one.
    node_reps
        One `Irrep` per node.  The default is the author's *"in reality"* case:
        factor `a` is `SU(N_a)` and node `a` carries its fundamental.
    """

    def __init__(self, pairing: Sequence[Sequence[int]],
                 flavour: FlavourSpace | Sequence[int],
                 node_reps: Sequence[Irrep] | None = None):
        B = [[int(x) for x in row] for row in pairing]
        g = len(B)
        if any(len(row) != g for row in B):
            raise ValueError("pairing must be square")
        for i in range(g):
            for j in range(g):
                if B[i][j] != -B[j][i]:
                    raise ValueError("pairing must be antisymmetric")
        self.pairing = tuple(tuple(row) for row in B)
        self.rank = g
        self.flavour = (flavour if isinstance(flavour, FlavourSpace)
                        else FlavourSpace(flavour))
        if node_reps is None:
            if len(self.flavour.factors) != g:
                raise ValueError(
                    "default node_reps needs one SU(N) factor per node "
                    f"({g}), got {len(self.flavour.factors)}")
            node_reps = [self.flavour.fundamental(a) for a in range(g)]
        if len(node_reps) != g:
            raise ValueError(f"need one irrep per node ({g})")
        self.node_reps = tuple(self.flavour._normalise(r) for r in node_reps)
        self._weights = tuple(self.flavour.irrep_weights(r)
                              for r in self.node_reps)

    def __repr__(self) -> str:
        return (f"FlavouredQuiver(rank={self.rank}, {self.flavour!r}, "
                f"reps={list(self.node_reps)})")

    def key(self) -> tuple:
        """A hashable identity, NOT canonicalised — relabelling the nodes
        changes it.  Use `canonical_key()` for the dictionary identity."""
        return (self.pairing, self.flavour.factors, self.node_reps)

    def node_colours(self) -> tuple:
        """Each node's flavour datum, as a colour an isomorphism must preserve.

        An isomorphism of flavoured quivers is a node permutation **together
        with** an automorphism of `G` permuting its simple factors — so a
        node's colour must not name a factor by its position in the product.
        Naming it by position gets two things wrong: relabelling the nodes then
        changes the key, and `A1 × A1` with an `SU(2)` at each node reports no
        symmetry although the two nodes are plainly interchangeable.

        The colour of a node is therefore the multiset of `(N_i, λ)` over the
        simple factors it is non-trivially charged under — the factor's
        **rank** and the rep, never the factor's index.  That is comparable
        across quivers, which a dictionary key must be.

        **Complete exactly when no factor is shared** — see
        `shares_a_flavour_factor`, which `canonical_key` refuses on.
        """
        charged = [{i: lam for i, lam in enumerate(self.node_reps[a]) if lam}
                   for a in range(self.rank)]
        return tuple(tuple(sorted((self.flavour.factors[i], lam)
                                  for i, lam in charged[a].items()))
                     for a in range(self.rank))

    def shares_a_flavour_factor(self) -> bool:
        """Is some simple factor of `G` charged under by more than one node?

        In the author's stated setting this is `False`: each group of `N_a`
        identical nodes gets its own `SU(N_a)` and the reduced node carries its
        fundamental, so the node-to-factor map is injective on the factors that
        are used at all.
        """
        seen: set[int] = set()
        for a in range(self.rank):
            for i, lam in enumerate(self.node_reps[a]):
                if not lam:
                    continue
                if i in seen:
                    return True
                seen.add(i)
        return False

    def canonical_key(self) -> tuple:
        """The dictionary identity: the flavoured quiver up to node relabelling.

        `quiver_enumeration.canonical_form` with the flavour datum as the node
        colour — an entry is then the pair (canonical exchange matrix, node
        colours in canonical order).  Two flavoured quivers have the same key
        iff a node permutation carries one to the other preserving the reps,
        which is precisely when they have the same `S`.

        This is the key a **dictionary of quivers with `G` symmetry** would use; the flavour datum being just another node colour is
        why the design record's machinery extends to it without change.

        **Honest-fails when a flavour factor is shared between nodes.**  The
        node colours are then not a complete invariant — two nodes under one
        `SU(2)` and two nodes under `SU(2) × SU(2)` give identical node colours
        and are different objects — and separating them needs the node–factor
        incidence canonicalised jointly with the quiver, which is not built.
        Rather than return a key that silently conflates them, this refuses.
        The case does not arise in the setting the construction is for (one
        factor per node group).
        """
        from quiver_enumeration import canonical_form
        if self.shares_a_flavour_factor():
            raise NotImplementedError(
                "canonical_key: a flavour factor is charged under by more "
                "than one node, and the node colours are not a complete "
                "invariant there — the node-factor incidence would have to be "
                "canonicalised jointly with the quiver, which is not built")
        colours = self.node_colours()
        cf = canonical_form(self.pairing, colours=colours)
        return (cf.key, tuple(colours[cf.perm[i]] for i in range(self.rank)))

    def colour_preserving_aut_order(self) -> int:
        """`|Aut|` of the flavoured quiver — node symmetries preserving the reps.

        Smaller than the uncoloured `|Aut(B)|` whenever the flavour assignment
        breaks a symmetry of the bare exchange matrix.
        """
        from quiver_enumeration import canonical_form
        return canonical_form(self.pairing, colours=self.node_colours()).aut_order

    def node_weights(self, a: int) -> dict[Weight, int]:
        return dict(self._weights[a])

    def bracket(self, k: Vec, l: Vec) -> int:
        B = self.pairing
        return sum(k[i] * B[i][j] * l[j]
                   for i in range(self.rank) if k[i]
                   for j in range(self.rank) if l[j])

    # ----- the chart on `Gamma_gauge (+) P` ------------------------------
    def gauge_weight_chart(self) -> tuple[list[list[int]], list[Vec],
                                          list[tuple[int, Weight]]]:
        """Chart data on `Γ_gauge ⊕ P` — the flavour weight lattice as a FACTOR.

        The author's ruling, 2026-09-14: *"in order to place your algebra in a flavoured
        KAlgebra context, you need to have the weight lattice of the non-Abelian
        flavour as a factor of the overall charge lattice.  Then when looking
        for F's you can relax the gauge-N-ality connection and satisfy the
        axioms"*.

        Returns `(pairing, node_charges, labels)` for the BPS chart on the
        lattice `Γ_gauge ⊕ P`, `P = ⊕_a P(SU(N_a))` in `to_abelian`
        coordinates: the pairing is the reduced `B` on the gauge block and zero
        on the flavour block (the flavour directions are isotropic and pair to
        zero with the gauge ones), and the node charges are `e_a ⊕ w` for each
        weight `w` of node `a`'s rep.

        This is **not** `unfold()`.  The unfolded quiver's node charges span
        only a finite-index sublattice of this one — for a node under `SU(2)`
        they generate the difference of the two leaf charges, i.e. the *root*
        `2ω`, never the fundamental weight `ω` itself.  That index is exactly
        what manufactured the N-ality condition in `enlarged_charge`, the
        absence of a flavour-trivial section at a charge of non-zero N-ality,
        and the factor of two between the chart's `ker(B)` coordinates and
        `FlavourSpace` weights.  Here `ω` is a lattice point, so every
        `(γ, w)` is a charge, the trivial irrep sections every gauge charge,
        and the flavour ring embeds centrally in full.

        On a single `SU(N)` factor this reproduces the input that
        `src/bps/gf_bps_kalgebra.py::GfBPSKAlgebra` already takes —
        asserted, not claimed, in `tests/test_gbps_kalgebra.py`.
        """
        F = self.flavour
        g, d = self.rank, F.dim
        n = g + d
        pairing = [[0] * n for _ in range(n)]
        for i in range(g):
            for j in range(g):
                pairing[i][j] = int(self.pairing[i][j])
        charges: list[Vec] = []
        labels: list[tuple[int, Weight]] = []
        for a in range(g):
            for w in sorted(self.node_weights(a)):
                v = [0] * n
                v[a] = 1
                for j in range(d):
                    v[g + j] = w[j]
                charges.append(tuple(v))
                labels.append((a, w))
        return pairing, charges, labels

    def gf_chart_data(self):
        """Constructor data for `src/bps/gf_bps_kalgebra.py::GfBPSKAlgebra`.

        Returns `(pairing, node_charges, reflections, ring, mu_basis)` — the five
        arguments that class takes by hand — on the `Γ_gauge ⊕ P` chart of
        `gauge_weight_chart`.

        * `reflections` are the simple transpositions of `W = ∏_a S_{N_a}`,
          generated per factor in that factor's `to_abelian` coordinates
          `x_i = w_i − w_N`: `s_i` (`i < N−1`) swaps `x_i, x_{i+1}`, and the last
          one sends `x_j ↦ x_j − x_{N−1}` (`j < N−1`), `x_{N−1} ↦ −x_{N−1}`.  They
          act trivially on the gauge block.
        * `mu_basis` is the trailing unit vectors: `gauge_weight_chart` PLACES the
          weight lattice as a named block, so the alignment between `ker B` and the
          ring's weight coordinates is known by construction rather than solved for.

        For one simple factor this reproduces that class's own hand-written `SU(2)`
        and `SU(3)` matrices — asserted in `tests/test_gbps_kalgebra.py`, which is
        the check that the generated data is the established convention and not a
        parallel one.
        """
        F = self.flavour
        pairing, charges, _labels = self.gauge_weight_chart()
        g, d = self.rank, F.dim
        n = g + d

        def unit(i):
            return [1 if k == i else 0 for k in range(n)]

        reflections = []
        for a, N in enumerate(F.factors):
            if N <= 1:
                continue
            # offset within the FULL lattice: the weight block starts at `g`
            lo, wd = g + F.offsets[a], F.widths[a]
            for i in range(N - 1):
                M = [unit(k) for k in range(n)]        # identity
                if i < N - 2:
                    M[lo + i] = unit(lo + i + 1)
                    M[lo + i + 1] = unit(lo + i)
                else:                                   # the last transposition
                    for j in range(wd - 1):
                        row = unit(lo + j)
                        row[lo + wd - 1] -= 1
                        M[lo + j] = row
                    last = [0] * n
                    last[lo + wd - 1] = -1
                    M[lo + wd - 1] = last
                reflections.append([list(r) for r in M])

        mu_basis = [tuple(unit(g + j)) for j in range(d)]
        return pairing, charges, reflections, F.zplus_ring(), mu_basis

    # ----- unfolding ----------------------------------------------------
    def unfoldable(self) -> bool:
        """Can every node rep be split into distinct one-dimensional weights?

        False exactly when some node rep has a repeated weight, in which case
        two unfolded nodes would carry the same charge and the unfolded object
        is not a BPS quiver.  The author's ruling (2026-09-13) is that node reps
        are fundamentals in reality, so this is `True` on everything the
        battery covers — which is what supplies the ground truth.
        """
        return all(all(m == 1 for m in w.values()) for w in self._weights)

    def unfold(self) -> tuple[list[list[int]], list[Vec], list[tuple[int, Weight]]]:
        """The ordinary BPS quiver on `Σ_a dim r_a` nodes.

        Returns `(pairing, node_charges, labels)` where `labels[i] = (a, w)`
        names the node as the weight `w` of node `a`'s rep.  The pairing between
        unfolded nodes is the reduced pairing of their gauge charges, since the
        flavour directions are central; in particular nodes within one group
        commute and pair identically with everything else — the *"identical
        permutable nodes"* the flavoured datum packages.
        """
        if not self.unfoldable():
            raise ValueError(
                "unfold: a node rep has a repeated weight, so the unfolded "
                "nodes would not have distinct charges")
        labels: list[tuple[int, Weight]] = []
        for a in range(self.rank):
            for w in sorted(self._weights[a]):
                labels.append((a, w))
        n = len(labels)
        B = [[self.pairing[labels[i][0]][labels[j][0]] for j in range(n)]
             for i in range(n)]
        charges = [tuple(1 if j == i else 0 for j in range(n)) for i in range(n)]
        return B, charges, labels


