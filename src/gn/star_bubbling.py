#: **OFF: measured SLOWER, and kept as the record of a rejected optimisation** —
#: see `_sparse_eliminate_rref` for the numbers and the diagnosis.
RREF_ELIMINATION = False


#: Feed the eliminator its rows shortest-first.  ON: measured a 48% cut with
#: identical solutions; see `sort_rows_shortest_first`.
SHORTEST_ROW_FIRST = True


def sort_rows_shortest_first(eqs):
    """Order the equation list by row length, shortest first.

    **Measured (2026-08-25): 135.1 s → 69.9 s, −48%, solutions identical**, over
    The five profiled labels:

        SU(3) m=(2,0)   10.00 → 8.52 s     Sp(2) m=(2,1)  113.30 → 51.31 s
        Spin(5) m=(2,1)  0.69 → 0.65 s     G₂ m=(1,0)      11.08 → 9.37 s

    The win is concentrated at Sp(2) (−55%), which is exactly the label where the profile
    measured 35 061 eliminations against at most 2 628 pivots.  So that diagnosis
    was right about *where* the waste is and wrong only about which lever removes
    it — the first candidate it named, full Gauss–Jordan reduction, is measured
    **slower** (`_sparse_eliminate_rref`, +55%).

    Why this works where that did not.  `solve_streaming` stops the moment the
    rank is full, so the cost is set by how many rows are consumed getting there
    and how expensive each is.  A short row is both cheaper to eliminate and
    likelier to yield a pivot, and it introduces less fill-in into the pivot rows
    it becomes — so every later elimination against it is cheaper too.  Gauss–
    Jordan attacked the *count* of eliminations and paid for it in density; this
    attacks density and the count together.

    **Sound for any order, which is why it is safe.**  Reordering changes neither
    the rank nor the solution of a linear system, and the benchmark checks the
    solved canonicals rather than assuming it.  It also leaves untouched the
    min-column echelon that `joint_solve`'s back-substitution depends on — unlike
    Markowitz pivot selection, which changes the pivot rule itself and would have
    to re-establish that invariant.

    Nor does it weaken the consistency check.  `solve_streaming` can only report
    `inconsistent` from rows it consumed before reaching full rank, and a
    different order consumes a different subset — but `joint_solve` verifies the
    lift **exactly over `Z` against every equation** afterwards, so an
    inconsistency missed early is caught there regardless.

    Free, too: `joint_solve` already materializes the stream (`dedup_rows`), so
    this is one stable sort on a list that exists rather than an extra pass.
    Python's sort is stable, so equal-length rows keep their generated order and
    the build stays deterministic."""
    return sorted(eqs, key=lambda rb: len(rb[0]))


def solve_streaming(row_iter, nvars, verbose=False, prime=_PRIME, rref=None,
                    out=None):
    """Pure-Python reference path: sparse elimination mod `_PRIME`, stopping as
    soon as the rank is full.  Returns `(status, solution, rows_seen)`.

    `out` (default `None`): a dict that receives the pivot columns as
    `out["pivots"]` — diagnostic only (`joint_solve`'s `stats`)."""
    piv: dict = {}
    colidx: dict = {}
    if rref is None:
        rref = RREF_ELIMINATION
    seen = 0
    for row, rhs in row_iter:
        seen += 1
        leftover = (_sparse_eliminate_rref(dict(row), rhs % prime, piv, colidx,
                                           prime) if rref else
                    _sparse_eliminate(dict(row), rhs % prime, piv, prime))
        if leftover is not None and leftover % prime:
            if out is not None:
                out["pivots"] = set(piv)
            return "inconsistent", None, seen
        if len(piv) == nvars:
            break
    if out is not None:
        out["pivots"] = set(piv)
    if len(piv) < nvars:
        return "underdetermined", None, seen
    sol = [0] * nvars
    for c in sorted(piv, reverse=True):
        prow, prhs = piv[c]
        acc = prhs
        for k, v in prow.items():
            if k != c:
                acc = (acc - v * sol[k]) % prime
        sol[c] = acc % prime
    half = prime // 2
    return "unique", [v - prime if v > half else v for v in sol], seen


def inv_den_series(datum, den, order) -> dict:
    """`∏_{(α,k)}(1 − 𝖖^k v^α)^{−mult}` as a `𝖖`-series truncated at `order`,
    as `{(qdeg, weight): int}`.

      k > 0:  Σ_{i≥0} 𝖖^{ki} v^{iα}                (valuation 0)
      k < 0:  −Σ_{i≥1} 𝖖^{|k|i} v^{−iα}            (valuation |k|)
    """
    d = datum.dim
    cur = {(0, (0,) * d): 1}
    for (al, k), mult in den.items():
        for _ in range(mult):
            a = abs(k)
            if k > 0:
                steps = [(k * i, tuple(i * x for x in al), 1)
                         for i in range(0, order // a + 2)]
            else:
                steps = [(a * i, tuple(-i * x for x in al), -1)
                         for i in range(1, order // a + 2)]
            nxt: dict = {}
            for (qd, wt), c in cur.items():
                for (dq, dw, s) in steps:
                    if qd + dq > order:
                        continue
                    key = (qd + dq, tuple(wt[i] + dw[i] for i in range(d)))
                    nxt[key] = nxt.get(key, 0) + c * s
            cur = {k2: v2 for k2, v2 in nxt.items() if v2}
    return cur


def wilson_weights(datum, e) -> list:
    """Weight support of `χ_e` — the box's `e`-tracking anchor, from the repo's
    own Wilson-line character.

    Taken at the **`W`-dominant representative** of `e`.  What the anchor wants
    is `e`'s weight orbit (and the weights below it); the Weyl character of a
    *singular* `e` vanishes identically — the alternating sum cancels — so
    reading the support off `χ_e` directly returns nothing there.  Singular `e`
    is not an exotic case: a legitimate label has `e` dominant only for the
    **Levi** `L_m`, and `PureGAbeKAlgebra.fold` transports `e` by the Weyl element
    that dominantizes `m` (the Weyl group acts diagonally on `(m, e)`), which can
    land `e` on a wall. never met this because it only ran `G`-dominant
    `e`, where `dominant_rep` is the identity and this is a no-op.

    Falling back to the bare Weyl orbit of `e` keeps the anchor non-empty in the
    residual case.  Both moves can only *enlarge* the box, never shrink it,
    which is the safe direction: the box is a cutoff certified by re-solving one
    pad wider (`solve_canonical`), so a larger box cannot change a unique
    answer — whereas a smaller one could silently select."""
    e = tuple(e)
    try:
        e_dom = tuple(datum.dominant_rep(e))
    except ValueError:                              # pragma: no cover
        e_dom = e
    x = W.wilson(datum, e_dom)
    f0 = x.residuals().get((0,) * datum.dim)
    if f0 is None:                                  # χ ≡ 0 even at the dom rep
        return sorted({tuple(datum.act(w, e)) for w in datum.weyl_elements()})
    return sorted(f0.num.terms)


def _primitive(al):
    """`(α₀, g)` with `α = g·α₀` and `α₀` primitive."""
    g = _gcd(al)
    if g <= 1:
        return tuple(al), 1
    return tuple(x // g for x in al), g


def box_points(datum, e, kf, pad, anchors=None) -> list:
    """`wt(χ_e) ⊕ Σ_α [0, mult_α·α]` — the closed zonotope of the denominator
    anchored at the Wilson weights.  A **cutoff**, certified by re-solving one
    pad wider; never a selector.

    `anchors` replaces the Wilson-weight anchor set.  It exists for the matter
    slices of `matter_star_bubbling`, whose numerators are shifted by **matter
    weights** — not roots, so `pad` (which dilates along root directions only)
    cannot reach them.  Default `None` keeps the pure behaviour exactly.

    Steps run along the PRIMITIVE direction `α₀` of each root (`α = g·α₀`).  In
    type A every root is primitive and this is a no-op, but C₃'s long roots `2ε`
    would otherwise skip every lattice point between a segment's endpoints —
    exactly the monomials a bubbling cell needs to cancel the seed residue on
    that wall.  `pad` dilates the POLYTOPE once per unit, not each factor's
    range (at 18 factors the latter inflates the box by the sum of all 18
    roots)."""
    d = datum.dim
    mult: dict = {}
    for (al, k) in kf:
        mult[al] = mult.get(al, 0) + 1
    pts = set(wilson_weights(datum, e)) if anchors is None \
        else {tuple(p) for p in anchors}
    for al, mu in mult.items():
        al0, g = _primitive(al)
        nxt = set()
        for p in pts:
            for s in range(0, mu * g + 1):
                nxt.add(tuple(p[i] + s * al0[i] for i in range(d)))
        pts = nxt
    # Dilate along EVERY primitive positive-root direction, not only the ones
    # occurring in this cell's denominator `K_f(n)`.  MEASURED at G₂, `m=(1,0)`,
    # `e=0`: the true numerator of the 6-cell Weyl orbit has 8 of its 9
    # monomials outside the `K_f`-only box (21 points), and the central cell
    # needs two steps; an all-roots box recovers every cell (`c=1` covers the
    # orbit, `c=2` the centre).  Confining the numerator to the denominator's
    # own root directions was a residue of the PROPERNESS intuition (numerator
    # inside the denominator's zonotope) that the author ruled invalid — a
    # Weyl-covariant numerator has no reason to live only there.  Enlarging is
    # the safe direction: the box is certified by re-solving one pad wider, so a
    # larger box cannot change a unique answer, whereas a smaller one can
    # silently select.
    dirs = {_primitive(al)[0] for al in datum.positive_roots()}
    for _ in range(pad):
        nxt = set(pts)
        for p in pts:
            for al0 in dirs:
                nxt.add(tuple(p[i] + al0[i] for i in range(d)))
                nxt.add(tuple(p[i] - al0[i] for i in range(d)))
        pts = nxt
    # CLOSE THE GAPS along each primitive direction.  The zonotope above grows
    # one-sidedly (`s` from 0 up) out of EACH anchor, which is harmless when the
    # anchors are one character's weight support — contiguous along the roots,
    # the pure case — but not when they are `wt(χ_e) ⊕ wt(Z[k⃗])` (the matter
    # slices): the matter anchors separate as the flavour level rises, the
    # one-sided zonotopes grow the SAME way out of each, and the union acquires a
    # HOLE between them.  Measured at SU(2)+Adj `m=(3,)`, `e=0`: at level 2 the
    # box is `−5…9` with `2` missing and the true numerator needs exactly `2`; by
    # level 6 the gap is `1…10`.  The hole widens linearly with the level while
    # `pad` widens each component by 1, which is why raising `pad` cannot fix it
    # and why a pad sweep reports the same `inconsistent` at every width (the
    # SU(3) `L_{(2,2),(0,0)}` wall, and the diagnosis that stalled there).
    #
    # A gap makes the box a SELECTOR, which is precisely what it must never be:
    # the "enlarging is the safe direction" certificate assumes the box only
    # truncates the answer's tail, but a hole can exclude the true answer while
    # still leaving a unique — hence wrong — solution inside the span.  So this is
    # a correctness fix, not a reach improvement.  Filling is monotone (it only
    # adds points), so it cannot change any answer the old box already pinned.
    for al0 in dirs:
        by_line: dict = {}
        for p in pts:
            t = _ratio_along(p, al0)
            if t is None:
                continue
            key = tuple(p[i] - t * al0[i] for i in range(d))
            by_line.setdefault(key, []).append(t)
        for base, ts in by_line.items():
            lo, hi = min(ts), max(ts)
            for t in range(lo, hi + 1):
                pts.add(tuple(base[i] + t * al0[i] for i in range(d)))
    return sorted(pts)


def _ratio_along(p, al0):
    """The integer `t` with `p − t·α₀` indexing the `α₀`-line through `p` — the
    first nonzero coordinate ratio, floored.  Two points share a base exactly
    when they differ by a multiple of `α₀`, so this partitions the box into
    `α₀`-lines and gap-filling along each is well defined.  (Any consistent
    section works; only the partition matters.)

    Returns `None` if the ratio is not integral — a box point with `Fraction`
    coordinates.  Skipping such a point only makes the fill smaller, which is the
    safe direction, so this degrades to the previous behaviour rather than
    raising."""
    for i, c in enumerate(al0):
        if c:
            t = p[i] // c
            try:
                ti = int(t)
            except (TypeError, ValueError):     # pragma: no cover
                return None
            return ti if ti == t else None
    return None


def _identity_weyl(datum) -> int:
    d = datum.dim
    basis = [tuple(1 if i == j else 0 for i in range(d)) for j in range(d)]
    for w in datum.weyl_elements():
        if all(tuple(datum.act_cochar(w, b)) == b for b in basis):
            return w
    raise RuntimeError("no identity in weyl_elements()")


