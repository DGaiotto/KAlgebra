    # --------------------------------------------------------------------
    # Self-consistency: associativity verification
    # --------------------------------------------------------------------
    # As k grows, BPS computation becomes infeasible (f-solver, Schur).
    # Instead, the algebra is self-consistent iff multiply satisfies
    # associativity: (a · b) · c = a · (b · c).  This is the primary
    # consistency check that does NOT depend on BPS.

    def verify_associativity(self, sample_labels=None):
        """Check (a · b) · c = a · (b · c) on sample triples.
        Returns (n_ok, n_bad, list_of_failures)."""
        if sample_labels is None:
            # Default: single-letter generators from each chord family
            sample_labels = [(((a, 0, 1),), 0) for a in range(1, max(self._mult_table.family_periods.keys()) + 1)]
            sample_labels.append((((1, 1, 1),), 0))  # also non-zero offset
        n_ok = n_bad = 0
        fails = []
        for a in sample_labels:
            for b in sample_labels:
                for c in sample_labels:
                    # (a·b)·c
                    ab = self.multiply(a, b)
                    abc_left = Element({})
                    for lab_ab, coef_ab in ab.terms.items():
                        lab_abc = self.multiply(lab_ab, c)
                        for lab_out, coef_out in lab_abc.terms.items():
                            contribution = coef_ab * coef_out
                            if lab_out in abc_left.terms:
                                abc_left.terms[lab_out] = abc_left.terms[lab_out] + contribution
                            else:
                                abc_left.terms[lab_out] = contribution
                    # a·(b·c)
                    bc = self.multiply(b, c)
                    abc_right = Element({})
                    for lab_bc, coef_bc in bc.terms.items():
                        lab_abc = self.multiply(a, lab_bc)
                        for lab_out, coef_out in lab_abc.terms.items():
                            contribution = coef_bc * coef_out
                            if lab_out in abc_right.terms:
                                abc_right.terms[lab_out] = abc_right.terms[lab_out] + contribution
                            else:
                                abc_right.terms[lab_out] = contribution
                    # Compare (drop zero terms)
                    left = {k: v for k, v in abc_left.terms.items() if not v.is_zero()}
                    right = {k: v for k, v in abc_right.terms.items() if not v.is_zero()}
                    if left == right:
                        n_ok += 1
                    else:
                        n_bad += 1
                        if len(fails) < 3:
                            fails.append((a, b, c, left, right))
        return (n_ok, n_bad, fails)


