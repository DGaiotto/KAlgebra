def test_the_canonical_key_identifies_flavoured_quivers_up_to_relabelling():
    """The dictionary identity: `(canonical B, node colours in canonical order)`.

    The flavour datum is an extra node colour, so `quiver_enumeration`'s
    colour-refinement canonical form extends to flavoured quivers unchanged —
    which is what a dictionary of *quivers with `G` symmetry* needs.  Relabelling the nodes must not change the key; changing the
    flavour assignment must.
    """
    B = [[0, 1], [-1, 0]]
    swapped = [[0, -1], [1, 0]]                 # the same quiver, nodes swapped
    a = FlavouredQuiver(B, [2, 1])
    a_relabelled = FlavouredQuiver(swapped, [1, 2])
    assert a.canonical_key() == a_relabelled.canonical_key()

    keys = {}
    for fac in ([1, 1], [2, 1], [1, 2], [2, 2], [3, 1], [1, 3], [3, 2], [2, 3]):
        keys[tuple(fac)] = FlavouredQuiver(B, fac).canonical_key()
    assert len(set(map(str, keys.values()))) == len(keys), keys


def test_the_colour_preserving_automorphisms_are_the_flavoured_ones():
    """`|Aut|` drops exactly when the flavour assignment breaks a symmetry.

    `A1 × A1` has `|Aut(B)| = 2`.  With an `SU(2)` at each node the two remain
    interchangeable, so the flavoured group is still order 2 — a node's colour
    must name its factor's RANK, never the factor's index in the product, or
    this reports 1.  With `SU(2)` at one node only, or `SU(2)` and `SU(3)`, the
    symmetry is genuinely broken and the order is 1.
    """
    from quiver_enumeration import canonical_form
    B = [[0, 0], [0, 0]]
    assert canonical_form(B).aut_order == 2
    for fac, want in (([1, 1], 2), ([2, 2], 2), ([2, 1], 1), ([2, 3], 1)):
        got = FlavouredQuiver(B, fac).colour_preserving_aut_order()
        assert got == want, (fac, got, want)


def test_equal_canonical_key_implies_equal_S():
    """Dictionary soundness: one entry, one `S`.

    Over a family of flavoured quivers including relabelled copies, every group
    sharing a canonical key has one and the same `S` in canonical coordinates —
    so an entry may store a single `S` without a witness permutation.
    """
    families = []
    for B in ([[0, 1], [-1, 0]], [[0, -1], [1, 0]],
              [[0, 2], [-2, 0]], [[0, -2], [2, 0]], [[0, 0], [0, 0]]):
        for fac in ([1, 1], [2, 1], [1, 2], [2, 2]):
            families.append(FlavouredQuiver(B, fac))
    groups: dict[str, list] = {}
    for Q in families:
        groups.setdefault(str(Q.canonical_key()), []).append(Q)
    assert any(len(v) > 1 for v in groups.values()), "no key had two members"
    for key, members in groups.items():
        base = canonical_spectrum_generator(members[0], 4)
        for Q in members[1:]:
            assert _same(canonical_spectrum_generator(Q, 4), base), key


def test_the_key_is_finer_than_S_because_S_is_arrow_reversal_invariant():
    """`S(B) = S(−B)`: distinct entries may share an `S`, and that is expected.

    Reversing every arrow, `B ↦ −B`, is the opposite quiver.  `X_γ ↦ X_γ` is an
    **anti**-isomorphism `Q_\\fq(B) → Q_\\fq(−B)`, so it carries a product of
    `E^{(s)}` factors to the same factors in the REVERSED order — and `S` is
    order-independent.  So arrow-reversal invariance of `S` is a corollary of
    the PBW conjecture rather than anything about flavour, and it is why the
    canonical key is strictly finer than `S`.

    Checked unflavoured, where it is a statement about `S` alone, on quivers
    with `B` genuinely NOT isomorphic to `−B`; and then in the flavoured
    setting, where the colouring makes `(B, colours)` and `(−B, colours)`
    distinct entries that nevertheless share an `S`.
    """
    import quiver_enumeration as qe

    checked = 0
    for key in qe.enumerate_connected_quivers(5):
        n = len(key)
        if n != 3:
            continue
        neg = tuple(tuple(-x for x in row) for row in key)
        if qe.canonical_key(neg) == key:
            continue                    # isomorphic to its own opposite
        charges = qe.standard_nodes(n)
        a = BPSFactorSpectrum(key, charges, 3, order="lex")
        a.run()
        b = BPSFactorSpectrum(neg, charges, 3, order="lex")
        b.run()
        assert _same(a.spectrum_generator(), b.spectrum_generator()), key
        checked += 1
        if checked == 6:
            break
    assert checked == 6, checked

    # Flavoured: distinct entries, equal S.
    p = FlavouredQuiver([[0, 1], [-1, 0]], [2, 1])
    q = FlavouredQuiver([[0, 1], [-1, 0]], [1, 2])
    assert p.canonical_key() != q.canonical_key()
    assert _same(canonical_spectrum_generator(p, 4),
                 canonical_spectrum_generator(q, 4))


def test_a_shared_flavour_factor_honest_fails_rather_than_conflating():
    """Where the node colours are not a complete invariant, the key refuses.

    Two nodes in the fundamental of ONE `SU(2)` and two nodes in fundamentals
    of `SU(2) × SU(2)` have identical node colours and are different objects;
    telling them apart needs the node–factor incidence canonicalised jointly
    with the quiver, which is not built.  The case does not arise in the
    setting the construction is for.
    """
    shared = FlavouredQuiver([[0, 1], [-1, 0]], FlavourSpace([2]),
                             [((1,),), ((1,),)])
    assert shared.shares_a_flavour_factor()
    for call in (shared.canonical_key,
                 lambda: canonical_spectrum_generator(shared, 3)):
        try:
            call()
        except NotImplementedError:
            continue
        raise AssertionError("expected an honest failure on a shared factor")
    assert not FlavouredQuiver([[0, 1], [-1, 0]], [2, 2]).shares_a_flavour_factor()


