# 1.  The conventional presentation and (★)
#
# `x = Σ_m f_m(𝖖^m v)·U_m` with `U_m = u^m·ψ_m(v)` expands to the difference
# operator `D = Σ_a d_a(v)·u^a`, `d_a = T_a(f_a)·ψ_a`, acting by
# `(D·f)(v) = Σ_a d_a(v)·f(𝖖^{2a}v)`.  `ψ_a` carries the W-boson poles, so each
# individual `d_a` is singular on the walls even though the operator is not —
# that cancellation is exactly (★).
# ---------------------------------------------------------------------------

def conventional(x) -> dict:
    """`{m: d_m}` — the conventional (difference-operator) presentation of a
    `WRQTorus` element.  Datum-general: `ψ` is `wrq_torus.dressing_psi`."""
    dat = x.datum
    return {tuple(m): (f.q_shift(tuple(m)) * W.dressing_psi(dat, m)).simplify()
            for m, f in x.residuals().items()}


def neumann_row(x) -> TorusRational:
    """`(L|N]` — the Neumann row: the operator applied to `|N] = 1 ∈ R(G)`, i.e.
    the plain sum of the `d_a`.  Polynomiality of this (no surviving
    denominator) is condition R1 of the recognition record; it is the *single
    vector* reading, strictly weaker than (★), which tests the whole module."""
    out = TorusRational.zero(x.datum)
    for d in conventional(x).values():
        out = out + d
    return out.simplify()


#: `coroot_of` results, keyed `(id(datum), alpha)` with a strong ref to the datum so
#: the id cannot be reused.  Pure function over the FINITE root set, so bounded.
_COROOT_MEMO: dict = {}


def coroot_of(datum, alpha):
    """`α^∨`, identified from the Weyl reflection in `α` acting on
    cocharacters.  Datum-general — this is what makes the affine-reflection
    partner rule well defined in the non-simply-laced case (measured on B₂:
    `⟨α, α^∨⟩ = 2` on all four roots, short and long).

    Memoized: this searches the Weyl group and does `Fraction` arithmetic to
    identify the coroot, and it is a pure function of `(datum, α)` over the finite
    root set — but it was recomputed on every call.  Profiling one dressed SU(3)
    chart build put it among the largest `Fraction` consumers in the process."""
    key = (id(datum), tuple(alpha))
    hit = _COROOT_MEMO.get(key)
    if hit is not None and hit[0] is datum:
        return hit[1]
    d = datum.dim
    for w in datum.weyl_elements():
        cv, ok = None, True
        for i in range(d):
            e = tuple(1 if k == i else 0 for k in range(d))
            img = datum.act_cochar(w, e)
            diff = tuple(e[k] - img[k] for k in range(d))
            p = datum.shift_pairing(e, alpha)
            if p == 0:
                if any(diff):
                    ok = False
                    break
            else:
                cand = tuple(Fraction(x, p) for x in diff)
                if cv is None:
                    cv = cand
                elif cv != cand:
                    ok = False
                    break
        if ok and cv is not None and all(x.denominator == 1 for x in cv):
            c = tuple(int(x) for x in cv)
            if any(c):
                _COROOT_MEMO[key] = (datum, c)
                return c
    _COROOT_MEMO[key] = (datum, None)
    return None


def _walls(D) -> set:
    ks = set()
    for d in D.values():
        ks.update(d.simplify().den)
    return ks


def wall_partner(datum, a, alpha, k, cor):
    """The affine-Weyl partner of the term `a` on the wall `v^α = 𝖖^{−k}`.

    On the wall the reflection acts on the *point* as `s_α(v) = 𝖖^{−2l α^∨}·v`,
    so `s_α(p_a) = p_b` with `b = s_α(a) − l·α^∨` — the affine reflection fixing
    `⟨a, α⟩ = −l`.  An involution, so terms genuinely pair up and nothing is
    left over."""
    if k % 2:
        return None
    l = -k // 2
    t = datum.shift_pairing(a, alpha) + l
    return tuple(a[i] - t * cor[i] for i in range(datum.dim))


def criterion(x):
    """(★): pairwise residue cancellation on every wall — equivalently,
    regularity of `x`'s difference operator on `Λ = R(G)`.

    Returns `(ok, report)`.  Tested by **exact division** (does the pair sum
    still carry the wall factor in its denominator?), never numerically."""
    dat = x.datum
    D = conventional(x)
    ok, rep = True, []
    for (alpha, k) in sorted(_walls(D)):
        cor = coroot_of(dat, alpha)
        if cor is None:
            return False, [("no coroot for", alpha)]
        if k % 2:
            return False, [(alpha, k, "odd k")]
        seen = set()
        for a in list(D):
            if a in seen:
                continue
            p = wall_partner(dat, a, alpha, k, cor)
            seen.add(a)
            seen.add(p)
            s = (D.get(a, TorusRational.zero(dat))
                 + D.get(p, TorusRational.zero(dat))).simplify()
            if s.den.get((tuple(alpha), k), 0) > 0 and not s.is_zero():
                ok = False
                rep.append((alpha, k, f"a={a} <-> {p}: pole SURVIVES"))
    return ok, rep


