class U1A1AoddConeData(FiniteConeData):
    """Generic FiniteConeData for U1A1AoddKAlg(k).
    E± labels use family index (max_family + 1) to avoid collision with L families."""

    def __init__(self, k: int, chord_charges, E_charge, mult_table, family_periods):
        self.k = k
        self.chord_charges = chord_charges
        self.E_charge = E_charge
        self.mult_table = mult_table
        self.family_periods = family_periods
        # E± family index = max chord family + 1
        max_fam = max(family_periods.keys())
        self.E_GEN = (max_fam + 1, 0)
        self.E_INV = (max_fam + 1, 1)
        # Extract MU_LETTER_QPOWER per chord generator (cocycle with E)
        self.MU_LETTER_QPOWER = {}
        from bps_kalgebra import BPSKAlgebra
        # We don't have BPS at runtime — use mult_table for L·L cocycle,
        # but for L·E we need the cocycle.  Compute it from the chord_charges
        # via mathematical formula: L_l · E = q^{2c} · E · L_l where c is the
        # cocycle.  Empirically for our chord families, parity-based:
        # for magnetic families, cocycle = -1 if i even else +1; non-magnetic 0.
        # We need to determine which families are magnetic.
        # Heuristic: a family is magnetic iff its ρ-orbit closes mod E with non-zero cocycle.
        # For simplicity here, we extract empirically via direct BPS evaluation at init.
        bps = _build_bps(k)
        for (a, i), chg in chord_charges.items():
            fwd = bps.multiply(chg, E_charge)
            bwd = bps.multiply(E_charge, chg)
            if len(fwd.terms) == 1 and len(bwd.terms) == 1:
                f_lp = list(fwd.terms.values())[0]
                b_lp = list(bwd.terms.values())[0]
                fq = list(f_lp._coeffs.keys())[0] if f_lp._coeffs else 0
                bq = list(b_lp._coeffs.keys())[0] if b_lp._coeffs else 0
                diff = fq - bq
                if diff % 2 != 0:
                    raise ValueError(
                        f"MU_LETTER_QPOWER: non-integer cocycle for L_{(a, i)} "
                        f"with E (literal q-diff = {diff}, expected even)"
                    )
                self.MU_LETTER_QPOWER[(a, i)] = diff // 2
            else:
                self.MU_LETTER_QPOWER[(a, i)] = 0
        self._mult_gens = tuple(sorted(chord_charges.keys()) + [self.E_GEN, self.E_INV])
        self._cones = None

    def mult_gens(self):
        return self._mult_gens

    def cones(self):
        if self._cones is None:
            V = list(self._mult_gens)
            neighbours = {
                v: frozenset(u for u in V if u != v and self.q_commute(v, u))
                for v in V
            }
            cliques = []
            def bk(R, P, X):
                if not P and not X:
                    cliques.append(R); return
                pivot = max(P | X, key=lambda u: len(P & neighbours[u]))
                for v in list(P - neighbours[pivot]):
                    bk(R | {v}, P & neighbours[v], X & neighbours[v])
                    P = P - {v}; X = X | {v}
            bk(frozenset(), frozenset(V), frozenset())
            self._cones = tuple(cliques)
        return self._cones

    def _is_L_letter(self, g):
        return g not in (self.E_GEN, self.E_INV)

    def q_commute(self, g, h):
        if g == h: return True
        # QTCone (Laurent E): E and E⁻¹ q-commute with cocycle 0.
        # The cancellation E · E⁻¹ = 1 is handled by the universal
        # `_torus_inverse_letter` collapse in
        # `ConeData._word_to_gens_powers`, not via cross_product.
        if {g, h} == {self.E_GEN, self.E_INV}: return True
        if self._is_L_letter(g) and self._is_L_letter(h):
            fwd = self.mult_table.get((g, h))
            return fwd is not None and len(fwd) == 1
        return True

    def cocycle(self, g, h):
        if g == h: return 0
        # E and E⁻¹ commute (cocycle 0) — torus direction.
        if {g, h} == {self.E_GEN, self.E_INV}: return 0
        if self._is_L_letter(g) and self._is_L_letter(h):
            fwd = self.mult_table.get((g, h)); bwd = self.mult_table.get((h, g))
            if fwd is None or len(fwd) != 1 or bwd is None or len(bwd) != 1:
                raise ValueError(f"cocycle: {g}, {h} not q-commuting")
            c_full = fwd[0][0] - bwd[0][0]
            assert c_full % 2 == 0
            return c_full // 2
        if g == self.E_GEN and self._is_L_letter(h): return -self.MU_LETTER_QPOWER[h]
        if h == self.E_GEN and self._is_L_letter(g): return self.MU_LETTER_QPOWER[g]
        if g == self.E_INV and self._is_L_letter(h): return self.MU_LETTER_QPOWER[h]
        if h == self.E_INV and self._is_L_letter(g): return -self.MU_LETTER_QPOWER[g]
        raise ValueError(f"cocycle undefined for ({g}, {h})")

    def cross_product(self, g, h):
        # Note: (E_GEN, E_INV) no longer reaches here — q-commute with
        # cocycle 0, cancellation via `_torus_inverse_letter`.
        if self._is_L_letter(g) and self._is_L_letter(h):
            terms = self.mult_table.get((g, h))
            if terms is None:
                raise ValueError(f"mult_table missing ({g}, {h})")
            out = []
            for (q_pow, e_E, factors, q_coef) in terms:
                word = list(factors)
                if e_E > 0: word.extend([self.E_GEN] * e_E)
                elif e_E < 0: word.extend([self.E_INV] * (-e_E))
                gens_set = frozenset(word)
                powers = {gx: word.count(gx) for gx in gens_set}
                phase = self.cone_label_phase(gens_set, powers)
                coef = q_coef * LaurentPoly({q_pow + phase: 1})
                out.append((coef, tuple(word)))
            return out
        raise ValueError(f"cross_product undefined for q-commuting ({g}, {h})")

    def to_cone_label(self, native_label):
        factors, e_E = native_label
        word = []
        for (a, i, exp) in sorted(factors):
            word.extend([(a, i)] * exp)
        if e_E > 0: word.extend([self.E_GEN] * e_E)
        elif e_E < 0: word.extend([self.E_INV] * (-e_E))
        if not word:
            for c in self.cones():
                if self.E_GEN in c: return (c, {g: 0 for g in c})
            return (self.cones()[0], {g: 0 for g in self.cones()[0]})
        gens_in_word = set(word)
        for cone in self.cones():
            if gens_in_word <= set(cone):
                powers = {g: word.count(g) for g in cone}
                return (cone, powers)
        raise ValueError(f"no cone for {native_label}: {gens_in_word}")

    def from_cone_label(self, gens, powers):
        factors_dict = {}; e_E = 0
        for g, p in powers.items():
            if p == 0: continue
            if g == self.E_GEN: e_E += p
            elif g == self.E_INV: e_E -= p
            else:
                a, i = g
                factors_dict[(a, i)] = factors_dict.get((a, i), 0) + p
        factors = tuple(sorted((a, i, p) for (a, i), p in factors_dict.items()))
        return (factors, e_E)

    # -- torus inverse letter (Laurent E direction; QTCone semantics) -----

    def _torus_inverse_letter(self, g):
        """E ↔ E⁻¹ pairing.  Universal cancellation collapse in
        `ConeData._word_to_gens_powers` replaces the previous
        cross_product Plücker handling."""
        if g == self.E_GEN: return self.E_INV
        if g == self.E_INV: return self.E_GEN
        return None

    # -- QTCone iter ------------------------------------------------------

    def iter_cones(self):
        """Yield QTCone instances per maximal cone, with
        `torus_gens = {E, E⁻¹} ∩ cone_gens`."""
        torus_all = frozenset({self.E_GEN, self.E_INV})
        for cone_gens in self.cones():
            yield Cone(self, cone_gens, torus_gens=torus_all & cone_gens)


