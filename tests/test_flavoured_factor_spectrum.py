def test_S_is_a_function_of_the_flavoured_quiver_alone():
    """`S[Q]` depends only on the flavoured quiver, up to relabelling of nodes.

    The property a dictionary keyed by *quivers with `G` symmetry* needs: the
    flavour assignment is an extra node colour, and permuting the nodes
    permutes `S` and nothing else.
    """
    B = [[0, 1, -1], [-1, 0, 1], [1, -1, 0]]
    fac = [2, 1, 3]
    perm = (2, 0, 1)                       # new node i is old node perm[i]
    Q = FlavouredQuiver(B, fac)
    Bp = [[B[perm[i]][perm[j]] for j in range(3)] for i in range(3)]
    Qp = FlavouredQuiver(Bp, [fac[perm[i]] for i in range(3)])
    D = 3
    S = build_flavoured_spectrum_generator(Q, D)
    Sp = build_flavoured_spectrum_generator(Qp, D)

    # The flavour coordinates are concatenated in node order, so permuting the
    # nodes permutes the weight blocks as well as the charge coordinates.
    F, Fp = Q.flavour, Qp.flavour

    def relabel(key):
        k, w = key
        new_k = tuple(k[perm[i]] for i in range(3))
        new_w = ()
        for i in range(3):
            src, wd = F.offsets[perm[i]], F.widths[perm[i]]
            new_w += tuple(w[src:src + wd])
        assert len(new_w) == Fp.dim
        return new_k, new_w

    assert len(S) == len(Sp)
    assert {relabel(key) for key in S} == set(Sp)
    for key, h in S.items():
        assert Sp[relabel(key)] == h, key


