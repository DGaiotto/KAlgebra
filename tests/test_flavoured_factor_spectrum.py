"""The flavoured `S` axiomatics — `\\cE_G` and its BPS quiver constraint.

**This suite is written to BE the axiom statements**, one test per statement,
so that it can be read as the axiomatics rather than as a regression net.  Each test's name is the claim; its docstring is
the claim in the paper's notation; its body decides it.

The setting.  As soon as a quiver has `N` identical nodes it
has a manifest `SU(N)` symmetry, so a quiver with groups of `N_a` nodes carries
`G = ∏_a SU(N_a)` — and one may as well package the group of nodes as a single
node carrying the `N_a`-dimensional irrep `r_a`.  Then, with `μ^w` the central
character of the maximal torus at the weight `w`,

    E^{(s;r)}_\\fq(X_γ)  =  ∏_{w ∈ r} E^{(s)}_\\fq(μ^w X_γ) ,

`\\cE_G ⊂ \\cG` is generated by the `E^{(s;r)}_\\fq(X_γ)^{±1}`, and the
flavoured BPS quiver constraint replaces the node charge monomials by
sequences:

    S  =  1  -  \\fq Σ_a χ_{r_a}(μ) X_{γ_a}  +  O(\\fq^2) .

What is EMERGENT and what is ENFORCED (the audit — a green check is
evidence only where the property is not built in):

* **Enforced** — the leading data.  The recursion solves for exactly it, so
  `verify_leading_data` is a regression guard on the arithmetic, never evidence
  about the conjectures.  It is here, and labelled, for that reason alone.
* **Emergent** — that each `Ω(γ)` is a `G`-character.  `Ω` is forced weight by
  weight, independently, with no Weyl symmetry imposed anywhere in the
  recursion; that the answer is nevertheless `W`-invariant is the substantive
  claim `S ∈ \\cE_G`.
* **Independent** — agreement with the **unfolded** quiver, run through the
  unflavoured engine `bps_factor_spectrum.BPSFactorSpectrum`.  The two share
  the univariate ray arithmetic and nothing else: this one recurses on the
  reduced cone with a weight grading, that one on the enlarged cone with no
  notion of flavour at all.

Run:  `python3 run_tests.py`
"""
