def _sparse_eliminate(row, rhs, piv, prime=_PRIME):
    """Reduce a sparse row `{col: int}` against the pivot table (mod `prime`)."""
    while row:
        c = min(row)
        if c not in piv:
            inv = pow(row[c], prime - 2, prime)
            prow = {k: (v * inv) % prime for k, v in row.items()}
            piv[c] = (prow, (rhs * inv) % prime)
            return None
        prow, prhs = piv[c]
        f = row[c]
        if not f:
            continue
        for k, v in prow.items():
            nv = (row.get(k, 0) - f * v) % prime
            if nv:
                row[k] = nv
            else:
                row.pop(k, None)
        rhs = (rhs - f * prhs) % prime
    return rhs


def _sparse_eliminate_rref(row, rhs, piv, colidx, prime=_PRIME):
    """`_sparse_eliminate` against a **fully reduced** pivot table (Gauss–Jordan).

    The profile: at Sp(2) `m=(2,1)` the eliminator runs 35 061 eliminations to
    find at most 2 628 pivots, i.e. **~92% of eliminations add nothing** — they
    only confirm a row is already implied.  The cause is that `piv` is kept in
    *echelon* form, so a pivot row may itself carry other pivot columns and
    reducing against it cascades.

    Here every pivot row carries **only its own pivot column plus non-pivot
    columns**, so reducing an incoming row against one pivot introduces no new
    pivot column and the cascade is gone: a row needs at most one elimination per
    pivot column it actually has.  The cost moved is that a new pivot must be
    back-substituted into the existing pivot rows that contain its column, which
    is what `colidx` (column → the pivot rows carrying it) makes cheap.

    **The echelon invariant the caller depends on survives.**  `joint_solve`
    back-substitutes with `for c in sorted(piv, reverse=True)`, which assumes a
    pivot row has no column below its pivot.  It still holds: a pivot row for
    `c_old` has min column `c_old`, so it can only contain `c_new` if
    `c_new > c_old`, and subtracting a multiple of the new pivot row (min column
    `c_new`) adds only columns `≥ c_new > c_old`.  At full rank — the only case
    `joint_solve` proceeds from — every column is a pivot, so each pivot row
    collapses to its own pivot and the back-substitution reads off the answer
    directly.

    Same contract as `_sparse_eliminate`: returns `None` when the row became a
    new pivot, else the reduced right-hand side (non-zero ⇒ inconsistent).

    🛑 **MEASURED SLOWER — REJECTED, and kept as the record of that** (2026-08-25).
    A/B over the five profiled labels, `RREF_ELIMINATION` switching the two,
    with the solved canonicals compared: **identical results**, and

        echelon TOTAL 136.1 s      RREF TOTAL 211.7 s      (+55%)

        SU(3) m=(2,0)   9.86 → 21.34 s     Sp(2) m=(2,1)  117.3 → 177.9 s
        G₂ m=(1,0)      11.4 → 12.4 s      Spin(5) m=(2,1) 0.70 → 0.69 s

    The implementation is correct; the idea is wrong, and the reason is worth
    keeping.  **The "92% of eliminations add nothing" counts STEPS, not COST.**
    This reduces steps and raises the work per step twice over: a reduced pivot
    row has absorbed every later pivot, so it is *denser* than an echelon one and
    each elimination against it touches more entries; and maintaining the reduction
    means back-substituting each new pivot into every pivot row carrying its
    column, which is quadratic in the pivot count (`nvars = 2628` at Sp(2)).  In a
    sparse system the density dominates the shortened cascade — the classical
    Gauss–Jordan trade, landing on the wrong side here.

    The lesson generalises past this function: an optimisation aimed at a
    *counted* quantity needs the count to be a proxy for the cost, and that was
    assumed rather than measured.  The remaining candidate — fill-in-aware
    (Markowitz) pivot selection — targets fill directly, but it changes the
    min-column echelon that `joint_solve`'s back-substitution assumes, so it must
    re-establish that invariant.  A cheaper move that does **not** touch the
    invariant is to reorder the row stream (shortest first): `solve_streaming`
    stops the moment the rank is full, and a sparse row is both cheaper to
    eliminate and likelier to yield a pivot."""
    while row:
        c = min(row)
        if c not in piv:
            inv = pow(row[c], prime - 2, prime)
            prow = {k: (v * inv) % prime for k, v in row.items()}
            prhs = (rhs * inv) % prime
            piv[c] = (prow, prhs)
            for k in prow:
                if k != c:
                    colidx.setdefault(k, set()).add(c)
            for pcol in list(colidx.get(c, ())):
                if pcol == c:
                    continue
                entry = piv.get(pcol)
                if entry is None:
                    continue
                orow, orhs = entry
                f = orow.get(c)
                if not f:
                    continue
                for k, v in prow.items():
                    nv = (orow.get(k, 0) - f * v) % prime
                    if nv:
                        if k not in orow and k != pcol:
                            colidx.setdefault(k, set()).add(pcol)
                        orow[k] = nv
                    elif k in orow:
                        del orow[k]
                        idx = colidx.get(k)
                        if idx is not None:
                            idx.discard(pcol)
                piv[pcol] = (orow, (orhs - f * prhs) % prime)
            colidx.pop(c, None)
            return None
        prow, prhs = piv[c]
        f = row[c]
        if not f:
            row.pop(c, None)
            continue
        for k, v in prow.items():
            nv = (row.get(k, 0) - f * v) % prime
            if nv:
                row[k] = nv
            else:
                row.pop(k, None)
        rhs = (rhs - f * prhs) % prime
    return rhs


def dedup_rows(row_iter) -> list:
    """Materialize the equation stream once, dropping duplicate equations.

    **Measured (2026-08-25), and the reason this exists:** the stream is
    overwhelmingly repetitive — `L_{m,e}` at SU(3) `m=(2,0)` generates 37 580 rows
    of which **9 430** are distinct, Spin(5) `m=(2,1)` 10 268 → 1 433, G₂ `m=(1,0)`
    46 884 → 5 691 (75–88% duplicates).  The repetition is structural: the (★)
    rows are generated per wall and per `𝖖`-degree, and the same linear condition
    is reached along many walls.

    Two costs follow from it, and both are paid twice over because `joint_solve`
    consumed the stream TWICE — once for the mod-`p` solve, once for the exact
    verification over `Z` — regenerating every row through `expand` the second
    time.  A duplicate row is not free: it goes through a full sparse elimination
    and contributes nothing, since it reduces to `0 = 0`.

    Dedup is exact and order-preserving (first occurrence wins), so it changes
    neither the solution nor the verdict — only how long they take.  Rows whose
    right-hand side is unhashable are kept as-is rather than risking a wrong
    drop.

    **Measured end-to-end** against the previous code, same five labels, identical
    results: 70.4 s → 48.7 s (−31%), and at the expensive label Sp(2) `m=(2,1)`
    61.9 s → 41.3 s (−33%).  A third mode was run to attribute the gain —
    materializing WITHOUT dedup came in at 72.5 s, i.e. no better than the
    original — so the win is the deduplication, not the single pass: the cost
    sits in `_sparse_eliminate`, not in regenerating rows."""
    seen, out = set(), []
    for row, b in row_iter:
        try:
            key = (tuple(sorted(row.items())), b)
        except TypeError:
            out.append((row, b))
            continue
        if key not in seen:
            seen.add(key)
            out.append((row, b))
    return out


