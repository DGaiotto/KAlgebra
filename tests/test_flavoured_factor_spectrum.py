def _quiver(entry):
    _, B, fac, D = entry
    return FlavouredQuiver(B, fac), D


def _same(a, b):
    keys = set(a) | set(b)
    return all(a.get(k, H0) == b.get(k, H0) for k in keys)


def _random_piece_key(seed):
    rng = random.Random(seed)
    memo = {}

    def key(*args):
        if args not in memo:
            memo[args] = rng.random()
        return memo[args]

    return key


