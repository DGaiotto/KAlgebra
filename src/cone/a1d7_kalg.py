# ---------------------------------------------------------------------------
# ρ helpers (table lookup with caching for iterated application)
# ---------------------------------------------------------------------------


_IDENTITY_LABEL = (0, 0, 0, 0, 0, 0, 0)


def _rho_apply(label: tuple) -> tuple:
    if label == _IDENTITY_LABEL:
        return _IDENTITY_LABEL
    try:
        return _RHO_TABLE[label]
    except KeyError as e:
        raise KeyError(
            f"_RHO_TABLE missing entry for {label!r}.  This label is "
            f"outside the precomputed mult-gen × mult-gen closure."
        ) from e


def _rho_inverse_apply(label: tuple) -> tuple:
    if label == _IDENTITY_LABEL:
        return _IDENTITY_LABEL
    try:
        return _RHO_INV_TABLE[label]
    except KeyError as e:
        raise KeyError(
            f"_RHO_INV_TABLE missing entry for {label!r}."
        ) from e


def _rho_n_apply(label: tuple, n: int) -> tuple:
    """ρ^n applied to a single label.  Period 7."""
    cur = label
    n = n % 7
    for _ in range(n):
        cur = _rho_apply(cur)
    return cur


