# MULT_TABLE generation (per k)
# ============================================================================

def _qcommute(bps, c1, c2):
    return len(bps.multiply(c1, c2).terms) == 1


def _all_qcommute(bps, gens, facs):
    for i in range(len(facs)):
        for j in range(i+1, len(facs)):
            if facs[i] != facs[j] and not _qcommute(
                bps, gens[facs[i]], gens[facs[j]]):
                return False
    return True


def _is_E_multiple(diff, E_charge):
    n = len(diff)
    # diff = c·E means diff[i] = c if E[i] = 1 else 0
    nonzero_E_positions = [i for i in range(n) if E_charge[i] != 0]
    zero_E_positions = [i for i in range(n) if E_charge[i] == 0]
    for i in zero_E_positions:
        if diff[i] != 0: return None
    if not nonzero_E_positions: return None
    c = diff[nonzero_E_positions[0]]
    for i in nonzero_E_positions:
        if diff[i] != c: return None
    return c


def _decompose(gamma, chord_charges, primitives, E_charge, bps, max_factors=4):
    """Find γ = sum(L_a(i) charges) + e_E·E with factors all q-commuting.

    Greedy: tries n_facs = 0, 1, ..., max_factors and accepts the first
    q-commuting factorisation that reproduces γ mod E.  max_factors=4
    suffices for every chord-pair Plücker daughter observed at k ≤ 4;
    if you ever see this return None on a chord-pair input, the right
    fix is almost always a missing primitive seed (not a higher rank)."""
    n = len(gamma)
    for n_facs in range(0, max_factors + 1):
        for facs in iproduct(primitives, repeat=n_facs):
            if list(facs) != sorted(facs): continue
            if not _all_qcommute(bps, chord_charges, facs): continue
            fc = [0] * n
            for f in facs:
                fci = chord_charges[f]
                for k_ in range(n): fc[k_] += fci[k_]
            diff = tuple(gamma[k_] - fc[k_] for k_ in range(n))
            e_E = _is_E_multiple(diff, E_charge)
            if e_E is not None:
                return (e_E, list(facs))
    return None


def generate_mult_table(k: int):
    """Compute the chord-pair multiply table for U1A1AoddKAlg(k).
    Returns (chord_charges, E_charge, MULT_TABLE)."""
    chord_charges, E_charge, bps, family_periods = _bootstrap_chord_charges(k)
    # Wrap-around E-drift per family + the ρ(E)=E⁻¹ check — the only data the
    # closed-form ρ needs beyond the orbit shift `(a,i)→(a,i+1 mod P_a)`:
    # ρ(L_{a, P_a-1}) = E^{eps_wrap[a]}·L_{a, 0}.  Derived once from BPS (ground
    # truth).  (Previously `rho` did `(i+1)%P` with `e_E` UNCHANGED — dropping
    # both this wrap pickup AND the `E→E⁻¹` inversion, so ρ disagreed with BPS
    # on the wrap letters and on every `e_E≠0` label, failing the algebra-
    # automorphism axiom; see the audit note on the long-chord ρ/trace bug.)
    eps_wrap = _wrap_drift_from_bps(chord_charges, E_charge, bps, family_periods, k)
    primitives = sorted(chord_charges.keys())
    table = {}
    for g1 in primitives:
        c1 = chord_charges[g1]
        for g2 in primitives:
            c2 = chord_charges[g2]
            prod = bps.multiply(c1, c2)
            terms = []
            for chg, qcoef in prod.terms.items():
                coef_terms = sorted(qcoef._coeffs.items())
                dec = _decompose(chg, chord_charges, primitives, E_charge, bps, 4)
                if dec is None:
                    raise RuntimeError(
                        f"k={k}: failed to decompose {chg} from L_{g1}·L_{g2}. "
                        f"This means a primitive chord family is missing from "
                        f"`_canonical_seeds(k)` — extend it with the new seed "
                        f"by hand (BPS exploration), or move to an RGKAlgebra "
                        f"presentation for higher k."
                    )
                e_E, factors = dec
                for q_pow, q_coef in coef_terms:
                    terms.append((int(q_pow), int(e_E), tuple(factors), int(q_coef)))
            table[(g1, g2)] = terms
    return chord_charges, E_charge, MultTable(
        table, family_periods, E_charge, eps_wrap)


def _wrap_drift_from_bps(chord_charges, E_charge, bps, family_periods, k):
    """Per-family wrap E-drift `eps_wrap[a]` with `ρ(L_{a,P-1}) =
    E^{eps_wrap[a]}·L_{a,0}`, plus the `ρ(E)=E⁻¹` check — extracted from BPS
    (ground truth), exactly as the good-branch `u1a1aodd_kalg` does it via its
    oracle.  Raises if a wrap drift is not a clean E-power or `ρ(E)≠E⁻¹`."""
    n = len(E_charge)
    Esup = [j for j in range(n) if E_charge[j] != 0]
    if not Esup:
        raise AssertionError(f"k={k}: E_charge has empty support")
    eps = {}
    for a, P in family_periods.items():
        r = tuple(bps.rho(chord_charges[(a, P - 1)]))
        c0 = chord_charges[(a, 0)]
        diff = tuple(r[j] - c0[j] for j in range(n))
        m = diff[Esup[0]] // E_charge[Esup[0]]
        if any(diff[j] != m * E_charge[j] for j in range(n)):
            raise AssertionError(
                f"k={k}: wrap drift for family {a} is not a pure E-power: {diff}")
        eps[a] = m
    rE = tuple(bps.rho(tuple(E_charge)))
    if rE != tuple(-x for x in E_charge):
        raise AssertionError(f"k={k}: ρ(E) is not E⁻¹: {rE}")
    return eps


class MultTable:
    """Container for k-specific multiply table + metadata."""
    def __init__(self, table, family_periods, E_charge, eps_wrap=None):
        self.table = table
        self.family_periods = family_periods
        self.E_charge = E_charge
        # Per-family wrap-around E-drift: ρ(L_{a, P_a-1}) = E^{eps_wrap[a]}·L_{a, 0}
        # (with ρ(E)=E⁻¹).  The data the closed-form ρ needs beyond the orbit
        # shift; derived from BPS in `generate_mult_table`.
        self.eps_wrap = eps_wrap or {}

    def get(self, key, default=None):
        return self.table.get(key, default)

    def __getitem__(self, key):
        return self.table[key]

    def __contains__(self, key):
        return key in self.table


