# The generating function G(x, μ) — Tr(K^n) exactly through 𝖖^K
# ---------------------------------------------------------------------------

def _eq_coeffs(K: int) -> list[dict]:
    """`[y^i] E_𝖖(y) = (−1)^i 𝖖^i / (𝖖²;𝖖²)_i` for `i = 0..K`, each a sparse
    `{𝖖-exponent: int}` truncated at `𝖖^K`.  `E_𝖖(y) = 1/(−𝖖y; 𝖖²)_∞`, and the
    𝖖-binomial theorem gives `1/(z;q)_∞ = Σ_n z^n/(q;q)_n` with `q → 𝖖²`,
    `z → −𝖖y`."""
    inv = {0: 1}                                 # 1/(𝖖²;𝖖²)_i, running
    out = []
    for i in range(K + 1):
        out.append({e + i: c * ((-1) ** i) for e, c in inv.items() if e + i <= K})
        step = 2 * (i + 1)                       # next: divide by (1 − 𝖖^{step})
        if step <= K:
            new: dict = {}
            for e, c in inv.items():
                t = 0
                while e + step * t <= K:
                    new[e + step * t] = new.get(e + step * t, 0) + c
                    t += 1
            inv = {e: c for e, c in new.items() if c}
    return out


def _qpoch_q2_sq(K: int) -> dict:
    """`(𝖖²;𝖖²)_∞²` truncated at `𝖖^K`, sparse."""
    base = {0: 1}
    n = 1
    while 2 * n <= K:
        for _ in range(2):
            nxt = dict(base)
            for e, c in base.items():
                ee = e + 2 * n
                if ee <= K:
                    nxt[ee] = nxt.get(ee, 0) - c
            base = {e: c for e, c in nxt.items() if c}
        n += 1
    return base


def _mul2(A: dict, B: dict, K: int) -> dict:
    """Product of two `{(𝖖-exp, μ-exp): int}` polynomials, truncated at 𝖖^K."""
    out: dict = {}
    for (e1, j1), c1 in A.items():
        for (e2, j2), c2 in B.items():
            e = e1 + e2
            if e > K:
                continue
            key = (e, j1 + j2)
            out[key] = out.get(key, 0) + c1 * c2
    return {k: v for k, v in out.items() if v}


def cartan_traces(K: int) -> dict[int, dict]:
    """`[x^n] G(x, μ)` for every `n` with `|n| ≤ K`, exactly through `𝖖^K`, as
    `{n: {(𝖖-exp, μ-exp): int}}`.

    `G = (𝖖²;𝖖²)_∞² · A(x) · A(x⁻¹)` with `A(x) = E_𝖖(μx)E_𝖖(μ⁻¹x) = Σ_p x^p A_p(μ)`,
    `A_p(μ) = Σ_{i+j=p} e_i e_j μ^{i−j}` of 𝖖-valuation `p`; so
    `[x^n]G = pref · Σ_{p−p'=n} A_p A_{p'}`, and only `p + p' ≤ K` contributes
    below `𝖖^{K+1}`.  Symmetric under `n ↦ −n` (swap `p ↔ p'`) and under
    `μ ↦ μ⁻¹` (swap `i ↔ j`), as the trace axioms require."""
    e = _eq_coeffs(K)
    A: list[dict] = []
    for p in range(K + 1):
        Ap: dict = {}
        for i in range(p + 1):
            j = p - i
            for e1, c1 in e[i].items():
                for e2, c2 in e[j].items():
                    ee = e1 + e2
                    if ee > K:
                        continue
                    key = (ee, i - j)
                    Ap[key] = Ap.get(key, 0) + c1 * c2
        A.append({k: v for k, v in Ap.items() if v})
    pref = {(ee, 0): c for ee, c in _qpoch_q2_sq(K).items()}
    out: dict[int, dict] = {}
    for p in range(K + 1):
        for pp in range(K + 1 - p):
            n = p - pp
            prod = _mul2(A[p], A[pp], K)
            acc = out.setdefault(n, {})
            for key, c in prod.items():
                acc[key] = acc.get(key, 0) + c
    for n in list(out):
        out[n] = _mul2(out[n], pref, K)
    return out


