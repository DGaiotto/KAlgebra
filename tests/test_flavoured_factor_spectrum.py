def test_weights_and_characters_round_trip_including_virtual_ones():
    """`decompose` inverts `irrep_weights`, on products and on signed sums.

    The `R(G)`-valued bookkeeping rests on this: a `W`-invariant weight function
    is the weight diagram of a unique virtual character.  Certified machinery
    (`SUNZPlusRing.from_abelian`), exercised here on the product groups this
    module actually builds.
    """
    for factors, reps in (
        ([2, 2], [((), ()), ((1,), ()), ((), (1,)), ((1,), (1,)), ((2,), (2,))]),
        ([3, 2], [((1,), ()), ((1, 1), (1,)), ((2, 1), (2,))]),
        ([4], [((1,),), ((1, 1),), ((2, 1),)]),
    ):
        F = FlavourSpace(factors)
        for r in reps:
            assert F.decompose(F.irrep_weights(r)) == {r: 1}, (factors, r)
        a, b = reps[-1], reps[0]
        wa, wb = F.irrep_weights(a), F.irrep_weights(b)
        mix = {k: wa.get(k, 0) - 2 * wb.get(k, 0) for k in set(wa) | set(wb)}
        got = FlavourSpace(factors).decompose(mix)
        want = {a: 1, b: -2} if a != b else {a: -1}
        assert got == {k: v for k, v in want.items() if v}, (factors, got)


def test_decompose_honest_fails_on_a_non_invariant_weight_function():
    """A weight function that is not `W`-invariant is not a virtual character,
    and is refused rather than projected onto the invariants."""
    F = FlavourSpace([2])
    fn = {(1,): 1}                      # one weight of the fundamental, alone
    assert not F.is_weyl_invariant(fn)
    try:
        F.decompose(fn)
    except ValueError:
        return
    raise AssertionError("decompose accepted a non-invariant weight function")


