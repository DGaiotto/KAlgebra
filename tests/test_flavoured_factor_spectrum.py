def test_S_does_not_depend_on_the_order_on_charge_spin_irrep():
    """The flavoured PBW conjecture: the factorization
    `∏_{γ,s,r} E^{(s;r)}_\\fq(X_γ)^{Ω(γ,s,r)}` may be taken in any total order
    on `Γ_+ × ½N × Irr(G)`, and `S` does not depend on the choice.

    The order is honoured **globally**, not merely within each degree: a
    `piece_key` sends the engine down `_run_insert`, which keeps the factors in
    a `piece_key`-sorted list and inserts each newly discovered one at its own
    position — before lower-degree factors when the order says so.  That
    matters, because the conjecture quantifies over all total orders and the
    degree-compatible ones are a thin subset of them.
    """
    for entry in CORPUS[:6]:
        Q, D = _quiver(entry)
        base = build_flavoured_spectrum_generator(Q, D)
        for seed in range(4):
            S = build_flavoured_spectrum_generator(
                Q, D, piece_key=_random_piece_key(seed))
            assert set(S) == set(base) and _same(S, base), (entry[0], seed)


def test_a_degree_compatible_order_agrees_with_the_general_route():
    """The two routes agree where both apply.

    `_run_append` (no `piece_key`) places whole charges degree by degree;
    `_run_insert` honours an arbitrary order.  Handed a key that sorts by
    degree first — a degree-compatible order, where the general route reduces
    to the special one — they must produce the same `S` and the same `Ω`.
    """
    for entry in CORPUS[:6]:
        Q, D = _quiver(entry)
        append = FlavouredFactorSpectrum(Q, D)
        append.run()
        insert = FlavouredFactorSpectrum(
            Q, D, piece_key=lambda k, two_s, r: (sum(k), k, two_s, r))
        insert.run()
        assert _same(append.spectrum_generator(),
                     insert.spectrum_generator()), entry[0]
        assert append.multiplicities_by_spin() == \
            insert.multiplicities_by_spin(), entry[0]


def test_the_order_moves_the_factor_content_so_the_previous_test_has_teeth():
    """`S` is order-independent; its FACTORIZATION is not.

    Without this the order-independence test would be vacuous — it would be
    comparing a computation with itself.  At least one corpus entry must yield
    genuinely different `Ω` under different orders.  With the order honoured
    globally the spread is wide: 5 to 8 distinct factor contents from 8 random
    orders, against 2 when the order was applied only within each degree.
    """
    moved = 0
    for entry in CORPUS:
        Q, D = _quiver(entry)
        contents = set()
        for seed in range(6):
            eng = FlavouredFactorSpectrum(Q, D,
                                          piece_key=_random_piece_key(seed))
            eng.run()
            contents.add(repr(sorted(
                (k, sorted(map(str, v.items())))
                for k, v in eng.multiplicities_by_spin().items())))
        if len(contents) > 1:
            moved += 1
    assert moved >= len(CORPUS) - 2, f"order moved the content on only {moved}"


def test_a_weight_level_order_leaves_cE_G():
    """The index set of the flavoured PBW statement is `Irr(G)`, NOT the weights.

    NEGATIVE CONTROL.  Ordering the individual `E^{(s)}_\\fq(μ^w X_γ)` factors
    independently is a legitimate order in the ENLARGED `\\cE`, and indeed
    leaves `S` unchanged — but the resulting multiplicities are then not
    `G`-characters, so the factorization is not one in `\\cE_G`.  So a whole
    `E^{(s;r)}_\\fq(X_γ)` must be placed as a unit, and that requirement is not
    a convention: it is what the generator set of `\\cE_G` means.
    """
    broke = 0
    trials = 0
    for entry in (CORPUS[0], CORPUS[3], CORPUS[5], CORPUS[9]):
        Q, D = _quiver(entry)
        base = build_flavoured_spectrum_generator(Q, D)
        for seed in range(8):
            eng = FlavouredFactorSpectrum(
                Q, D, piece_key=_random_piece_key(seed), split_weights=True)
            eng.run()
            trials += 1
            assert _same(eng.spectrum_generator(), base), (entry[0], seed)
            if eng.verify_omega_is_a_character():
                broke += 1
    assert broke, ("no weight-level order broke the character property; the "
                   "negative control has no teeth")


