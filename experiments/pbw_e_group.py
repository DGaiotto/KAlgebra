def key_degree_lex(gamma, two_s):
    return (deg(gamma), gamma, two_s)


def key_anti_degree(gamma, two_s):
    """Every top-degree factor before any node factor.

    Reachable by no central charge and by no degree-compatible scheme, so this
    is the structured extreme the shuffles rarely produce.
    """
    return (-deg(gamma), gamma, two_s)


def key_lex_reversed(gamma, two_s):
    return (tuple(-x for x in gamma), -two_s)


def key_spin_first(gamma, two_s):
    return (-two_s, deg(gamma), gamma)


def make_key_shuffled(rank, D, rng, max_two_s):
    """A uniformly random total order on the truncated `Gplus x (1/2)N`."""
    pairs = [(gm, ts)
             for d in range(1, D + 1) for gm in cone_points(rank, d)
             for ts in range(max_two_s + 1)]
    rng.shuffle(pairs)
    pos = {p: i for i, p in enumerate(pairs)}
    n = len(pairs)

    def key(gamma, two_s):
        return pos.get((gamma, two_s), n + two_s)

    return key


def make_key_phase(phases):
    """The physical order: by `arg Z_gamma` for a linear central charge."""
    import cmath

    def key(gamma, two_s):
        z = sum(p * x for p, x in zip(phases, gamma))
        return (cmath.phase(z) if z != 0 else 0.0, deg(gamma), gamma, two_s)

    return key


# --------------------------------------------------------------------------
# Laurent expansion, the BPS quiver constraint, and the forced build of S.
#
# These support the remaining conjectures of the paper's "Seiberg-Witten RG
# flows" section: uniqueness of S, S_cluster = S, and the upper-cluster
# statement.
# --------------------------------------------------------------------------


def cf_expand(c: Coeff, top: int) -> dict[int, int]:
    """Laurent expansion of a coefficient, keeping every exponent `<= top`.

    `1/(1-q^{2n}) = sum_k q^{2nk}`, so dividing RAISES the bottom of the
    support and never lowers it -- hence the part of the expansion below any
    fixed `top` is a finite dict, computed exactly with no truncation error.
    """
    num, den = c
    if not num:
        return {}
    res = dict(num)
    for n, e in den.items():
        for _ in range(e):
            if not res:
                break
            lo = min(res)
            out: dict[int, int] = {}
            for k in range(lo, top + 1):
                v = res.get(k, 0) + out.get(k - 2 * n, 0)
                if v:
                    out[k] = v
            res = out
    return {k: v for k, v in res.items() if k <= top and v}


def forced_omega(f_exp: dict[int, int], target: int) -> dict[int, int]:
    """The `Omega` forced at one charge by the accumulated coefficient.

    A BPS factor contributes `-L*Omega` at its own charge, with
    `L = q/(1-q^2) = q + q^3 + q^5 + ...`  -- NOT `-q*Omega`; that misreading
    is blind on pure SU(2) and the pentagon (the design notes
    section 11).

    The BPS quiver constraint `S = 1 - q*sum_i X_{gamma_i} + O(q^2)` demands
    that `f - L*Omega` vanish at every exponent `<= 0` and equal `target` at
    exponent `1`.  That fixes `A_n := (L*Omega)[n]` for `n <= 1`, and since
    `A_n - A_{n-2} = Omega[n-1]`, it fixes `Omega[j] = A_{j+1} - A_{j-1}` for
    `j <= 0`.  `Omega` is palindromic, so its `j <= 0` half determines it.

    Returns `Omega` as a palindromic Laurent polynomial (the note's `P`).
    """
    def A(n: int) -> int:
        if n <= 0:
            return f_exp.get(n, 0)
        if n == 1:
            return f_exp.get(1, 0) - target
        raise AssertionError("A_n is only determined for n <= 1")

    lo = min(f_exp) if f_exp else 0
    om: dict[int, int] = {}
    for j in range(min(lo - 1, 0), 1):
        w = A(j + 1) - A(j - 1)
        if w:
            om[j] = w
    for j in list(om):
        if j < 0:
            om[-j] = om[j]
    return om


def leading_data_violations(g, nodes, *, D=None):
    """Where `g` fails the BPS quiver constraint `1 - q*sum_i X_i + O(q^2)`.

    Returns a list of `(charge, exponent, coefficient)`: a nonzero coefficient
    at a `q`-exponent `<= 0`, or a `q^1` coefficient that is not `-1` at a node
    and `0` elsewhere.  An empty list is the constraint holding.

    Sweeps the whole truncated cone, NOT just the support of `g`.  Iterating the
    support alone misses the case that matters most on the cluster side: a spec
    with a node dropped has coefficient identically zero there, so the missing
    `-q` is invisible and the wrong element passes.  (Measured: `spec = [gamma_1]`
    on the pentagon reported zero violations until this was fixed.)
    """
    nodeset = {tuple(n) for n in nodes}
    rank = len(nodes[0]) if nodes else 0
    if D is None:
        D = max((deg(x) for x in g), default=0)
    bad = []
    charges = [c for d in range(1, D + 1) for c in cone_points(rank, d)]
    for gamma in charges:
        c = g.get(gamma, CF_ZERO)
        exp = cf_expand(c, 1)
        for e, v in sorted(exp.items()):
            if e <= 0 and v:
                bad.append((gamma, e, v))
        want = -1 if gamma in nodeset else 0
        got = exp.get(1, 0)
        if got != want:
            bad.append((gamma, 1, got - want))
    return bad


def build_S_forced(B, nodes, D, key, gen=None):
    """Build `S` from the BPS quiver constraint alone, in the order `key`.

    This is the same forced recursion the repo engine runs; it is reimplemented
    here only so that the ORDER can be varied freely and the resulting elements
    compared.  That comparison -- same element in every order -- is the
    measurement; the recursion itself is not independent evidence, since it
    imposes the leading data by construction rather than measuring it.
    """
    rank = len(B)
    nodeset = {tuple(n) for n in nodes}
    if gen is None:
        def gen(gm, ts, p):
            return E_spin_element_cached(gm, ts, p, D)
    factors: list[tuple] = []
    prefix: list[dict] = [elt_one(rank)]

    for d in range(1, D + 1):
        P = prefix[len(factors)]
        new = []
        for gamma in cone_points(rank, d):
            f_exp = cf_expand(P.get(gamma, CF_ZERO), 1)
            target = -1 if gamma in nodeset else 0
            om = forced_omega(f_exp, target)
            if not om:
                continue
            dec = decompose_into_chi(om)
            if dec is None:
                raise PBWFailure(gamma, "forced Omega is not in P")
            for two_s, a in dec.items():
                if a:
                    new.append((gamma, two_s, a))
        if new:
            merged = sorted(factors + new, key=lambda f: key(f[0], f[1]))
            fc = 0
            while fc < len(factors) and factors[fc] == merged[fc]:
                fc += 1
            factors = merged
            del prefix[fc + 1:]
            for i in range(fc, len(factors)):
                gm, ts, a = factors[i]
                prefix.append(elt_mul(prefix[i], gen(gm, ts, a), B, D))
    return prefix[len(factors)], factors


def spec_product(spec, B, D):
    """`S_cluster = prod_a E_q(X_{gamma(a)})`, ordered by increasing `a`.

    The paper's candidate spectrum generator from a maximal green sequence.
    Every factor is a plain `E_q` -- spin 0, multiplicity 1.
    """
    rank = len(B)
    out = elt_one(rank)
    for gamma in spec:
        gamma = tuple(int(x) for x in gamma)
        if deg(gamma) > D or any(x < 0 for x in gamma):
            continue
        out = elt_mul(out, E_spin_element_cached(gamma, 0, 1, D), B, D)
    return out


# --------------------------------------------------------------------------
# The upper-cluster conjecture: RG_gamma from `RG_gamma * S = X_gamma + O(q)`.
# --------------------------------------------------------------------------


def solve_RG(gamma, S, B, Dk):
    """`RG_gamma` with `RG_gamma * S = X_gamma + O(q)`, on `gamma + Gplus`.

    Returned as `{kappa: coefficient}` -- the coefficient of `X_{gamma+kappa}`
    -- for `kappa` in the cone of degree `<= Dk`.

    At each `kappa` the equation reads `acc + c_kappa = O(q)` with `acc` the
    contribution of the strictly lower `kappa'` (the `kappa' = kappa` term is
    `c_kappa * S_0 = c_kappa`, since `S_0 = 1` and the phase vanishes).  The
    unique bar-invariant `c_kappa` over `Z[q, q^{-1}]` killing the non-positive
    part of `acc` is `-acc[0] - sum_{n<0} acc[n](q^n + q^{-n})`, so existence
    and uniqueness are automatic -- what is NOT automatic, and is what the
    conjecture asserts, is that the support TERMINATES, i.e. that this formal
    sum is an actual element of `Q_q(Gamma)`.
    """
    rank = len(B)
    zero = (0,) * rank
    c: dict[Charge, Coeff] = {zero: CF_ONE}
    for d in range(1, Dk + 1):
        for kappa in cone_points(rank, d):
            acc = CF_ZERO
            for kp, ck in c.items():
                rest = tuple(a - b for a, b in zip(kappa, kp))
                if any(x < 0 for x in rest) or not any(rest):
                    continue
                s = S.get(rest)
                if s is None or cf_is_zero(s):
                    continue
                ph = bracket(B, tuple(g + k for g, k in zip(gamma, kp)), rest)
                acc = cf_add(acc, cf_mul(cf_mul(ck, s), cf_from_lp({ph: 1})))
            if cf_is_zero(acc):
                continue
            e = cf_expand(acc, 0)
            lp: dict[int, int] = {}
            for n, v in e.items():
                if n > 0:
                    continue
                lp[n] = lp.get(n, 0) - v
                if n < 0:
                    lp[-n] = lp.get(-n, 0) - v
            lp = {k: v for k, v in lp.items() if v}
            if lp:
                c[kappa] = cf_from_lp(lp)
    return c


def rg_element(gamma, rg, D):
    """`RG_gamma` as a G-group-style element keyed by ABSOLUTE charges."""
    out = {}
    for kappa, coeff in rg.items():
        ch = tuple(g + k for g, k in zip(gamma, kappa))
        if deg(ch) <= D:
            out[ch] = coeff
    return out


def rg_support_top(rg):
    """Top cone degree carried by `RG_gamma`'s `kappa` support."""
    return max((deg(k) for k, v in rg.items() if not cf_is_zero(v)), default=0)


def decompose_in_RG(x, S, B, D, cache=None):
    """Write `x` in the `RG` basis, triangularly; None if it does not close.

    `RG_eps = X_eps + (strictly higher in the cone)`, so peeling the lowest
    charge of the support is forced and the decomposition is unique.  Returns
    `{eps: coefficient}`.  The coefficients are NOT constrained to be Laurent
    by the construction -- whether they are is the measured content of the
    conjecture's "define a sub-algebra over Z[q, q^{-1}]".
    """
    if cache is None:
        cache = {}

    def RG_at(eps):
        key = eps
        if key not in cache:
            cache[key] = solve_RG(eps, S, B, max(0, D - deg(eps)))
        return cache[key]

    rem = {g: v for g, v in x.items() if not cf_is_zero(v) and deg(g) <= D}
    out: dict[Charge, Coeff] = {}
    guard = 0
    while rem:
        guard += 1
        if guard > 20000:
            return None
        eps = min(rem, key=lambda g: (deg(g), g))
        a = rem.pop(eps)
        if cf_is_zero(a):
            continue
        out[eps] = a
        for kappa, cc in RG_at(eps).items():
            ch = tuple(g + k for g, k in zip(eps, kappa))
            if deg(ch) > D or not any(kappa):
                continue
            v = cf_add(rem.get(ch, CF_ZERO), cf_neg(cf_mul(a, cc)))
            if cf_is_zero(v):
                rem.pop(ch, None)
            else:
                rem[ch] = v
    return out


def E_spin_of_element(F, two_s, power, D, B, rank, base_deg):
    """`E^{(s)}_q(F)^power` for a torus element `F = X_a + (strictly higher)`.

    The universal one-variable series evaluated at `F` instead of at `X_a`.
    Because `F^n` starts at cone degree `n * base_deg`, the series terminates
    inside the truncation, and at degree `base_deg` only the linear term
    survives -- so the `x`-linear coefficient `-q*chi_s/(1-q^2)` governs the
    read-off exactly as it does on the `X_gamma`.
    """
    assert base_deg >= 1
    N = D // base_deg
    ser = _series_pow(E_spin_series_cached(two_s, N), power, N)
    out = elt_one(rank)
    Fp = elt_one(rank)
    for n in range(1, N + 1):
        Fp = elt_mul(Fp, F, B, D)
        if not Fp:
            break
        c = ser[n]
        if cf_is_zero(c):
            continue
        for g, v in Fp.items():
            w = cf_add(out.get(g, CF_ZERO), cf_mul(c, v))
            if cf_is_zero(w):
                out.pop(g, None)
            else:
                out[g] = w
    return out
