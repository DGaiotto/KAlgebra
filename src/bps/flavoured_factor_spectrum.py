class FlavouredFactorSpectrum:
    """`S ∈ \\cE_G` from flavoured leading data, on the reduced cone.

    The recursion is the unflavoured one of `BPSFactorSpectrum` carrying a
    weight grading: the accumulator is `{reduced cone point: {weight: Habiro}}`,
    and at each reduced cone point `Ω` is forced **independently at each
    weight** — legitimate because the `μ` are central and of `\\fq`-degree zero,
    so the `\\fq`-triangularity that forces `Ω` in the unflavoured case runs
    unchanged weight by weight.  `Ω`'s Weyl invariance is therefore never
    imposed; it comes out, and `multiplicities()` is where it is read.

    Parameters
    ----------
    quiver
        A `FlavouredQuiver`.
    cutoff
        Reduced-cone degree truncation `D`.  The only truncation.
    leading_data
        `reduced charge -> {weight: int}`, the prescribed `\\fq^1`-coefficient
        of `S`.  Default: `-χ_{r_a}` at the node charge `γ_a`, zero elsewhere —
        the flavoured BPS quiver constraint.
    piece_key
        `(charge, 2s, r) -> sortable` — **the index set is
        `Γ_+ × ½N × Irr(G)`**, one position per multiplet factor
        `E^{(s;r)}_\\fq(X_γ)^{Ω(γ,s,r)}`.  `S` is conjecturally independent of
        it (the flavoured PBW conjecture).  Pieces at one charge commute
        (`⟨γ,γ⟩ = 0`, flavour central), so placing them separately is licensed
        exactly as in the unflavoured engine.

        ⚠ **It is the index set that matters, and it is `Irr(G)`, not the
        weights.**  A whole `E^{(s;r)}` must be placed as one unit.  Ordering
        the individual weight factors `E^{(s)}_\\fq(μ^w X_γ)` independently
        still factors `S` — that is a factorization in the *enlarged* `\\cE` —
        but the resulting multiplicities are **not** `G`-characters, so it
        leaves `\\cE_G`.  Measured: on Kronecker-2 with `SU(2)` on one node a
        random weight-level order makes `Ω` fail Weyl invariance, and
        `multiplicities()` honest-fails rather than projecting.  That negative
        control is `split_weights=True` below.
    split_weights
        **Negative control only.**  Place individual weight factors rather than
        whole reps, ordered by `piece_key(charge, 2s, weight)`.  `S` is
        unchanged (it is order-independent in the enlarged `\\cE`), but `Ω`
        generally stops being a character — which is the evidence that the
        generator set of `\\cE_G` is doing real work.
    """

    def __init__(self, quiver: FlavouredQuiver, cutoff: int, *,
                 leading_data: Callable[[Vec], dict[Weight, int]] | None = None,
                 piece_key: Callable[..., object] | None = None,
                 split_weights: bool = False):
        if cutoff < 1:
            raise ValueError(f"cutoff must be >= 1, got {cutoff}")
        if split_weights and piece_key is None:
            raise ValueError("split_weights is a negative control; it needs a "
                             "piece_key(charge, 2s, weight) to order by")
        self.quiver = quiver
        self.rank = quiver.rank
        self.degree_cap = int(cutoff)
        self._piece_key = piece_key
        self._split_weights = bool(split_weights)
        self._leading = leading_data
        self.omega: dict[Vec, dict[Weight, dict[int, int]]] = {}
        #: `(charge, irrep, 2s, exponent)` in the order the generators were
        #: placed — the sequence a spec reading needs, since a spec is an
        #: ordered product and `Ω` alone is only a multiset.
        self.placements: list[tuple[Vec, Irrep, int, int]] = []
        self._placement_keys: list = []
        self._S: dict[Vec, dict[Weight, HabiroElement]] | None = None

    # ----- the constraint ----------------------------------------------
    def target(self, k: Vec) -> dict[Weight, int]:
        """The prescribed `\\fq^1`-coefficient of `S` at the reduced charge `k`."""
        if self._leading is not None:
            return {w: int(c) for w, c in self._leading(k).items() if c}
        if sum(k) == 1:
            a = k.index(1)
            return {w: -m for w, m in self.quiver.node_weights(a).items()}
        return {}

    # ----- the run ------------------------------------------------------
    def _readout(self, acc, degree: int):
        """`Ω` at every reduced cone point of one degree, forced by `acc`.

        Reading a whole degree before placing any of its factors is sound: a
        factor at a charge `k` of degree `d` contributes only at the multiples
        `nk`, `n ≥ 1`, hence only at degrees `≥ d`, and two distinct degree-`d`
        charges interact first at degree `2d`.  So no degree-`d` factor can
        change another degree-`d` readout.
        """
        fresh: list[tuple[Vec, dict[Weight, dict[int, int]]]] = []
        for k in cone_simplex(self.rank, self.degree_cap):
            if sum(k) != degree:
                continue
            here = acc.get(k, {})
            tgt = self.target(k)
            om_w: dict[Weight, dict[int, int]] = {}
            for w in set(here) | set(tgt):
                h = here.get(w)
                om = BPSFactorSpectrum._forced(
                    expansion(h) if h is not None else {}, tgt.get(w, 0))
                if om:
                    om_w[w] = om
            if om_w:
                fresh.append((k, om_w))
        return fresh

    def run(self) -> dict[Vec, dict[Weight, dict[int, int]]]:
        if self._piece_key is not None:
            return self._run_insert()
        return self._run_append()

    def _run_append(self) -> dict[Vec, dict[Weight, dict[int, int]]]:
        """No `piece_key`: place each charge's whole factor, in cone order."""
        F = self.quiver.flavour
        zero = tuple([0] * self.rank)
        acc: dict[Vec, dict[Weight, HabiroElement]] = {zero: {F.zero: H1}}
        self.omega = {}
        self.placements = []
        for d in range(1, self.degree_cap + 1):
            fresh = self._readout(acc, d)
            for k, om_w in fresh:
                self.omega[k] = om_w
            for k, om_w in fresh:
                for (rep, two_s), amount in self._omega_by_rep_spin(om_w).items():
                    self.placements.append((k, rep, two_s, amount))
                acc = self._factor_multiply(acc, k, d, om_w)
        self._S = acc
        return self.omega

    def _run_insert(self) -> dict[Vec, dict[Weight, dict[int, int]]]:
        """An ARBITRARY total order on `Γ_+ × ½N × Irr(G)`, honoured globally.

        The paper's PBW statement quantifies over *any* total order, not only
        the degree-compatible ones, so a factor discovered at degree `d` may
        have to be placed **before** factors already placed at lower degrees.
        That is what this mode does: factors are kept in a list sorted by
        `piece_key`, with cached prefix products, and each newly discovered
        factor is inserted at its sorted position with only the invalidated
        suffix rebuilt.

        Reading out at a higher degree stays correct after such an insertion
        because a degree-`d` factor contributes nothing below degree `d`, so
        every readout already taken is unaffected by where the new factor lands.

        (The degree-compatible special case is `_run_append`, which is cheaper
        and is what runs when no `piece_key` is given.  An earlier version of
        this module applied `piece_key` only *within* a degree — that silently
        tested a weaker statement than the conjecture makes.)
        """
        import bisect

        F = self.quiver.flavour
        zero = tuple([0] * self.rank)
        placed: list[tuple[Vec, dict[Weight, dict[int, int]], int]] = []
        self._placement_keys = []
        sort_keys: list = []
        prefix: list[dict[Vec, dict[Weight, HabiroElement]]] = [
            {zero: {F.zero: H1}}]
        self.omega = {}

        for d in range(1, self.degree_cap + 1):
            fresh = self._readout(prefix[-1], d)
            if not fresh:
                continue
            for k, om_w in fresh:
                self.omega[k] = om_w
            first = len(placed)
            for key, k, blk in self._pieces_of_degree(fresh):
                self._placement_keys.append((key, k, blk))
                at = bisect.bisect_left(sort_keys, key)
                sort_keys.insert(at, key)
                placed.insert(at, (k, blk, d))
                first = min(first, at)
            del prefix[first + 1:]
            for i in range(first, len(placed)):
                k, blk, deg = placed[i]
                prefix.append(self._factor_multiply(prefix[i], k, deg, blk))

        self._S = prefix[-1]
        # The spec reading: the generators in the order they were placed.
        # Under `split_weights` — the negative control — the pieces are single
        # weight factors and `Ω` is generally NOT a character, so there is no
        # rep labelling to read; `placements` stays empty rather than forcing a
        # decomposition that is meant to fail there.
        self.placements = []
        if not self._split_weights:
            for _key, k, blk in sorted(self._placement_keys, key=lambda t: t[0]):
                for (rep, two_s), amount in self._omega_by_rep_spin(blk).items():
                    self.placements.append((k, rep, two_s, amount))
        return self.omega

    def _pieces_of_degree(self, fresh):
        """The `(key, charge, weight-block)` factors discovered at one degree.

        One entry per generator `E^{(s;r)}_\\fq(X_γ)^{Ω(γ,s,r)}`, the rep kept
        whole — or, under `split_weights`, one per individual weight factor,
        which is the negative control.
        """
        out = []
        for k, om_w in fresh:
            if self._split_weights:
                for w, om in om_w.items():
                    for two_s, amount in spin_decompose(om).items():
                        piece = {j: amount for j in range(-two_s, two_s + 1, 2)}
                        out.append((self._piece_key(k, two_s, w), k, {w: piece}))
                continue
            for (rep, two_s), amount in self._omega_by_rep_spin(om_w).items():
                blk: dict[Weight, dict[int, int]] = {}
                for w, m in self.quiver.flavour.irrep_weights(rep).items():
                    blk[w] = {j: amount * m
                              for j in range(-two_s, two_s + 1, 2)}
                out.append((self._piece_key(k, two_s, rep), k, blk))
        return out

    # ----- Ω: weights -> (irrep, spin) ----------------------------------
    def _omega_by_rep(self, om_w: dict[Weight, dict[int, int]]
                      ) -> dict[Irrep, dict[int, int]]:
        """One `Ω(γ)`, from its weight expansion to a per-irrep `\\fq`-polynomial.

        Honest-fails (via `FlavourSpace.decompose`) if the weight function is
        not `W`-invariant — it never silently projects onto the invariants.
        """
        F = self.quiver.flavour
        by_q: dict[int, dict[Weight, int]] = {}
        for w, om in om_w.items():
            for j, c in om.items():
                if c:
                    by_q.setdefault(j, {})[w] = c
        per_rep: dict[Irrep, dict[int, int]] = {}
        for j, fn in by_q.items():
            for rep, c in F.decompose(fn).items():
                if c:
                    poly = per_rep.setdefault(rep, {})
                    poly[j] = poly.get(j, 0) + c
        per_rep = {r: {j: c for j, c in poly.items() if c}
                   for r, poly in per_rep.items()}
        return {r: poly for r, poly in per_rep.items() if poly}

    def _omega_by_rep_spin(self, om_w) -> dict[tuple[Irrep, int], int]:
        out: dict[tuple[Irrep, int], int] = {}
        for rep, poly in self._omega_by_rep(om_w).items():
            for two_s, amount in spin_decompose(poly).items():
                if amount:
                    out[(rep, two_s)] = amount
        return out

    # ----- the flavoured factor ----------------------------------------
    def _factor_series(self, om_w: dict[Weight, dict[int, int]], n_max: int):
        """`∏_{s,r} E^{(s;r)}_\\fq(X_γ)^{Ω(γ,s,r)}` along the ray, weight-graded.

        Written on weights rather than on irreps, which is the same product:
        `E^{(s;r)}_\\fq(X_γ) = ∏_{w∈r} E^{(s)}_\\fq(μ^w X_γ)`, so collecting the
        `E^{(s)}` factors by weight gives one ordinary charge series per weight,
        with content `Ω(γ)[w]`.  They all commute, so the ray factor is their
        weight-convolution.  Returns `[{weight: Habiro}] * (n_max+1)`, indexed by
        the multiple `n` of the reduced charge.
        """
        F = self.quiver.flavour
        out: list[dict[Weight, HabiroElement]] = [{} for _ in range(n_max + 1)]
        out[0] = {F.zero: H1}
        for w, om in sorted(om_w.items()):
            ray = charge_series(om, n_max)
            nxt: list[dict[Weight, HabiroElement]] = [{} for _ in range(n_max + 1)]
            for n1 in range(n_max + 1):
                block = out[n1]
                if not block:
                    continue
                for n2 in range(n_max + 1 - n1):
                    u = ray[n2]
                    if u.is_zero():
                        continue
                    shift = F.scale(w, n2)
                    dest = nxt[n1 + n2]
                    for W, h in block.items():
                        key = F.add(W, shift)
                        prev = dest.get(key)
                        dest[key] = h * u if prev is None else prev + h * u
            out = [{k: v for k, v in blk.items() if not v.is_zero()}
                   for blk in nxt]
        return out

    def _factor_multiply(self, acc, k0: Vec, deg0: int,
                         om_w: dict[Weight, dict[int, int]]):
        """`acc · (the ray factor at k0)`, truncated to the reduced cone."""
        F = self.quiver.flavour
        n_max = self.degree_cap // deg0
        ray = self._factor_series(om_w, n_max)
        out: dict[Vec, dict[Weight, HabiroElement]] = {}
        for k, block in acc.items():
            deg_k = sum(k)
            br = self.quiver.bracket(k, k0)
            for n in range(n_max + 1):
                if deg_k + n * deg0 > self.degree_cap:
                    break
                piece = ray[n]
                if not piece:
                    continue
                key_k = tuple(k[i] + n * k0[i] for i in range(self.rank))
                phase = q_pow(n * br) if br else None
                dest = out.setdefault(key_k, {})
                for W, h in block.items():
                    for W2, u in piece.items():
                        term = h * u
                        if phase is not None:
                            term = term * phase
                        key = F.add(W, W2)
                        prev = dest.get(key)
                        dest[key] = term if prev is None else prev + term
        return {k: {w: h for w, h in blk.items() if not h.is_zero()}
                for k, blk in out.items()
                if any(not h.is_zero() for h in blk.values())}

    # ----- readouts -----------------------------------------------------
    def spectrum_generator(self) -> dict[tuple[Vec, Weight], HabiroElement]:
        """`S` as `{(reduced charge, flavour weight): coefficient}`.

        The identity term sits at `((0,…,0), 0)`.  This is the flavoured `S`
        written on the enlarged lattice, which is the shape the unflavoured
        engine's `S` has and therefore the shape a comparison needs.
        """
        if self._S is None:
            self.run()
        out: dict[tuple[Vec, Weight], HabiroElement] = {}
        for k, blk in self._S.items():
            for w, h in blk.items():
                if not h.is_zero():
                    out[(k, w)] = h
        return out

    def multiplicities(self) -> dict[Vec, dict[Irrep, dict[int, int]]]:
        """`Ω(γ, r)` — at each reduced charge, a palindromic `\\fq`-polynomial
        per irrep of `G`.

        Raises if some `Ω(γ)` is not Weyl-invariant, i.e. is not a virtual
        character — an honest failure.  That it never does is the substantive
        flavoured claim (`S ∈ \\cE_G`), so this is the load-bearing readout.
        """
        if self._S is None:
            self.run()
        out: dict[Vec, dict[Irrep, dict[int, int]]] = {}
        for k, om_w in self.omega.items():
            per_rep = self._omega_by_rep(om_w)
            if per_rep:
                out[k] = per_rep
        return out

    def multiplicities_by_spin(self) -> dict[Vec, dict[tuple[Irrep, int], int]]:
        """`Ω(γ, s, r)` — the flavoured PBW exponents, keyed `(r, 2s)`."""
        if self._S is None:
            self.run()
        out: dict[Vec, dict[tuple[Irrep, int], int]] = {}
        for k, om_w in self.omega.items():
            here = self._omega_by_rep_spin(om_w)
            if here:
                out[k] = here
        return out

    # ----- the generators, as operations on a built `S` ------------------
    def generator_weight_content(self, rep: Irrep, two_s: int,
                                 exponent: int = 1) -> dict[Weight, dict[int, int]]:
        """`E^{(s;r)}_\\fq(X_γ)^{exponent}` as a per-weight `Ω` block.

        The generator is `∏_{w∈r} E^{(s)}_\\fq(μ^w X_γ)^{exponent}`, so at the
        weight `w` its content is `exponent·mult_r(w)·χ_s` — which is exactly
        what one ordinary ray factor of content `Ω[w]` means.  Independent of
        the charge, since a charge's self-bracket vanishes.
        """
        out: dict[Weight, dict[int, int]] = {}
        for w, m in self.quiver.flavour.irrep_weights(rep).items():
            out[w] = {j: exponent * m for j in range(-two_s, two_s + 1, 2)}
        return out

    def times_generator(self, acc, charge: Vec, rep: Irrep, two_s: int,
                        exponent: int = 1):
        """`acc · E^{(s;r)}_\\fq(X_charge)^{exponent}`, cone-truncated.

        The operation the uniqueness axiom is stated against: multiplying a
        candidate `S` by a single generator of `\\cE_G` and asking whether the
        BPS quiver constraint survives.
        """
        deg = sum(charge)
        if deg < 1:
            raise ValueError("charge must lie in the positive cone")
        return self._factor_multiply(
            acc, tuple(charge), deg,
            self.generator_weight_content(rep, two_s, exponent))

    def constraint_violations(self, acc=None) -> list[tuple[Vec, Weight, str]]:
        """Where a candidate `S` fails the flavoured BPS quiver constraint.

        Two conditions, both of them what `\\cE_G ∋ S = 1 - \\fq Σ_a χ_{r_a}(μ)
        X_{γ_a} + O(\\fq^2)` says: no coefficient carries a non-positive power
        of `\\fq` away from the identity, and the `\\fq^1` coefficients are the
        prescribed leading data.  Empty list = the constraint holds on the
        truncated cone.
        """
        if acc is None:
            if self._S is None:
                self.run()
            acc = self._S
        F = self.quiver.flavour
        zero = tuple([0] * self.rank)
        bad: list[tuple[Vec, Weight, str]] = []
        for k, blk in acc.items():
            for w, h in blk.items():
                if h.is_zero():
                    continue
                if (k, w) == (zero, F.zero):
                    if h != H1:
                        bad.append((k, w, "identity term != 1"))
                    continue
                neg = {e: c for e, c in expansion(h).items() if e <= 0 and c}
                if neg:
                    bad.append((k, w, f"non-positive \\fq powers {neg}"))
        for k in cone_simplex(self.rank, self.degree_cap):
            k = tuple(k)
            blk = acc.get(k, {})
            tgt = self.target(k)
            for w in set(tgt) | set(blk):
                got = expansion(blk[w]).get(1, 0) if w in blk else 0
                want = tgt.get(w, 0)
                if got != want:
                    bad.append((k, w, f"\\fq^1 = {got}, leading data says {want}"))
        return bad

    # ----- verifiers ----------------------------------------------------
    def verify_leading_data(self) -> list[tuple[Vec, Weight, str]]:
        """`S`'s `\\fq^1`-coefficient against the prescribed leading data.

        **Enforced, not emergent** — the recursion solves for exactly this, so
        this is a regression guard on the arithmetic and not evidence about the
        conjectures (the audit, the same caveat as unflavoured).
        """
        S = self.spectrum_generator()
        bad: list[tuple[Vec, Weight, str]] = []
        F = self.quiver.flavour
        zero = (tuple([0] * self.rank), F.zero)
        for (k, w), h in S.items():
            exp = expansion(h)
            if (k, w) == zero:
                if h != H1:
                    bad.append((k, w, "identity term != 1"))
                continue
            neg = {e: c for e, c in exp.items() if e <= 0 and c}
            if neg:
                bad.append((k, w, f"non-positive \\fq powers {neg}"))
        for k in cone_simplex(self.rank, self.degree_cap):
            tgt = self.target(tuple(k))
            for w, want in tgt.items():
                got = expansion(S.get((tuple(k), w), H0)).get(1, 0)
                if got != want:
                    bad.append((tuple(k), w,
                                f"\\fq^1 = {got}, leading data says {want}"))
        return bad

    def verify_omega_is_a_character(self) -> list[tuple[Vec, str]]:
        """Every `Ω(γ)` is `W`-invariant, i.e. a virtual character of `G`.

        **Emergent** — nothing in the recursion imposes it (`Ω` is forced weight
        by weight, independently), so a pass is genuine evidence for
        `S ∈ \\cE_G`.  This is the substantive flavoured claim.
        """
        F = self.quiver.flavour
        if self._S is None:
            self.run()
        bad: list[tuple[Vec, str]] = []
        for k, om_w in self.omega.items():
            by_q: dict[int, dict[Weight, int]] = {}
            for w, om in om_w.items():
                for j, c in om.items():
                    if c:
                        by_q.setdefault(j, {})[w] = c
            for j, fn in by_q.items():
                if not F.is_weyl_invariant(fn):
                    bad.append((k, f"\\fq^{j} weight function not W-invariant"))
        return bad


