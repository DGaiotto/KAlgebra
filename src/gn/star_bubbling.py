def _audit_candidate(datum, cand, reps, sym_basis, T_of, idx, nvars,
                     all_equations, oq_rows):
    """Why is a KNOWN-GOOD answer not found?  Report representability in the
    ansatz, then which equations it violates.

    The solver can only ever say `unique` / `non-unique` / `inconsistent`, and
    an `inconsistent` verdict has (at least) two very different causes: the true
    answer is outside the ansatz (a **cutoff** defect — box too small, `𝖖`-window
    too narrow), or it is inside and the equations are wrong.  Distinguishing
    them by re-solving at wider `pad` cannot work when the deficiency is not in
    the direction `pad` dilates, which is exactly the situation was
    left unable to discriminate.  This makes the distinction directly
    measurable, given a candidate from an independent construction (the RG flow,
    or product-and-peel).

    `cand` is `{interior cell: TorusRational}` — the candidate residual `f`.
    Returns a report dict; never solves anything and never mutates state."""
    rep_report, coords, unrep = {}, {}, False
    for n in reps:
        f = cand.get(n)
        if f is None:
            rep_report[n] = {"status": "absent from candidate"}
            unrep = True
            continue
        f = f.simplify()
        basis = sym_basis[n]
        if not basis:
            rep_report[n] = {"status": "empty ansatz"}
            unrep = True
            continue
        den = basis[0].den
        if f.den != den:
            rep_report[n] = {"status": "DENOMINATOR mismatch",
                             "cand_den": dict(f.den), "ansatz_den": dict(den)}
            unrep = True
            continue
        # triangular solve against the basis, keyed on each element's largest
        # weight (basis numerators are distinct stabilizer-orbit sums)
        sig = []
        for j, sym in enumerate(basis):
            sig.append((max(sym.num.terms), j))
        sig.sort(reverse=True)
        rem = dict(f.num.terms)
        xs: dict = {}
        for wt, j in sig:
            lp = rem.get(wt)
            if lp is None or lp.is_zero():
                continue
            bnum = basis[j].num.terms
            blead = bnum[wt]
            if blead != LaurentPoly.one():
                rep_report[n] = {"status": "non-unit basis lead", "weight": wt}
                unrep = True
                break
            xs[j] = lp
            for bw, bc in bnum.items():
                cur = rem.get(bw, LaurentPoly.zero())
                rem[bw] = cur - lp * bc
        else:
            leftover = sorted(w for w, c in rem.items() if not c.is_zero())
            bad_pal, bad_deg = [], []
            for j, lp in xs.items():
                degs = [d for d, c in lp._coeffs.items() if c]
                if not degs:
                    continue
                if max(abs(d) for d in degs) > T_of[n]:
                    bad_deg.append((j, max(abs(d) for d in degs), T_of[n]))
                for d, c in lp._coeffs.items():
                    if c and lp._coeffs.get(-d, 0) != c:
                        bad_pal.append((j, d))
                        break
            st = "representable"
            if leftover:
                st = "WEIGHTS OUTSIDE THE BOX"
                unrep = True
            elif bad_deg:
                st = "𝖖-WINDOW too narrow"
                unrep = True
            elif bad_pal:
                st = "coefficient not palindromic"
                unrep = True
            rep_report[n] = {"status": st, "outside": leftover,
                             "window": bad_deg, "nonpalindromic": bad_pal,
                             "T_of": T_of[n]}
            if st == "representable":
                for j, lp in xs.items():
                    for t in range(0, T_of[n] + 1):
                        c = lp._coeffs.get(t, 0)
                        if t == 0:
                            coords[idx[(n, j, 0)]] = c
                        else:
                            coords[idx[(n, j, t)]] = c
            continue
    out = {"representable": not unrep, "cells": rep_report}
    if unrep:
        return out
    vec = [0] * nvars
    for col, v in coords.items():
        vec[col] = v
    viol, first, noq = 0, None, 0
    for i, (row, b) in enumerate(all_equations()):
        if sum(c * vec[j] for j, c in row.items()) != b:
            viol += 1
            if i < len(oq_rows):
                noq += 1
            if first is None:
                first = (i, "O(𝖖)" if i < len(oq_rows) else "(★)", dict(row), b)
    out.update(violated=viol, violated_oq=noq, first=first)
    return out


def joint_solve(datum, m, e, pad=1, q_extra=2, weyl_cov=True, verbose=False,
                seed_f=None, anchors=None, oq_offset=None, admits_e=None,
                audit=None, support=None, stats=None):
    """Solve every bubbling cell of `L_{m,e}` at once from (★) + bar + `O(𝖖)`.

    Returns `(status, Ff, support, interior, K_f)`; `status == "unique"` is the
    only case in which `Ff` (the interior/bubbling cells) is not `None`.

    `weyl_cov=False` drops Weyl covariance, giving every interior cell its own
    unknowns — the measurement that the assumption is *subsumed* rather than
    needed (SU(2) `(2,3)`: 88 → 176 unknowns; SU(3) adjoint: 120 → 728; still
    uniquely solvable, answer automatically covariant).

    `seed_f` / `anchors` (both default `None` = the pure behaviour, unchanged)
    make the solver reusable for the **matter slices** of
    `matter_star_bubbling`: at μ-level `n` the extremal cells are seeded with
    `pure·Z[n]` rather than the bare leading orbit, and the ansatz box is
    anchored on weights shifted by `n` matter weights.  (★) was measured to
    hold separately at every μ-level, which is what makes the slice a
    well-posed instance of this same system.

    `oq_offset` (`{cell: TorusRational}`, default `None`) shifts the `O(𝖖)`
    condition from `val_𝖖(f_n) ≥ 1` to `val_𝖖(f_n − offset_n) ≥ 1`.  The pure
    theory needs no offset; a matter slice does, because the object with the
    uniform threshold is the **quotient** `Q = f/Z`, not `f` itself.  Since
    `Z[0] = 1`, `f[n] = Q[n] + Σ_{i≥1} Z[i]·Q[n−i]`, and the sum is known once
    the lower levels are solved — so it enters here as a constant RHS.
    (Measured: at SU(2) `m=(3,)` and U(2) `m=(0,−3)` the true interior slices
    have `val_𝖖 f[n] = 0` at the intermediate levels, so the unoffset condition
    is FALSE there and forces a unique-but-wrong answer, while
    `val_𝖖 Q[j] ≥ 1` holds uniformly at every cell and level.)

    `admits_e` (default `None` = unchanged, the simply connected behaviour) is the
    global form's electric-admissibility predicate, i.e. **(★) for the form** rather
    than for `G̃`.

    Why it can drop equations, derived rather than guessed: multiplying by `χ_e`
    changes the numerator but **not** the denominators, so the residue of `x·χ_e` on
    a wall is `Res_wall(x)·χ_e|_wall`.  Therefore a wall condition is required by
    `Λ_H` **iff some admitted `χ_e` is non-zero on that wall** — and one on which
    every admitted character vanishes imposes nothing.  `wall_is_probed` decides it.

    ⚠ Relaxing constraints can cost UNIQUENESS, which is the licensed solve's first
    guard condition.  Fewer equations can turn `inconsistent` into a genuinely
    underdetermined system, and an unguarded non-unique solve is the hazard the whole
    tier's discipline exists to prevent.  So a
    relaxed solve that comes back non-unique must be reported as such, never
    resolved by picking a solution.

    `support` (default `None` = `tropical_support(datum, m)`, the hull `conv(W·m)`
    — unchanged) replaces the set of cells that carry the seed and the unknowns.
    It exists to MEASURE the support condition rather than assume it: the draft
    remarks that bubbling supported on the Weyl orbits subdominant to `m` "appears
    to follow from the above axioms", and the direct test is to solve on a larger
    set of cells and see whether the unique solution vanishes outside the hull.
    The override must contain the hull and be Weyl-invariant; take it convex too
    (`tropical_support(datum, m')` for a dominant `m' ≥ m`), so that every pole of
    a cell's dressing `ψ_n` keeps its residue partner inside the set — asserted
    below, since a pole with no partner would be left unconstrained.  One thing
    changes when the set is larger than the hull: a seed cell acquires partners
    outside it, on walls where the seed has NO pole.  So the seed's walls are then
    a SUBSET of the predicted ones, and the seed numerator is taken over the full
    predicted denominator — it vanishes on the extra walls, which is what forces
    the partner's residue there to zero.  An `oq_offset` (a matter slice) is taken
    over the full denominator in the same way: a hull cell acquires walls too, and
    an offset assembled from lower levels that were simplified has cancelled
    them.  With `support=None` both are bit-identical to before.

    `stats` (default `None`): a dict that receives the system's shape — `nvars`,
    the columns of each orbit representative (`cols`), the representative of each
    interior cell (`rep_of`) — and, after the solve, its `status` and pivot
    columns (`pivots`).  Diagnostic only.  Its use is the CONTROL for the support
    measurement: with the residue rows removed (`admits_e` admitting nothing) the
    remaining `O(𝖖)` rows are cell-local, so a representative whose columns are
    not all pivots carries a nonzero bar-invariant `O(𝖖)` filling — and if (★)
    then empties that cell, it is (★), not bar + `O(𝖖)`, that does it."""
    d = datum.dim
    m, e = tuple(m), tuple(e)
    hull = [tuple(p) for p in tropical_support(datum, m)]
    if support is None:
        support = hull
    else:
        support = list(dict.fromkeys(tuple(p) for p in support))
        _sset = set(support)
        if not set(hull) <= _sset:
            raise ValueError(f"{datum.name}: support override does not contain "
                             f"the hull conv(W·{m})")
        for _p in support:
            for _w in datum.weyl_elements():
                if tuple(datum.act_cochar(_w, _p)) not in _sset:
                    raise ValueError(f"{datum.name}: support override is not "
                                     f"Weyl-invariant (at {_p})")
    enlarged = len(support) > len(hull)
    orbit = sorted({tuple(datum.act_cochar(w, m)) for w in datum.weyl_elements()})
    oset = set(orbit)
    extremal = [p for p in support if p in oset]
    interior = [p for p in support if p not in oset]

    if seed_f is None:
        seed = W.leading_orbit(datum, m, e)
        seed_f = {tuple(a): f for a, f in seed.residuals().items()}
        if not seed_f:
            # The seed carries the leading-term normalization, so an EMPTY seed
            # means `χ_e` vanished on the Levi `L_m` — i.e. `e` is not
            # `L_m`-dominant, so this is not the NORMALIZED representative of a
            # label.  It usually still names a perfectly good line: labels are
            # `W`-orbits of pairs, and `fold` transports `(m, e)` to the
            # representative this solver wants (at SU(3), `(0, α₁) ↦ (0, θ)`,
            # the adjoint character).  Say that, rather than reporting a support
            # mismatch downstream: the two failures look identical there and
            # mean completely different things.
            raise ValueError(
                f"{datum.name}: (m, e) = ({m}, {e}) is not the normalized "
                f"representative of a label — the leading orbit is empty "
                f"because the Levi character χ_e vanishes, i.e. e is not "
                f"L_m-dominant (datum.is_dominant(e) = "
                f"{datum.is_dominant(e)}).  This solver wants (m "
                f"cochar-dominant, e Levi-dominant); `PureGAbeKAlgebra.fold(m, "
                f"e)` transports an arbitrary pair of the W-orbit there, and "
                f"`chart` applies it for you.")
    else:
        seed_f = {tuple(a): f for a, f in seed_f.items()}
    if sorted(seed_f) != sorted(extremal):
        raise RuntimeError(
            f"seed support {sorted(seed_f)} != extremal {sorted(extremal)}")

    psi = {n: W.dressing_psi(datum, n).simplify() for n in support}
    d_seed = {a: (seed_f[a].q_shift(a) * psi[a]).simplify() for a in extremal}
    cor = {tuple(al): coroot_of(datum, al) for al in datum.positive_roots()}

    def partner(n, al, k):
        t = datum.shift_pairing(n, al) + (-k // 2)
        c = cor[tuple(al)]
        return tuple(n[i] - t * c[i] for i in range(d))

    def _ratio(diff, c):
        t = None
        for i in range(d):
            if c[i] == 0:
                if diff[i]:
                    return None
                continue
            if diff[i] % c[i]:
                return None
            ti = diff[i] // c[i]
            if t is None:
                t = ti
            elif t != ti:
                return None
        return t

    # `K_d` is consulted from four places — the seed check, `K_f`, the wall-pair
    # loop, and `restricted_den` once per (cell, wall) — and is a pure function
    # of `n`, so memoize it (ported from; measured a large share of the
    # rank-3 win).
    _kd_cache: dict = {}
    _kf_cache: dict = {}
    _rd_cache: dict = {}

    def K_d(n):
        got = _kd_cache.get(n)
        if got is not None:
            return got
        out = set()
        for al in datum.positive_roots():
            for p in support:
                if p == n:
                    continue
                diff = tuple(n[i] - p[i] for i in range(d))
                t = _ratio(diff, cor[tuple(al)])
                if t is None:
                    continue
                # `⟨n, α⟩` is integral on `P^∨` but Fraction-TYPED for a cell of a
                # non-simply-connected form, and `k` ends up as a `range()` bound
                # via `S_of`/`T_of` in the ansatz below — so normalise here, at the
                # source, rather than at each consumer
                k = _as_int(-2 * (t - W._root_pairing_count(datum, al, n)),
                            datum, n, al)
                if partner(n, al, k) == p:
                    out.add((tuple(al), k))
        res = sorted(out)
        _kd_cache[n] = res
        return res

    def K_f(n):
        got = _kf_cache.get(n)
        if got is not None:
            return got
        P = set(psi[n].den)
        res = sorted((al, _as_int(k - W._root_pairing_count(datum, al, n),
                                  datum, n, al))
                     for (al, k) in K_d(n) if (al, k) not in P)
        _kf_cache[n] = res
        return res

    for a in extremal:              # R3 + the K_f derivation, checked on the seed
        if enlarged:
            # beyond the hull the seed meets partners on walls where it has no
            # pole: its walls are a subset of the predicted ones (docstring)
            if not set(d_seed[a].den) <= set(K_d(a)):
                raise RuntimeError(f"R3 wall prediction failed at {a}")
        elif sorted(K_d(a)) != sorted(d_seed[a].den):
            raise RuntimeError(f"R3 wall prediction failed at {a}")
    if enlarged:
        for n in interior:
            if not set(psi[n].den) <= set(K_d(n)):
                raise RuntimeError(
                    f"a pole of ψ at {n} has no residue partner in the support "
                    "override — take the override convex (docstring)")

    # The seed numerators over the FULL predicted denominator `K_d(a)`: with the
    # hull they are the seed's own numerators; beyond it, times the factors
    # `(1 − 𝖖^k v^α)` of the walls the seed has no pole on.
    seed_num = {}
    for a in extremal:
        num = d_seed[a].num
        if enlarged:
            for (al2, k2) in K_d(a):
                if (al2, k2) not in d_seed[a].den:
                    num = num * TorusLaurent(datum, {
                        (0,) * d: LaurentPoly.one(),
                        tuple(al2): LaurentPoly.zero() - LaurentPoly.q(k2)})
        seed_num[a] = num

    # --- Weyl covariance: unknowns on orbit representatives ------------------
    orbit_of, reps = {}, []
    iset = set(interior)
    if weyl_cov:
        for n in interior:
            if n in orbit_of:
                continue
            reps.append(n)
            for w in datum.weyl_elements():
                wn = tuple(datum.act_cochar(w, n))
                if wn in iset and wn not in orbit_of:
                    orbit_of[wn] = (n, w)
    else:
        wid = _identity_weyl(datum)
        reps = list(interior)
        orbit_of = {n: (n, wid) for n in interior}

    # --- the ansatz: box points x palindromic 𝖖-blocks, integer unknowns ----
    sym_basis, S_of, T_of, idx, off = {}, {}, {}, {}, 0
    for n in reps:
        kf = K_f(n)
        den: dict = {}
        for key in kf:
            den[key] = den.get(key, 0) + 1
        S_of[n] = sum(k for (_al, k) in kf if k > 0)
        T_of[n] = max(S_of[n] - 1, 0) + q_extra
        stab = ([w for w in datum.weyl_elements()
                 if tuple(datum.act_cochar(w, n)) == n]
                if weyl_cov else [_identity_weyl(datum)])
        made, seen = [], []
        for lam in box_points(datum, e, kf, pad, anchors=anchors):
            base = TorusRational(
                datum, TorusLaurent(datum, {lam: LaurentPoly.one()}), den)
            imgs = []
            for w in stab:              # orbit sum over DISTINCT images
                im = base.weyl_act(w)
                if im.den != den:
                    raise RuntimeError(f"Stab moved the denominator at {n}")
                if not any((im.num - prev.num).is_zero() for prev in imgs):
                    imgs.append(im)
            acc = TorusLaurent.zero(datum)
            for im in imgs:
                acc = acc + im.num
            if acc.is_zero() or any((acc - prev).is_zero() for prev in seen):
                continue
            seen.append(acc)
            made.append(TorusRational(datum, acc, den))
        sym_basis[n] = made
        if not made:
            raise RuntimeError(f"empty ansatz at {n}")

    if verbose:
        print(f"\n=== {datum.name}  m={m}, e={e}  pad={pad} ===")
        print(f"  support {len(support)} (extremal {len(extremal)}, "
              f"interior {len(interior)}; {len(reps)} orbit reps)", flush=True)

    B = {}
    for n in interior:
        rep, w = orbit_of[n]
        for j, sym in enumerate(sym_basis[rep]):
            B[(n, j)] = (sym.weyl_act(w).q_shift(n) * psi[n])

    def restricted_den(n, al, k):
        key = (n, tuple(al), k)
        got = _rd_cache.get(key)
        if got is not None:
            return got
        acc = TorusLaurent.one(datum)
        for (al2, k2) in K_d(n):
            if (al2, k2) == (tuple(al), k):
                continue
            acc = acc * TorusLaurent(datum, {
                (0,) * d: LaurentPoly.one(),
                tuple(al2): LaurentPoly.zero() - LaurentPoly.q(k2)})
        _rd_cache[key] = acc
        return acc

    # --- (★): symbolic rows over Z[𝖖^±], expanded per 𝖖-degree on demand ---
    sym_rows, checks = [], 0

    def expand(sym_row, const):
        """`Σ_col P_col·x_col + const = 0` with `x_col = Σ_t a_t(𝖖^t+𝖖^{−t})`:
        the monomial `𝖖^{dg}` of `P_col` contributes to the `𝖖^{dg±t}` equations.
        Iterating over the NONZERO coefficients is what makes rank 3
        affordable."""
        by_g: dict = {}
        for (rep, j), lp in sym_row.items():
            T = T_of[rep]
            # `idx[(rep, j, t)]` does NOT depend on `dg`, so hoist it out of the
            # coefficient loop: inside, it rebuilt and rehashed the same tuple key
            # once per 𝖖-degree per `t`.  Bit-identical — same columns, same order.
            # `t = 0` is split off rather than tested inside the loop: it is the
            # only `t` contributing a single equation, so keeping it in the list
            # cost a branch AND a tuple allocation — `(dg,)` or `(dg±t)` — on every
            # one of the innermost iterations.  Order is preserved exactly (`t=0`
            # first, then `dg+t` before `dg−t`), so the dicts are built in the same
            # sequence and the result is bit-identical.
            col0 = idx[(rep, j, 0)]
            rest = [(t, idx[(rep, j, t)]) for t in range(1, T + 1)]
            for dg, c in lp._coeffs.items():
                if not c:
                    continue
                # `get`-then-assign rather than `setdefault(g, {})`: the latter
                # allocates a fresh dict on EVERY iteration, hit or miss.
                cell = by_g.get(dg)
                if cell is None:
                    cell = by_g[dg] = {}
                cell[col0] = cell.get(col0, 0) + c
                for t, col in rest:
                    g = dg + t
                    cell = by_g.get(g)
                    if cell is None:
                        cell = by_g[g] = {}
                    cell[col] = cell.get(col, 0) + c
                    g = dg - t
                    cell = by_g.get(g)
                    if cell is None:
                        cell = by_g[g] = {}
                    cell[col] = cell.get(col, 0) + c
        for g, cst in const._coeffs.items():
            if cst:
                by_g.setdefault(g, {})
        for g in sorted(by_g):
            row = {k2: v2 for k2, v2 in by_g[g].items() if v2}
            b = -const._coeffs.get(g, 0)
            if row:
                yield row, b
            elif b:
                raise RuntimeError("seed inconsistency")

    seen_pairs = set()
    sset, eset = set(support), set(extremal)
    dropped_walls = []
    for n in support:
        for (al, k) in K_d(n):
            p = partner(n, al, k)
            if p not in sset or p == n:
                continue
            if admits_e is not None and not wall_is_probed(
                    datum, al, k, e, admits_e, pad):
                # (★) for the form does not see this wall: every admitted χ_e
                # vanishes on it, so `Res·χ_e ≡ 0` regardless of the residue.
                dropped_walls.append((tuple(al), k))
                continue
            key = (tuple(al), k, tuple(sorted([n, p])))
            if key in seen_pairs:
                continue
            seen_pairs.add(key)
            Dn, Dp = restricted_den(n, al, k), restricted_den(p, al, k)
            comps, const_comps = {}, {}
            for who, Dother in ((n, Dp), (p, Dn)):
                if who in eset:
                    prod = seed_num[who] * Dother
                    for cc, comp in wall_restrict(prod, al, k, d).items():
                        tgt = const_comps.setdefault(cc, {})
                        for r, v in comp.items():
                            tgt[r] = tgt.get(r, LaurentPoly.zero()) + v
                else:
                    rep_w = orbit_of[who][0]
                    for j in range(len(sym_basis[rep_w])):
                        prod = B[(who, j)].num * Dother
                        for cc, comp in wall_restrict(prod, al, k, d).items():
                            tgt = comps.setdefault(cc, {})
                            for r, v in comp.items():
                                cell = tgt.setdefault(r, {})
                                kk = (rep_w, j)
                                cell[kk] = cell.get(kk, LaurentPoly.zero()) + v
            for cc in sorted(set(comps) | set(const_comps)):
                rowmap = comps.get(cc, {})
                cmap = const_comps.get(cc, {})
                for r in sorted(set(rowmap) | set(cmap)):
                    sr = rowmap.get(r, {})
                    cst = cmap.get(r, LaurentPoly.zero())
                    if not sr:
                        checks += 1
                        if not cst.is_zero():
                            raise RuntimeError(
                                f"seed inconsistency at wall {(al, k)}, "
                                f"pair {n},{p}, class {cc}, weight {r}")
                        continue
                    sym_rows.append((sr, cst))

    # --- the 𝖖-window, DERIVED from the equations, not guessed --------------
    # An unknown `a_{rep,j,t}` reaches 𝖖-degree `dg ± t`.  A seed constant at a
    # degree NO unknown can reach makes a row look inconsistent when the window
    # is merely too narrow — exactly how Sp(6) failed with a guessed window.
    need = {n: 0 for n in reps}
    for sr, cst in sym_rows:
        if not cst._coeffs:
            continue
        for g in cst._coeffs:
            best, who = None, None
            for (rep, j), lp in sr.items():
                for dg in lp._coeffs:
                    dist = abs(g - dg)
                    if best is None or dist < best:
                        best, who = dist, rep
            if who is not None and best > need[who]:
                need[who] = best
    for n in reps:
        T_of[n] = max(T_of[n], need[n])

    for n in reps:
        for j in range(len(sym_basis[n])):
            for t in range(0, T_of[n] + 1):
                idx[(n, j, t)] = off
                off += 1
    nvars = off
    if stats is not None:
        stats["nvars"] = nvars
        stats["cols"] = {n: [idx[(n, j, t)] for j in range(len(sym_basis[n]))
                             for t in range(0, T_of[n] + 1)] for n in reps}
        stats["rep_of"] = {n: orbit_of[n][0] for n in interior}

    # --- O(𝖖): the ACTUAL condition on a_n(v) = f_n -------------------------
    oq_rows = []
    for n in reps:
        den = sym_basis[n][0].den
        ser = inv_den_series(datum, den, T_of[n])
        acc: dict = {}
        for j, sym in enumerate(sym_basis[n]):
            for wt, lp in sym.num.terms.items():
                for qd0, c0 in lp._coeffs.items():
                    for (dq, dw), c1 in ser.items():
                        base_q = qd0 + dq
                        weight = tuple(wt[i] + dw[i] for i in range(d))
                        for t in range(0, T_of[n] + 1):
                            for sgn in ((1,) if t == 0 else (1, -1)):
                                g = base_q + sgn * t
                                if g > 0:
                                    continue
                                col = idx[(n, j, t)]
                                cell = acc.setdefault((g, weight), {})
                                cell[col] = cell.get(col, 0) + c0 * c1
        rhs: dict = {}
        off_n = None if oq_offset is None else oq_offset.get(n)
        if off_n is not None and not off_n.is_zero():
            off_n = off_n.simplify()
            off_num = off_n.num
            if off_n.den != den:
                # beyond the hull: the offset's walls a subset of the ansatz's,
                # taken over the full denominator like the seed (docstring)
                missing = {w: c - off_n.den.get(w, 0) for w, c in den.items()}
                if (not enlarged or any(c < 0 for c in missing.values())
                        or not set(off_n.den) <= set(den)):
                    raise RuntimeError(
                        f"oq_offset at {n} has a different denominator than the "
                        "ansatz — the offset must live on the same cell")
                for (al2, k2), c in missing.items():
                    for _ in range(c):
                        off_num = off_num * TorusLaurent(datum, {
                            (0,) * d: LaurentPoly.one(),
                            tuple(al2): LaurentPoly.zero() - LaurentPoly.q(k2)})
            for wt, lp in off_num.terms.items():
                for qd0, c0 in lp._coeffs.items():
                    if not c0:
                        continue
                    for (dq, dw), c1 in ser.items():
                        if not c1:
                            continue
                        g = qd0 + dq
                        if g > 0:
                            continue
                        weight = tuple(wt[i] + dw[i] for i in range(d))
                        rhs[(g, weight)] = rhs.get((g, weight), 0) + c0 * c1
        for key in sorted(set(acc) | set(rhs)):
            row = {c: v for c, v in acc.get(key, {}).items() if v}
            b = rhs.get(key, 0)
            if row or b:
                oq_rows.append((row, b))

    def all_equations():
        """The whole system, streamed: `O(𝖖)` first (those rows are sparse and
        mostly kill high-𝖖 unknowns outright, so the (★) rows that follow
        collapse against far fewer live columns), then (★) per 𝖖-degree."""
        yield from oq_rows
        for sr, cst in sym_rows:
            yield from expand(sr, cst)

    if audit is not None:
        return _audit_candidate(datum, audit, reps, sym_basis, T_of, idx,
                                nvars, all_equations, oq_rows)

    if verbose:
        print(f"  unknowns {nvars}; (★) rows {len(sym_rows)} + O(𝖖) rows "
              f"{len(oq_rows)} (+{checks} seed checks)", flush=True)

    # ONE solver path.  There used to be a second, `solve_streaming_numpy`,
    # dispatched on `_HAVE_NUMPY and nvars >= 200` and documented as a "blocked
    # dense int64" accelerator.  It was removed because
    # it was not one: `numpy` was imported to set the dispatch flag and then
    # never called, so the "accelerator" ran the SAME `_sparse_eliminate` with an
    # extra 256-row buffer — measured 21.0 s vs 20.6 s at `G₂ (1,0)`, i.e.
    # strictly slower, which is also the real explanation of the earlier A/B
    # (it was never dense-vs-sparse; both paths were sparse).
    #
    # It also carried a genuine defect worth remembering: the retry below read
    # `if status != "unique" and not use_np`, so merely having numpy importable
    # SKIPPED the unlucky-prime retry at `nvars >= 200` — meaning whether a
    # canonical built or honest-failed could depend on whether a third-party
    # library happened to be installed.  With one path the retry is
    # unconditional and that asymmetry cannot recur.
    # Materialize + dedup ONCE: the stream is 75-88% duplicates and was being
    # consumed twice (mod-p solve, then exact verification over Z).  See
    # `dedup_rows`.
    eqs = dedup_rows(all_equations())
    if SHORTEST_ROW_FIRST:
        eqs = sort_rows_shortest_first(eqs)
    _out = {} if stats is not None else None
    status, sol, _seen = solve_streaming(iter(eqs), nvars, out=_out)
    if status != "unique":
        # An UNLUCKY prime — a rank drop, or a spurious `0 = b` — is the only way
        # the small search prime can differ from the rational answer, so retry
        # once against the big prime before believing a non-unique verdict.
        # Nothing rests on either prime: the lift is verified exactly over `Z`.
        _out = {} if stats is not None else None
        status_big, sol_big, _s2 = solve_streaming(
            iter(eqs), nvars, prime=_PRIME_BIG, out=_out)
        if status_big == "unique":
            status, sol = status_big, sol_big
        else:
            status = status_big
    if stats is not None:
        stats["status"] = status
        stats["pivots"] = _out.get("pivots", set())
    if status != "unique":
        return status, None, support, interior, K_f

    bad = 0
    for row, b in eqs:                  # EXACT verification over Z
        if sum(c * sol[j] for j, c in row.items()) != b:
            bad += 1
    if bad:
        return "inconsistent", None, support, interior, K_f

    if not T_of:
        # NO INTERIOR CELLS — nothing to bubble, so the system is empty and the
        # element is the leading orbit alone.  That is a legitimate verdict, not a
        # failure: `solve_canonical` still assembles the orbit and still applies W1
        # and (★) to it, which is the whole guard in this case.
        #
        # This path was unreachable in the even sector (a minuscule `m` is routed to
        # the `minuscule` route before it ever reaches the solve, and every
        # non-minuscule `m` bubbles), and it first came up at the ODD-height charges,
        # where the minimal ones — SO(3) `ω^∨`, SO(5) `(1,½)`, Sp(4)/Z₂ `(½,½)`,
        # PSU(4) `ω_1^∨`/`ω_3^∨` — have a bare Weyl orbit as their whole support.
        # It used to raise `ValueError: max() arg is an empty sequence` from the
        # line below.
        return "unique", {}, support, interior, K_f
    qpal = {t: (LaurentPoly.q(t) + LaurentPoly.q(-t)) if t else LaurentPoly.one()
            for t in range(0, max(T_of.values()) + 1)}
    Ff = {}
    for n in interior:
        rep, w = orbit_of[n]
        acc = TorusRational.zero(datum)
        for j, sym in enumerate(sym_basis[rep]):
            c = LaurentPoly.zero()
            for t in range(0, T_of[rep] + 1):
                a = sol[idx[(rep, j, t)]]
                if a:
                    c = c + qpal[t] * a
            if c.is_zero():
                continue
            acc = acc + sym.weyl_act(w) * TorusRational.from_scalar(datum, c)
        Ff[n] = acc.simplify()
    if verbose:
        print(f"  unique; {len(interior)} bubbling cells, verified over Z",
              flush=True)
    return "unique", Ff, support, interior, K_f


def build_element(datum, seed_f, Ff):
    """Assemble the `WRQTorus` element from the extremal seed + solved cells."""
    f = dict(seed_f)
    f.update(Ff)
    return W.WRQTorus(datum, f)


def solve_canonical(datum, m, e, pad=1, certify_box=True, verbose=False):
    """`L_{m,e}` on `WRQTorus(datum)` from (★) + bar + `O(𝖖)` — **the guarded
    entry point**, and the only one production code should call.

    The solve is licensed only because of the guard, so the guard is applied
    here and a failure raises `StarGuardFailure` rather than returning a
    candidate:

      1. the system must be **unique** and verified exactly over `Z`;
      2. `W1` (bar): every residual `𝖖`-palindromic;
      3. (★): the difference operator preserves `Λ = R(G)`;
      4. the **box certificate** (`certify_box`): re-solving one pad wider
         returns the same element, so the `v`-window bounded without selecting.

    `certify_box` is the expensive half (it re-solves the whole system); it
    defaults on and callers that have already certified a label may turn it off.
    Note the W2 leading-orbit half of the KL acceptance is *not* checked here —
    that is `AbeKAlgebra.certify_canonical`'s job on the finished chart, and the
    realisation asserts it against its own label map."""
    m, e = tuple(m), tuple(e)
    status, Ff, _support, interior, _K_f = joint_solve(
        datum, m, e, pad=pad, verbose=verbose)
    if status != "unique":
        raise StarGuardFailure(
            f"{datum.name}: L_{{{m},{e}}} not pinned by (★)+bar+O(𝖖) "
            f"(status: {status})")
    seed_f = {tuple(a): f for a, f in
              W.leading_orbit(datum, m, e).residuals().items()}
    x = build_element(datum, seed_f, Ff)

    if not x.well_formed_w1():
        raise StarGuardFailure(f"{datum.name}: L_{{{m},{e}}} fails W1 (bar)")
    ok, report = criterion(x)
    if not ok:
        raise StarGuardFailure(
            f"{datum.name}: L_{{{m},{e}}} fails (★): {report[:3]}")
    if certify_box:
        st2, Ff2, _s2, _i2, _k2 = joint_solve(datum, m, e, pad=pad + 1,
                                              verbose=False)
        if st2 != "unique" or not all(
                (Ff[n] - Ff2[n]).simplify().is_zero() for n in interior):
            raise StarGuardFailure(
                f"{datum.name}: L_{{{m},{e}}} fails the box certificate at "
                f"pad={pad + 1} ({st2}) — the window may be selecting")
    return x



def _oq_holds(datum, f) -> bool:
    """`val_𝖖(f) ≥ 1` — exactly, with a certified truncation bound.

    `f = num/den` is expanded as a `𝖖`-series and every coefficient of `𝖖^{≤0}`
    must vanish.  The bound is provable rather than guessed: every factor of
    `inv_den_series` has NON-NEGATIVE `𝖖`-valuation (`k > 0` starts at 0, `k < 0`
    at `|k| ≥ 1`), so a term dropped by truncating at `order` has `𝖖`-degree
    `qd₀ + dq > qd₀ + order`; taking `order = max(0, −min qd₀)` makes that
    `> 0`, i.e. outside the window being tested.  So no dropped term can
    contribute to a coefficient this function reads — the design notes rule about
    tracking the per-series exactness bound, discharged rather than assumed."""
    f = f.simplify()
    if f.is_zero():
        return True
    d = datum.dim
    qmin = min(min(lp._coeffs) for lp in f.num.terms.values())
    ser = inv_den_series(datum, f.den, max(0, -qmin))
    acc: dict = {}
    for wt, lp in f.num.terms.items():
        for qd0, c0 in lp._coeffs.items():
            for (dq, dw), c1 in ser.items():
                g = qd0 + dq
                if g > 0:
                    continue
                key = (g, tuple(wt[i] + dw[i] for i in range(d)))
                acc[key] = acc.get(key, 0) + c0 * c1
    return not any(acc.values())


def verify_axioms(datum, m, e, x) -> dict:
    """Run the axioms of the `L_{m,e}` construction against a FINISHED element.

    `{condition: (ok, detail)}` over the five conditions `kalgebra.md` lists
    ("The `L_{m,e}` construction — the axioms, and the single route"):

    | key | condition |
    |---|---|
    | `bar (W1)` | every residual `𝖖`-palindromic |
    | `seed (W2)` | the `𝖖`-extreme slice is the single leading Weyl orbit of `(m, e)`, multiplicity 1 |
    | `support` | the magnetic support lies in `conv(W·m) ∩ (m + Q^∨)` |
    | `O(𝖖)` | `val_𝖖 f_n ≥ 1` at every cell OFF the leading orbit |
    | `(★)` | the element preserves `Λ = R(G)` |

    Why this exists separately from `solve_canonical`'s internal guard: the
    guard runs on what the solver just built, whereas this runs on **anything** —
    in particular on the retired constructive routes' output, which is the only
    independent construction of these elements.  Checking a build against the
    axioms is then a real test rather than a restatement of how it was made.

    Note what is *not* claimed: passing this is not a proof that the label is
    pinned.  Uniqueness is a property of the SYSTEM (`joint_solve`), not of a
    finished element, and it is the solver's own first guard."""
    m, e = tuple(m), tuple(e)
    out = {}
    out["bar (W1)"] = (bool(x.well_formed_w1()), "")

    q_ext = x.recognize_q_extreme(False)
    out["seed (W2)"] = (q_ext == {(m, e): 1}, f"q-extreme slice {q_ext}")

    sup = set(tuple(p) for p in tropical_support(datum, m))
    stray = sorted(n for n, f in x.residuals().items()
                   if not f.simplify().is_zero() and tuple(n) not in sup)
    out["support"] = (not stray, f"cells outside conv(W·m): {stray}")

    orbit = {tuple(datum.act_cochar(w, m)) for w in datum.weyl_elements()}
    bad = sorted(n for n, f in x.residuals().items()
                 if tuple(n) not in orbit and not _oq_holds(datum, f))
    out["O(𝖖)"] = (not bad, f"val_𝖖 = 0 at {bad}")

    ok, report = criterion(x)
    out["(★)"] = (bool(ok), f"{report[:2]}" if not ok else "")
    return out





# ===========================================================================
#  Analytic structure of the L_{m,e} cone  (2026-07-27)
# ===========================================================================
#  Two exact laws, both MEASURED across `SU(2)`, `SU(3)`, `Spin(5)`, `Sp(2)`
#  and `G₂`, that turn part of the (★)-solved data into closed form:
#
#  (i)  the `e ↦ e + k·m̄` symmetry — a monomial twist of the
#       torus that carries whole cones of dressed lines for FREE, no solve;
#  (ii) the one-step bubbling law — a closed form for the cells one positive
#       coroot below the top orbit.
#
#  Both are recorded in the design notes §7.
# ---------------------------------------------------------------------------
def length_multipliers(datum):
    """`(L/d_i)` per simple root, where `d_i ∝ (α_i, α_i)` is the standard
    symmetrizer of the Cartan matrix (`d_i C_ij = d_j C_ji`) and `L = lcm(d_i)`.

    Short roots get the LARGER multiplier.  This is what makes
    `cochar_to_weight` Weyl-equivariant on a non-simply-laced datum; with the
    naive `α_i^∨ ↦ α_i` the twist below breaks `W`-symmetry outright and
    `_levi_decompose` rejects the result (measured at `Spin(5)`, `Sp(2)`, `G₂`).
    Simply-laced data give all-ones and the correction is invisible — which is
    exactly why it is easy to miss."""
    n, d = len(datum.simple_roots), datum.dim
    C = [[sum(datum.simple_roots[j][t] * datum.simple_coroots[i][t]
              for t in range(d)) for j in range(n)] for i in range(n)]
    dd = [Fraction(1)] * n
    seen, stack = {0}, [0]
    while stack:
        i = stack.pop()
        for j in range(n):
            if j in seen or C[i][j] == 0:
                continue
            dd[j] = dd[i] * C[i][j] / C[j][i]          # d_i C_ij = d_j C_ji
            seen.add(j)
            stack.append(j)
    den = 1
    for x in dd:
        den = den * x.denominator // _math_gcd(den, x.denominator)
    ints = [int(x * den) for x in dd]
    lcm = 1
    for x in ints:
        lcm = lcm * x // _math_gcd(lcm, x)
    return [lcm // x for x in ints]


def _math_gcd(a, b):
    while b:
        a, b = b, a % b
    return abs(a)


def _coroot_coords(datum, p):
    """Solve `p = Σ cᵢ αᵢ^∨` exactly.

    The cocharacter coordinates are NOT the coroot basis at every datum —
    `sp_n`'s `simple_coroots` are not the unit vectors — so this must be solved,
    not read off.  (Reading it off is a silent wrong answer at `Sp(n)` only,
    which is the sort of thing that passes every simply-laced test.)"""
    n, d = len(datum.simple_coroots), datum.dim
    A = [[Fraction(datum.simple_coroots[i][r]) for i in range(n)]
         + [Fraction(p[r])] for r in range(d)]
    piv, r = [], 0
    for c in range(n):
        k = next((i for i in range(r, d) if A[i][c] != 0), None)
        if k is None:
            continue
        A[r], A[k] = A[k], A[r]
        inv = Fraction(1) / A[r][c]
        A[r] = [x * inv for x in A[r]]
        for i in range(d):
            if i != r and A[i][c] != 0:
                f = A[i][c]
                A[i] = [x - f * y for x, y in zip(A[i], A[r])]
        piv.append(c)
        r += 1
    out = [Fraction(0)] * n
    for i, c in enumerate(piv):
        out[c] = A[i][n]
    # consistency: the solution must reproduce p (else p is off the coroot span)
    for rr in range(d):
        if sum(out[i] * datum.simple_coroots[i][rr] for i in range(n)) != p[rr]:
            raise NotImplementedError(
                f"cochar_to_weight: {tuple(p)} is not in the coroot span of "
                f"{datum.name} (a central-torus direction has no Weyl-equivariant "
                f"image in the weight lattice)")
    return out


def cochar_to_weight(datum, m):
    """`m̄` — the Weyl-equivariant image of the cocharacter `m` in the weight
    lattice, `αᵢ^∨ ↦ (L/dᵢ)·αᵢ` (`length_multipliers`).

    This is the identification induced by the invariant form, normalized to the
    smallest one landing in the lattice.  Raises `NotImplementedError` on a
    central-torus direction, which has no such image."""
    c = _coroot_coords(datum, tuple(m))
    mult = length_multipliers(datum)
    vals = [sum(c[i] * mult[i] * datum.simple_roots[i][j]
                for i in range(len(datum.simple_roots)))
            for j in range(datum.dim)]
    out = []
    for x in vals:
        if x.denominator != 1:              # pragma: no cover - lattice guard
            raise NotImplementedError(
                f"cochar_to_weight: {tuple(m)} ↦ non-integral {vals}")
        out.append(int(x))
    return tuple(out)


def theta_twist(x, k: int):
    """`T^k : f_p ↦ v^{k·p̄}·f_p` — the monomial twist of the `WRQTorus`.

    **MEASURED (2026-07-27): `T^k` carries the canonical `L_{m,e}` to the
    canonical `L_{m, e + k·m̄}`.**  Certified at `SU(2)`, `SU(3)` (regular `m`
    and `m` on a wall), `Spin(5)`, `Sp(2)` and `G₂`, for `k = 1, 2`: the image
    passes W1 (bar), passes (★), and `well_formed()` returns exactly
    `(m, e + k·m̄)` — 20/20.

    This is the `e → e + k m` symmetry of the construction.
    Its practical content: the cones `{L_{m, k·m̄}}` are `T^k`-images of the
    `{L_{m,0}}` cone, so their generators are the twisted cone generators and
    **cost no solve at all**.

    Note the twist is *not* a monomial cell-by-cell in the naive sense: at a
    cell `p` whose stabilizer `W_p` is nontrivial the resulting residual carries
    `|W_p|` terms — the Levi character of `k·p̄` — because the dressing label at
    a singular `p` is an irrep of the Levi, not a character of the torus.  That
    is automatic here; `f_p ↦ v^{k·p̄} f_p` produces it."""
    datum = x.datum
    out = {}
    for p, f in x.residuals().items():
        w = cochar_to_weight(datum, p)
        mono = TorusRational.from_laurent(
            TorusLaurent.monomial(datum, tuple(k * c for c in w)))
        out[p] = (f * mono).simplify()
    return W.WRQTorus(datum, out)


def _as_int(v, datum, n, alpha) -> int:
    """A wall exponent as a Python `int`, honest-failing if it genuinely is not one.

    The wall keys `(α, k)` become `range()` bounds in `joint_solve`'s ansatz (via
    `S_of` / `T_of`), so a `Fraction`-typed `k` — which is what a cell of a
    **non-simply-connected** global form produces, `⟨n, α⟩` being integral in value
    but fractional in type — breaks the solve on type alone.  Every cell in the
    support of such an element lies in `m + Q^∨ ⊂ P^∨`, so the value really is an
    integer there and this is sound; a non-integral one means the cell is outside
    `P^∨`, where the wall structure has no meaning."""
    iv = int(v)
    if iv != v:
        raise NotImplementedError(
            f"{datum.name}: wall exponent {v} at cell {tuple(n)}, root "
            f"{tuple(alpha)} is not an integer — the cell is outside the coweight "
            f"lattice P^∨, so its affine-reflection wall structure is undefined.")
    return iv


def _q_bracket(n: int) -> LaurentPoly:
    """`[n]_𝖖 = 𝖖^{-(n-1)} + 𝖖^{-(n-3)} + … + 𝖖^{n-1}` — the balanced 𝖖-integer
    (bar-invariant, as it must be for a residual of a bar-invariant element)."""
    return LaurentPoly({-(n - 1) + 2 * i: 1 for i in range(n)})


def one_step_residual(datum, m, alpha):
    """The closed-form residual at the cell `p = m − α^∨`, one positive coroot
    below the top orbit:

        f_p  =  [n]_𝖖 · v^α / ((1 − 𝖖^{−n} v^α)(1 − 𝖖^{n} v^α)),   n = ⟨α, m⟩.

    **Exact scope, and it is a clean criterion** (2026-07-27): the formula holds
    precisely when the `W_p`-orbit of `α` is `{±α}`, where `W_p` is the
    stabilizer of the cell `p` — i.e. when `|stabilizer_root_orbit(p, α)| == 1`.

    The reason is Weyl covariance: `f_p` must be `W_p`-invariant, and `B_α` is
    automatically invariant under `α ↦ −α` (its denominator is symmetric there),
    but not under a `W_p` element carrying `α` to a *different* root.  When the
    orbit is bigger the cell involves every root in it — two roots give
    `two_root_residual`.

    Measured, with **perfect separation** across `SU(2)`, `SU(3)`, `SU(4)`,
    `Spin(5)`, `Spin(7)`, `Sp(2)`, `Sp(3)`, `G₂`: every cell with orbit size 1
    matches this formula, and every cell that does not match — `G₂` `m=(2,3)`,
    `Sp(3)` `(1,1,0)`/`(1,1,1)`, `SU(4)` `(1,2,2)`/`(2,2,1)`, `Spin(7)`
    `(2,3,2)` — has orbit size ≥ 2.

    *History, recorded because it was a real wrong turn:* this was first written
    up as "holds everywhere except `G₂`", with `G₂`'s triple bond the suspect.
    That was the wrong diagnosis — `G₂` is simply the smallest datum whose
    generator has an orbit-size-2 cell, and `Sp(3)` and `SU(4)` do it too.  An
    earlier candidate criterion ("no intermediate dominant support cell between
    `m` and `p`") was refuted by measurement before the right invariant — the
    orbit size — was found.

    `n = 1` is not a bubbling cell at all: `s_α(m) = m − ⟨α,m⟩α^∨ = m − α^∨` is
    then in the top Weyl orbit, where `f_p = 1`.  The **deepest cell** `p = 0` is
    not given by this formula either at rank ≥ 2 (several channels superpose);
    it is fixed instead by the scalar Neumann row — see
    `closed_form_undressed`."""
    # `⟨α, m⟩` through the canonical coercion: it is a `Fraction` (though integral)
    # for a cocharacter of a non-simply-connected form, and `_q_bracket` below
    # feeds it to `range()`.  Honest-fails off `P^∨`, where `[n]_𝖖` is meaningless.
    n = W._root_pairing_count(datum, tuple(alpha), tuple(m))
    if n < 2:
        raise NotImplementedError(
            f"one_step_residual: ⟨α,m⟩ = {n} < 2 — `m − α^∨` is in the top Weyl "
            f"orbit (f = 1), not a bubbling cell")
    num = TorusRational.from_laurent(
        TorusLaurent.monomial(datum, tuple(alpha), _q_bracket(n)))
    return (num * TorusRational.factor_inv(datum, alpha, -n)
                * TorusRational.factor_inv(datum, alpha, n)).simplify()


def stabilizer_root_orbit(datum, p, alpha):
    """The `W_p`-orbit of the root `α`, deduplicated modulo `α ↦ −α`, where
    `W_p ⊆ W` is the stabilizer of the cocharacter `p`.

    Its SIZE is the exact scope invariant for the closed forms of the bubbling
    cells: 1 ⇒ `one_step_residual`, 2 ⇒ `two_root_residual`, ≥ 3 ⇒ not yet
    known.  Modulo `±` because `B_α` is already invariant under `α ↦ −α`."""
    p = tuple(p)
    orb = {tuple(datum.act(w, alpha))
           for w in range(len(datum.weyl))
           if tuple(datum.act_cochar(w, p)) == p}
    seen, out = set(), []
    for g in sorted(orb):
        key = min(g, tuple(-x for x in g))
        if key in seen:
            continue
        seen.add(key)
        out.append(g)
    return out


def one_step_cells(datum, m):
    """`{p: (α, n)}` — the cells `p = m − α^∨` with `α > 0` and `n = ⟨α,m⟩ ≥ 2`,
    reached by a unique positive coroot.

    These are *candidate* cells; which closed form applies is decided by
    `len(stabilizer_root_orbit(datum, p, α))` — see `one_step_residual` (orbit 1)
    and `two_root_residual` (orbit 2)."""
    d = datum.dim
    m = tuple(m)
    out = {}
    for a in datum._positive:
        # same coercion as `one_step_residual`: `n` is handed to `two_root_residual`
        # and thence to `_q_bracket`'s `range()`, so a Fraction-valued (but integral)
        # pairing from a non-simply-connected form must not leak through
        n = W._root_pairing_count(datum, tuple(a), m)
        if n < 2:
            continue
        try:
            cv = tuple(int(x) for x in coroot_of(datum, a))
        except Exception:                   # pragma: no cover
            continue
        p = tuple(m[i] - cv[i] for i in range(d))
        if p in out:                        # two channels ⇒ not a one-step cell
            out[p] = None
        else:
            out[p] = (tuple(a), n)
    return {p: v for p, v in out.items() if v is not None}


# ===========================================================================
#  The spectral law of the undressed monopoles  (2026-07-27)
# ===========================================================================
#  MEASURED at `SU(2)`, `SU(3)`, `Spin(5)`, `Sp(2)` and `G₂`:
#
#   (1) the `L_{m,0}` COMMUTE with each other (and not with Wilson lines);
#   (2) on `R(G)` they act triangularly with the explicit diagonal
#         `L_{m,0}·χ_μ = (−1)^{⟨ρ,m⟩} 𝖖^{⟨ρ,m⟩+2⟨μ,m⟩} χ_μ + (lower)`;
#   (3) hence there is a single basis `{P_μ}` of `R(G)`, independent of `m`,
#       diagonalizing all of them — `L_{m,0} = (−1)^{⟨ρ,m⟩}𝖖^{⟨ρ,m⟩}·Λ_m`,
#       `Λ_m : P_μ ↦ 𝖖^{2⟨μ,m⟩}P_μ`;
#   (4) and therefore, since `⟨ρ,·⟩` is LINEAR and eigenvalues multiply,
#
#           L_{m,0} · L_{m',0}  =  L_{m+m',0}          EXACTLY.
#
#  (4) is the operative one: every undressed monopole is an exact monomial in
#  the cone-generator monopoles, so the licensed (★) solve is confined to the
#  finitely many cone generators and nothing else — see
#  `PureGAbeKAlgebra._monoid` and the design notes §7e.
# ---------------------------------------------------------------------------
def rho_weight(datum):
    """`ρ = ½Σ_{α>0} α`, in the ambient weight coordinates."""
    s = [0] * datum.dim
    for a in datum._positive:
        for i in range(datum.dim):
            s[i] += a[i]
    out = []
    for x in s:
        if x % 2:                               # pragma: no cover - lattice guard
            raise NotImplementedError(f"{datum.name}: ρ is not integral ({s})")
        out.append(x // 2)
    return tuple(out)


def weyl_denominator(datum):
    """`Δ = Σ_w sgn(w)·v^{wρ}`."""
    rho = rho_weight(datum)
    terms = {}
    for w in range(len(datum.weyl)):
        img = tuple(datum.act(w, rho))
        terms[img] = terms.get(img, 0) + datum.weyl[w][1]
    return TorusLaurent(datum, {k: LaurentPoly({0: v})
                                for k, v in terms.items() if v})


_SHIFTED_DENOM = {}


def shifted_weyl_denominator(datum):
    """`Δ' = ∏_{α>0}(1 − v^{−α}) = v^{−ρ}·A_ρ` — the `ρ`-FREE Weyl denominator.

    Two reasons this exists beside `weyl_denominator`, and both are why
    `char_decompose` below uses it:

    * **it needs no `ρ`.**  `weyl_denominator` builds `A_ρ = Σ_w sgn(w) v^{wρ}`
      through `rho_weight`, which *raises* `NotImplementedError` where `ρ` is not
      integral — SO(3), SO(5), Sp(4), Sp(6), …  That refusal propagated into every
      consumer, so character decomposition (and hence the Neumann module action)
      was unavailable at exactly those forms.  Here `Δ'` is a product over the
      positive roots with integral exponents at every form.
    * **it is memoized.**  The product is datum-only, and consumers call it once
      per label; rebuilding it per call walked `|W|` (or `|Φ⁺|`) each time.

    `datum.weyl_denominator()` already computes the same `{weight: int}` dict; this
    wraps it as a `TorusLaurent` and caches it."""
    key = id(datum)
    hit = _SHIFTED_DENOM.get(key)
    if hit is not None and hit[0] is datum:
        return hit[1]
    val = TorusLaurent(datum, {k: LaurentPoly({0: v})
                               for k, v in datum.weyl_denominator().items() if v})
    _SHIFTED_DENOM[key] = (datum, val)          # keep a strong ref: no id reuse
    return val


def char_decompose(datum, P, weights=None):
    """Decompose a `W`-symmetric `TorusLaurent` into irreducible characters:
    `{ν: c_ν(𝖖)}`.

    Uses the Weyl denominator rather than a peel: `P = Σ c_ν χ_ν` iff
    `P·A_ρ = Σ c_ν A_{ν+ρ}`, so `c_ν = [v^{ν+ρ}](P·A_ρ)`.  Exact and
    `O(|W|·|P|)`.  The peel in `wrq_torus._levi_decompose` is fine at small rank
    but exceeds its iteration guard on `G₂` characters, which is how this route
    was needed.

    **The `ρ` shift cancels, so it is not taken.**  Dividing both sides by `v^ρ`
    and using `A_ρ = v^ρ·Δ'` with `Δ' = ∏_{α>0}(1 − v^{−α})`,

        c_ν  =  [v^ν]( P · Δ' )

    — no `ρ` anywhere, hence no `rho_weight` and no refusal at the half-integral-`ρ`
    forms (SO(3)/SO(5)/Sp(4)/…), where the shifted form was previously the only
    obstruction.  Uniqueness of the extraction is unchanged: `ν+ρ` is strictly
    dominant, so `w(μ+ρ) = ν+ρ` forces `w = 1` and `μ = ν`.

    **`weights=None` derives the candidates from `P`'s own support** — the
    dominant `ν` occurring in `P·Δ'` — instead of scanning a supplied grid.  A
    grid is both slower and *unsound*: a character outside the box was silently
    dropped, so the decomposition came back short and the caller saw a fabricated
    zero rather than a refusal.  Pass an explicit list only to restrict the answer
    on purpose."""
    Q = P * shifted_weyl_denominator(datum)
    if weights is None:
        # `datum.is_dominant` is the datum's OWN definition (plain pairing against
        # the simple coroots); rolling the test by hand via `shift_pairing` picks up
        # the optional metric matrix and admits non-dominant weights — measured at
        # SO(5)/Sp(4), where it let `(0,2)` through.
        return {tuple(nu): c for nu, c in Q.terms.items()
                if not c.is_zero() and datum.is_dominant(nu)}
    out = {}
    for nu in weights:
        c = Q.coeff(tuple(nu))
        if c is not None and not c.is_zero():
            out[tuple(nu)] = c
    return out


def operator_row(x, mu, weights):
    """`{ν: c_ν(𝖖)}` in `x·χ_μ = Σ_ν c_ν χ_ν` — the row of `x`'s matrix on
    `R(G)` at the character `χ_μ`.

    `x·χ_μ = (x·L_{0,μ})|N]` because `L_{0,μ}|N] = χ_μ` exactly, so this is
    `neumann_row` of the product.  Raises if the result is not polynomial, which
    is precisely a violation of (★) — the element does not preserve `R(G)`."""
    datum = x.datum
    row = neumann_row(x * W.wilson(datum, mu))
    if row.den:
        raise StarGuardFailure(
            f"operator_row: x·χ_{tuple(mu)} is not in R(G) (denominator "
            f"{sorted(row.den)}) — the element violates (★)")
    return char_decompose(datum, row.num, weights)


def preserves_neumann_module(x, admits_e, weights, test_e=None):
    """**(★) for a global form** — `x` preserves

        Λ_H = span{ L_{0,e}|N] : e admitted by the form }

    Returns `(ok, report)`.

    `criterion` above is the *simply connected* statement: a wall-by-wall residue test
    on `x.datum` alone, blind to which electric charges the form actually has.  That is
    the right test when the electric lattice is all of `P`, and it is measured to be
    nearly **vacuous** at a fractional cocharacter — at `su_2` `m=(½,)` the entire wall
    set is `{((2,), 0)}`, one wall at `k = 0`, so a bare leading orbit passes it while
    the bare orbit at even `m=(1,)` correctly fails (`pole SURVIVES`).  So at a
    non-simply-connected form (★) has to be asked of the module, not of the walls.

    **`|N]` is NOT a privileged basepoint — this statement is already level-symmetric**
    (*"conceptually there is no reason to favour `|N]` to
    `|N + k CS]`"*).  The CS-shifted analogue, "preserves
    `Λ^{(k)} = span{L_{0,e'}|N + k CS]}`", adds **no new constraints** either way:
    `(a|N(k)] = I(a, v^{km}f)` and the level shift is an IDENTITY, not data
    (a probe in the source repository::test_cs_family_is_the_v_km_dressing`
    — *"the sign is FORCED, not free … a consistency check, not independent data"*), so

        L_{m,e} preserves Λ^{(k)}   ⟺   L_{m,e−km} preserves Λ^{(0)}.

    If `k` is legal for the form, `e−km` is an admitted label and that condition is already
    imposed here (automatic); if `k` is illegal, `e+km` leaves the electric lattice and
    `|N+kCS]` is not a state of the form (vacuous).  Legality is closure of the admitted
    labels under `e ↦ e + k·m̄` with `m̄ = cochar_to_weight(datum, m)` (the map `theta_twist`
    itself uses).  Measured minimal legal levels: SU(2) `1/2`, **Sp(4) `1/2`, Spin(5) `1/2`**,
    SU(N≥3) / SU(4)/Z₂ / G₂ `1`, SO(3) `2`, Sp(4)/Z₂ and SO(5) `1`, PSU(N) `N`.  So a
    half-integral level is **not** an `A₁`-only phenomenon.

    The level lattice anti-correlates with odd `⟨Σ⁺,m⟩` (8/8: every form admitting a
    half-level has no odd-height charge, every form carrying one has minimal level `≥ 1`) —
    a fact about the two lattices, since growing `Q^∨ → P^∨` is what creates an odd-height
    charge while the dual move shrinking `P → Q` coarsens the level lattice.  **Do NOT read
    that as an obstruction** (the earlier reading is retracted): odd `⟨Σ⁺,m⟩` builds and
    certifies, because the atom phase is only ever needed through the integral coboundary
    `δS̃`.  The half-level question is *decoupled* from the odd-height question.

    `admits_e(e) -> bool` is injected rather than a `LineLattice` being imported, to keep
    this module free of the per-theory realisation layer; callers pass `lines.elec_admits`.
    `weights` bounds the decomposition (as in `char_decompose`); `test_e` defaults to the
    admitted members of `weights`.

    Two ways to fail, reported separately because they mean different things:

      * `not-polynomial` — `x·χ_e` has a surviving denominator, so it is not in `R(G)` at
        all, let alone `Λ_H`.  This is the failure `operator_row` raises on.
      * `left-module` — the image is polynomial but decomposes onto a character the form
        does **not** admit, i.e. `x` maps `Λ_H` out of `Λ_H`.

    Note what is NOT a failure: a coefficient with a negative power of `𝖖`.  The scalar
    ring is `Z[𝖖^{±1}]` (standing ruling), so `𝖖⁻²` is a perfectly good coefficient.  It
    happens to be the visible symptom of the wrong element at `su_2` `m=(½,)` — the row
    is `x·χ₂ = (−𝖖⁻²+1)χ₀ + 𝖖²χ₂` against the oracle's `𝖖^k` — but that is a matter for
    orthonormality to catch, not for (★).  Do not fold it in here."""
    datum = x.datum
    if test_e is None:
        test_e = [tuple(w) for w in weights if admits_e(tuple(w))]
    ok, rep = True, []
    for mu in test_e:
        row = neumann_row(x * W.wilson(datum, tuple(mu)))
        if row.den:
            ok = False
            rep.append((tuple(mu), "not-polynomial", sorted(row.den)))
            continue
        for nu in char_decompose(datum, row.num, weights):
            if not admits_e(tuple(nu)):
                ok = False
                rep.append((tuple(mu), "left-module", tuple(nu)))
    return ok, rep


def spectral_diagonal(datum, m, mu):
    """The measured diagonal entry of `L_{m,0}` on `χ_μ`:

        `(−1)^{⟨ρ,m⟩} · 𝖖^{⟨ρ,m⟩ + 2⟨μ,m⟩}`

    where the exponent `E` is the **reduced integral atom phase**
    `E := −RootDatum.atom_phase(m)`, *not* `⟨ρ,m⟩`:

        diag(m, μ)  =  (−𝖖)^E · 𝖖^{2⟨μ,m⟩},    E = −atom_phase(m).

    At even `⟨Σ⁺,m⟩` the two agree exactly (`−atom_phase = ⟨ρ,m⟩` there), so this
    reproduces the original law verbatim on its whole measured domain.

    **Why it is written with `atom_phase` and not `⟨ρ,m⟩`** (fixed 2026-07-29).  `⟨ρ,m⟩ = ½⟨Σ⁺,m⟩` is half-integral at odd `⟨Σ⁺,m⟩`, and
    then *both* factors leave the ring at once: `(−1)^{⟨ρ,m⟩}` is a **fourth root
    of unity** and the `𝖖`-exponent is a half power — i.e. the expression is
    literally `(−𝖖)^{⟨ρ,m⟩}`, the same square root of `−𝖖` that
    `_psi_monomial_data` materialises.  Python obliges (`(-1) ** Fraction(9,2)` is
    a `complex`), so this route used to raise
    `TypeError: int() argument must be … not 'complex'` out of `LaurentPoly` —
    which `_guarded_dispatch` does **not** treat as "route not applicable", so it
    escaped and killed `chart()` on a label the licensed (★) solve builds
    (measured at `SO(7)` `m = (1, 2, 3/2)`, `⟨Σ⁺,m⟩ = 9`, 14-cell support).

    **The substitution is MEASURED, not guessed.**  At `μ = 0` this diagonal *is*
    the Neumann-row scalar `(L_{m,0}|N]`, which `neumann_row` reads directly off a
    built element, so the solve supplies ground truth at exactly the charges the
    old formula could not express.  Read off built elements
    (a probe in the source repository):

    | form | `m` | `⟨Σ⁺,m⟩` | `(L\\|N]` | `(−𝖖)^{⟨ρ,m⟩}` | `(−𝖖)^{−atom_phase}` |
    |---|---|---|---|---|---|
    | SO(3) | `(1,)` | 1 odd | `1` | `(−𝖖)^{1/2}` ✗ | `1` ✓ |
    | SO(3) | `(3,)` | 3 odd | `−𝖖` | `(−𝖖)^{3/2}` ✗ | `−𝖖` ✓ |
    | SO(5) | `(1, ½)` | 3 odd | `−𝖖` | `(−𝖖)^{3/2}` ✗ | `−𝖖` ✓ |
    | Sp(4)/Z₂ | `(½, ½)` | 3 odd | `−𝖖` | `(−𝖖)^{3/2}` ✗ | `−𝖖` ✓ |
    | SO(3)/SO(5)/Sp(4)/Z₂/SU(3)/Spin(5) | even | even | — | ✓ | ✓ (identical) |

    and the full `μ`-dependence matches **100/100** over *dominant, admitted* `μ`
    at SO(5) (odd `h=3`, `h=7`; even `h=4`), Sp(4)/Z₂ (odd `h=3`, even `h=6`),
    Spin(5) and SU(3) (even controls) — 0 mismatches.

    ⚠ Two domain conditions the probe that found this had to learn, both of which
    make the law look violated when ignored, at **even** height just as much as
    odd — so neither is about the quotient:

      * `μ` must be **admitted by the form**.  `⟨μ,m⟩ ∈ Z` holds because the
        electric and magnetic lattices are dual; a `μ` outside the form's `Q`
        pairs half-integrally with `m ∈ P^∨` and there is no diagonal law for it
        (it is not a line operator of the theory).
      * `μ` must be **dominant**, since `χ_μ` for non-dominant `μ` is `±χ` of its
        dominant representative.

    Dropping the `rho_weight` dependency is a bonus: that helper *raises* at
    `SO(3)` (`ρ = ½Σ⁺` is not a character of the adjoint form), so this route
    could not even be evaluated there before."""
    E = -datum.atom_phase(tuple(m))
    pm = sum(mu[i] * m[i] for i in range(datum.dim))
    return LaurentPoly({E + 2 * pm: (-1) ** (E % 2)})


def two_root_residual(datum, alpha, beta, n):
    """The closed form for a bubbling cell whose `W_p`-orbit of the step root is
    the PAIR `{α, β}` (`stabilizer_root_orbit` size 2):

        f_p = [ v^γ·(1 + v^α)(1 + v^β) + [n]²·v^{α+β} ] / (D_α · D_β),
        γ = (α+β)/2,   D_δ = (1 − 𝖖^{−n}v^δ)(1 − 𝖖^{n}v^δ).

    **Verified exact** at `Sp(3)` `m = (1,1,0)`, at BOTH its orbit-size-2 cells
    (`p = (1,0,0)` and `p = (0,1,0)`, `n = 2`).  There `α`, `β` are the two long
    Levi roots and `γ = (α+β)/2` is the short one, so `γ` is itself a root.

    Honest scope: `γ = (α+β)/2` must itself be a **root**.  Two measured
    failures pin that down, and both honest-fail rather than returning a wrong
    element:

    * `G₂` `m = (2,3)`: `α+β` is the highest root `(0,1)`, whose half is not even
      in the weight lattice.  The true numerator there is a nine-term
      `W_p`-symmetric object with coefficients
      `1, [2]², [2], [2], [3]², [2], [2], [2]², 1` — of which this formula is
      presumably the `γ ∈ Φ` special case.
    * `Sp(3)` `m = (1,1,1)`, cell `(0,0,1)`: `α`, `β` are both SHORT roots and
      `γ = (α+β)/2 = −e₁` is a weight but **not a root** — and there the formula
      is measurably wrong (it produced an element failing W1 and (★)).  Requiring
      `γ ∈ Φ` is what separates it from `Sp(3)` `m = (1,1,0)`, where `α`, `β` are
      the LONG roots and `γ` is the short one.

    Recorded rather than guessed at (the design notes §7c)."""
    d = datum.dim
    alpha, beta = tuple(alpha), tuple(beta)
    s = tuple(alpha[i] + beta[i] for i in range(d))
    if any(x % 2 for x in s):
        raise NotImplementedError(
            f"two_root_residual: (α+β)/2 = {tuple(Fraction(x, 2) for x in s)} is "
            f"not in the weight lattice — the {datum.name} orbit-size-2 cell is "
            f"outside this formula's scope")
    g = tuple(x // 2 for x in s)
    if g not in set(datum._root_set):
        raise NotImplementedError(
            f"two_root_residual: γ = (α+β)/2 = {g} is a weight but NOT a root of "
            f"{datum.name} — outside this formula's measured scope (it is wrong "
            f"there: Sp(3) m=(1,1,1))")
    one = TorusRational.one(datum)

    def mono(wt, lp=None):
        return TorusRational.from_laurent(
            TorusLaurent(datum, {tuple(wt): lp or LaurentPoly({0: 1})}))

    num = (mono(g) * (one + mono(alpha)) * (one + mono(beta))
           + mono(s, _q_bracket(n) * _q_bracket(n)))
    return (num * TorusRational.factor_inv(datum, alpha, -n)
                * TorusRational.factor_inv(datum, alpha, n)
                * TorusRational.factor_inv(datum, beta, -n)
                * TorusRational.factor_inv(datum, beta, n)).simplify()


def _weyl_transport_residual(datum, w, fr):
    """`f ↦ f(w·)` on a `TorusRational` — act on the `v`-exponents of numerator
    and denominator.  This is the transport realizing the MEASURED covariance
    `f_{w·p}(v) = f_p(w⁻¹v)` (100% at every cone generator tested)."""
    num = TorusLaurent(datum, {tuple(datum.act(w, e)): lp
                               for e, lp in fr.num.terms.items()}, fr.scalar)
    den = {(tuple(datum.act(w, a)), k): mlt for (a, k), mlt in fr.den.items()}
    return TorusRational(datum, num, den)


def closed_form_undressed(datum, m):
    """`L_{m,0}` built in CLOSED FORM — no solve, no peel.

    Three ingredients, each measured (the design notes §7):

    * the top Weyl orbit `W·m` carries `f_p = 1`;
    * a bubbling cell `p = m − α^∨` carries `one_step_residual` when its
      `stabilizer_root_orbit` has size 1, `two_root_residual` when size 2, and
      is transported over `W·p` by Weyl covariance;
    * the origin carries `f_0 = (−1)^{⟨ρ,m⟩}𝖖^{⟨ρ,m⟩} − Σ_{p≠0} T_p(f_p)·ψ_p`,
      because **`L_{m,0}|N]` is a SCALAR** — the `μ = 0` row of the diagonal law,
      with nothing below `0` to correct it.

    Raises `NotImplementedError` when some dominant cell of the support is not
    covered (an orbit of size ≥ 3, or a `G₂`-type non-weight half-sum).

    ⚠ **NOT "honest-fail, never a wrong element" — that claim was measured FALSE
    and is withdrawn (2026-08-25).**  At `SU(3)` `m = (2,2)` this returns an
    element that is simply **wrong**, without raising: it fails both W1 and (★),
    and the cells where it differs from `solve_canonical` are exactly `W·(1,1)`
    together with the origin (whose value is a sum over the others).

    The mechanism, so this can be fixed rather than only avoided.
    `one_step_cells` means one **root** below `m`, not one **simple coroot**
    below.  At `m = (2,2)` the cell `m − θ^∨ = (1,1)` is therefore listed as a
    one-step cell although it lies two simple coroots down, and
    `one_step_residual` / `two_root_residual` are applied at a depth where they
    are not valid.  The coverage check below then cannot catch it: it asks
    whether every dominant cell of the support is PRESENT in `res`, and this one
    is present — carrying the wrong residual.  A correct check would ask whether
    each cell was filled by a rule valid AT THAT DEPTH.

    Consequence for callers, and the standing ruling.  This function is
    **excluded from the declared optimizations** of `PureGAbeKAlgebra`, even though it is 39–196× faster than the solve where it is
    right and reaches charges the `monoid` route cannot.  It stays reachable
    through `constructive_routes=True`, where every candidate is guarded by
    W1 + (★) and a failure falls through — i.e. where its output is COMPARED
    rather than trusted.  Never call it unguarded.

    Guard-certified (W1 + (★) + `well_formed` == the label) at: every cone
    generator of `SU(2)`, `SU(3)`, `Spin(5)`, `Sp(2)`; the adjoint (quasi-
    minuscule) generator of every datum tested INCLUDING `G₂`; and the low
    generators of `SU(4)`, `Spin(7)`, `Sp(3)`.  Those rows stand — they are
    guarded — but they are not evidence of the withdrawn claim."""
    d = datum.dim
    z = (0,) * d
    m = tuple(m)
    one = TorusRational.one(datum)
    res = {tuple(datum.act_cochar(w, m)): one for w in range(len(datum.weyl))}

    cells = one_step_cells(datum, m)
    for p, (alpha, n) in cells.items():
        if p == z:
            continue                    # the origin is fixed by the Neumann row
        orb = stabilizer_root_orbit(datum, p, alpha)
        if len(orb) == 1:
            base = one_step_residual(datum, m, alpha)
        elif len(orb) == 2:
            base = two_root_residual(datum, orb[0], orb[1], n)
        else:
            raise NotImplementedError(
                f"closed_form_undressed: cell {p} of L_{{{m},0}} has "
                f"stabilizer-root-orbit size {len(orb)} ({orb}); only 1 and 2 "
                f"have closed forms so far")
        for w in range(len(datum.weyl)):
            wp = tuple(datum.act_cochar(w, p))
            if wp in res:
                continue
            res[wp] = _weyl_transport_residual(datum, w, base).simplify()

    # every dominant cell of the support must now be accounted for
    for p in tropical_support(datum, m):
        p = tuple(p)
        if p == z or p in res:
            continue
        if datum.is_dominant_cochar(p):
            raise NotImplementedError(
                f"closed_form_undressed: dominant cell {p} of L_{{{m},0}} is "
                f"more than one coroot below m — no closed form yet")

    S = TorusRational.zero(datum)
    for p, fp in res.items():
        if p == z:
            continue
        S = S + (fp.q_shift(p) * W.dressing_psi(datum, p))
    c = spectral_diagonal(datum, m, z)
    res[z] = (TorusRational.from_laurent(TorusLaurent(datum, {z: c}))
              + (-S)).simplify()
    return W.WRQTorus(datum, res)


# ===========================================================================
#  The spectral construction: {P̄_μ} intrinsically, and the operator on R(G)
# ===========================================================================
#  `L_{m,0}` is diagonal on a basis `{P̄_μ}` of `R(G)` (the spectral law above).
#  Until now `{P̄_μ}` was extracted FROM the operator matrices, hence from the
#  (★)-solved charts — circular.  **It is not circular any more**: `{P̄_μ}` is
#  characterized intrinsically as
#
#     triangular in the characters, `P̄_μ = χ_μ + O(𝖖²)`, and
#     ORTHOGONAL for  ⟨f,g⟩ = CT_v[ f(v⁻¹)·g(v)·Δ(v) ],
#     Δ = ∏_{α∈Φ} (v^α ; 𝖖²)_∞ = ∏_{α∈Φ} ∏_{k≥0} (1 − 𝖖^{2k} v^α)
#
#  — a Gram–Schmidt entirely inside `R(G)`.  The variable is `𝖖²`, NOT `𝖖^{−2}`
# `𝖖²` is the expansion around `𝖖 = 0` matching
#  the repo's `δ + O(𝖖)` convention, and it is the direction the transcription
#  back to residuals truncates in.  See the design notes §7i.
#
#  Everything here is EXACT and dependency-free: truncated series with `Fraction`
#  coefficients, and a **truncation certificate** (recompute one order wider and
#  demand the same answer) in the spirit of `solve_canonical`'s box certificate.
#  The certificate is load-bearing, measured: at `SU(2)` with a height-10 window,
#  order 14 → certificate fails, agreement 74/81; order 30 → fails, 80/81;
#  order 40 → **passes, 81/81**.
# ---------------------------------------------------------------------------
class _Ser:
    """Truncated power series in `𝖖` with `Fraction` coefficients, `𝖖`-order ≤ N.

    Non-negative powers only — which is exactly why the `𝖖²` convention matters:
    in the `𝖖^{−2}` convention these objects would not be series at all."""

    __slots__ = ("c", "N")

    def __init__(self, c, N):
        self.c = {k: Fraction(v) for k, v in c.items() if v and 0 <= k <= N}
        self.N = N

    @classmethod
    def zero(cls, N):
        return cls({}, N)

    @classmethod
    def const(cls, v, N):
        return cls({0: Fraction(v)}, N)

    def __add__(self, o):
        d = dict(self.c)
        for k, v in o.c.items():
            d[k] = d.get(k, 0) + v
        return _Ser(d, min(self.N, o.N))

    def __neg__(self):
        return _Ser({k: -v for k, v in self.c.items()}, self.N)

    def __sub__(self, o):
        return self + (-o)

    def __mul__(self, o):
        N = min(self.N, o.N)
        d = {}
        for a, x in self.c.items():
            for b, y in o.c.items():
                if a + b <= N:
                    d[a + b] = d.get(a + b, 0) + x * y
        return _Ser(d, N)

    def is_zero(self):
        return not self.c

    def inv(self):
        a0 = self.c.get(0)
        if not a0:
            raise ZeroDivisionError("series has no constant term")
        out = {0: Fraction(1) / a0}
        for n in range(1, self.N + 1):
            out[n] = -sum(self.c.get(k, Fraction(0)) * out.get(n - k, Fraction(0))
                          for k in range(1, n + 1)) / a0
        return _Ser(out, self.N)

    def to_laurent(self, bar=False):
        """`LaurentPoly` over `Z`; `bar=True` applies `𝖖 ↦ 𝖖^{−1}`."""
        out = {}
        for k, v in self.c.items():
            if v.denominator != 1:
                raise ValueError(f"non-integral series coefficient {v} at 𝖖^{k}")
            out[-k if bar else k] = int(v)
        return LaurentPoly(out)


def _delta_measure(datum, order):
    """`Δ = ∏_{α∈Φ} (v^α ; 𝖖²)_∞`, truncated at `𝖖^order`, as `{weight: _Ser}`."""
    d = datum.dim
    D = {(0,) * d: _Ser.const(1, order)}
    for a in datum._root_set:
        for k in range(0, order // 2 + 1):
            fac = {(0,) * d: _Ser.const(1, order), tuple(a): _Ser({2 * k: -1}, order)}
            out = {}
            for wa, ca in D.items():
                for wb, cb in fac.items():
                    w = tuple(wa[i] + wb[i] for i in range(d))
                    out[w] = (out[w] + ca * cb) if w in out else ca * cb
            D = {w: c for w, c in out.items() if not c.is_zero()}
    return D


def _char_dict(datum, nu, order):
    lp = W.wilson(datum, nu).residuals()[(0,) * datum.dim].num
    return {tuple(wt): _Ser.const(sum(int(v) for v in l._coeffs.values()), order)
            for wt, l in lp.terms.items()}


def _ct_pair(datum, f, g, D, order):
    """`CT_v[ f(v^{-1})·g(v)·Δ(v) ]`."""
    d = datum.dim
    acc = {}
    for wa, ca in f.items():
        wa = tuple(-y for y in wa)
        for wb, cb in g.items():
            w = tuple(wa[i] + wb[i] for i in range(d))
            acc[w] = (acc[w] + ca * cb) if w in acc else ca * cb
    out = _Ser.zero(order)
    for wa, ca in acc.items():
        cb = D.get(tuple(-y for y in wa))
        if cb is not None:
            out = out + ca * cb
    return out


def coroot_height(datum, mu):
    """`⟨μ, Σ⁺^∨⟩` — a strictly positive functional on the dominant cone, used to
    linearly order the weights."""
    tot = 0
    for a in datum._positive:
        cv = coroot_of(datum, a)
        tot += sum(int(mu[i]) * cv[i] for i in range(datum.dim))
    return int(tot)


def dominant_weights(datum, height, span=8):
    """Dominant weights with `⟨μ, Σ⁺^∨⟩ ≤ height`, in increasing order."""
    out = []
    for e in itertools.product(range(0, span + 1), repeat=datum.dim):
        if datum.is_dominant(e) and 0 <= coroot_height(datum, e) <= height:
            out.append(tuple(e))
    return sorted(out, key=lambda mu: (coroot_height(datum, mu), mu))


def _solve_series(M, rhs, n):
    A = [row[:] + [rhs[i]] for i, row in enumerate(M)]
    for c in range(n):
        piv = next((r for r in range(c, n) if 0 in A[r][c].c), None)
        if piv is None:
            return None
        A[c], A[piv] = A[piv], A[c]
        iv = A[c][c].inv()
        A[c] = [z * iv for z in A[c]]
        for r in range(n):
            if r != c and not A[r][c].is_zero():
                f = A[r][c]
                A[r] = [A[r][k] - f * A[c][k] for k in range(n + 1)]
    return [A[i][n] for i in range(n)]


def _eigenbasis_raw(datum, height, order, span=8):
    D = _delta_measure(datum, order)
    weights = dominant_weights(datum, height, span)
    chis = {nu: _char_dict(datum, nu, order) for nu in weights}
    G = {}
    for a in weights:
        for b in weights:
            G[(a, b)] = G[(b, a)] if (b, a) in G else _ct_pair(
                datum, chis[a], chis[b], D, order)
    P = {}
    for i, mu in enumerate(weights):
        low = weights[:i]
        if not low:
            P[mu] = {mu: _Ser.const(1, order)}
            continue
        sol = _solve_series([[G[(nu, sig)] for nu in low] for sig in low],
                            [-G[(mu, sig)] for sig in low], len(low))
        if sol is None:                          # pragma: no cover
            return None, weights
        row = {mu: _Ser.const(1, order)}
        for nu, c in zip(low, sol):
            if not c.is_zero():
                row[nu] = c
        P[mu] = row
    return P, weights


_EIGENBASIS_CACHE: dict = {}


def _datum_key(datum):
    """A hashable fingerprint of a `RootDatum` (the class is not hashable).

    Name alone is not enough — two data can share a name — so the positive
    roots and simple coroots go in too."""
    return (datum.name, datum.dim,
            tuple(tuple(a) for a in datum.positive_roots()),
            tuple(tuple(c) for c in datum.simple_coroots))


def spectral_eigenbasis(datum, height, order, span=8, certify=True):
    """`({μ: {ν: LaurentPoly}}, weights)` — the basis `{P̄_μ}` of `R(G)`, built
    INTRINSICALLY: triangular in the characters and orthogonal for
    `Δ = ∏_{α∈Φ}(v^α;𝖖²)_∞`.  Coefficients lie in `Z[𝖖²]` and `P̄_μ = χ_μ + O(𝖖²)`.

    **No reference to any (★)-solved chart** — this is what makes the spectral
    description of `L_{m,0}` a construction rather than an observation.

    `certify=True` recomputes at `order + 4` and demands the same answer.  That
    guard is load-bearing, not decoration: at `SU(2)` with a height-10 window,
    order 14 gives 74/81 agreement with the solved operator and the certificate
    FAILS; order 30 gives 80/81 and still fails; order 40 passes and gives 81/81.
    Raises `StarGuardFailure` when it fails — enlarge `order`.

    **Memoized on `(datum, height, order, span, certify)` (2026-07-28).**  The
    result does not depend on `m`, but `spectral_operator_matrix` calls this on
    every charge, so building `k` monopoles at one datum used to pay for `k`
    Gram–Schmidts — and with `certify` each of those is two.  The cache is what
    makes the design notes §7m's "reused across all `m` at fixed `(G,N)`"
    true in code rather than only in principle."""
    ckey = (_datum_key(datum), height, order, span, certify)
    hit = _EIGENBASIS_CACHE.get(ckey)
    if hit is not None:
        return hit
    P, weights = _eigenbasis_raw(datum, height, order, span)
    if P is None:                                # pragma: no cover
        raise StarGuardFailure(f"{datum.name}: eigenbasis solve failed")
    if certify:
        P2, _ = _eigenbasis_raw(datum, height, order + 4, span)
        same = P2 is not None and all(
            sorted(P[mu][nu].c.items()) == sorted(P2[mu][nu].c.items())
            for mu in P for nu in P[mu])
        if not same:
            raise StarGuardFailure(
                f"{datum.name}: truncation certificate FAILED at order={order} "
                f"(height={height}) — the series are not yet exact; enlarge order")
    out = ({mu: {nu: s.to_laurent() for nu, s in row.items()}
            for mu, row in P.items()}, weights)
    _EIGENBASIS_CACHE[ckey] = out
    return out


def spectral_operator_matrix(datum, m, height, order, span=8, certify=True):
    """`{μ: {ν: LaurentPoly}}` — the matrix of `L_{m,0}` acting on `R(G)` in the
    CHARACTER basis, built from the spectral law alone:

        L_{m,0} = (−1)^{⟨ρ,m⟩}𝖖^{⟨ρ,m⟩}·Λ_m ,   Λ_m : P_μ ↦ 𝖖^{2⟨μ,m⟩}P_μ

    i.e. `C = T⁻¹ · diag(λ) · T` with `T` the (unbarred) eigenbasis transition.

    **This needs no (★) solve and no chart**, so it produces the operator for
    EVERY dominant `m` at EVERY `G` — including the labels where
    `closed_form_undressed` honest-fails (orbit size ≥ 3, orbit size 2 with `γ`
    not a root, cells more than one coroot down).  It is therefore both a new
    capability and an independent oracle against which the (★) solver can be
    checked — measured agreement 225/225 at `SU(3)` (all three cone generators),
    36/36 at `Spin(5)` and at `Sp(2)`, and 81/81 at `SU(2)` once the truncation
    certificate passes."""
    Pbar, weights = spectral_eigenbasis(datum, height, order, span, certify)
    # unbar: the eigen-relation with the POSITIVE eigenvalue is carried by `P`,
    # and `P = bar(P̄)`.
    T = {mu: {nu: LaurentPoly({-k: c for k, c in lp._coeffs.items()})
              for nu, lp in row.items()} for mu, row in Pbar.items()}
    rho = rho_weight(datum)
    rm = sum(rho[i] * m[i] for i in range(datum.dim))
    lam = {mu: LaurentPoly({rm + 2 * sum(mu[i] * m[i] for i in range(datum.dim)):
                            (-1) ** rm}) for mu in weights}
    # invert the unitriangular T (weights are height-ordered)
    Tinv = {}
    for nu in weights:
        row = {nu: LaurentPoly({0: 1})}
        for s in reversed(weights[:weights.index(nu)]):
            acc = LaurentPoly.zero()
            for t, c in row.items():
                if t != s:
                    acc = acc + c * T[t].get(s, LaurentPoly.zero())
            if not acc.is_zero():
                row[s] = LaurentPoly({0: -1}) * acc
        Tinv[nu] = row
    C = {}
    for nu in weights:
        acc = {}
        for mu, c in Tinv[nu].items():          # χ_ν = Σ_μ Tinv[ν][μ] P_μ
            cl = c * lam[mu]                    # L P_μ = λ_μ P_μ
            for sig, t in T[mu].items():        # P_μ = Σ_σ T[μ][σ] χ_σ
                acc[sig] = (acc.get(sig, LaurentPoly.zero()) + cl * t)
        C[nu] = {s: v for s, v in acc.items() if not v.is_zero()}
    return C, weights


