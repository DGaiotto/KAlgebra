def test_the_generator_is_the_product_of_E_s_over_the_weights_of_r():
    """`E^{(s;r)}_\\fq(X_γ) = ∏_{w∈r} E^{(s)}_\\fq(μ^w X_γ)`.

    Read off a one-node quiver, where the constraint forces `S` to be the
    generator itself: with `Ω(γ) = χ_r` at spin `0` and nothing at any `nγ`,
    `n ≥ 2`, the element built IS `E^{(0;r)}_\\fq(X_γ)`, and its weight-`w`
    component is the ordinary `E_\\fq` series — the flavoured generator is
    therefore exactly the stated product, with the weights entered with
    multiplicity.
    """
    for N in (2, 3, 4):
        Q = FlavouredQuiver([[0]], [N])
        eng = FlavouredFactorSpectrum(Q, 4)
        eng.run()
        fund = Q.flavour.fundamental(0)
        assert eng.multiplicities() == {(1,): {fund: {0: 1}}}, N
        S = eng.spectrum_generator()
        ray = charge_series({0: 1}, 4)          # one E_𝖖 factor, spin 0
        for w in Q.flavour.irrep_weights(fund):
            for n in range(1, 5):
                got = S.get(((n,), Q.flavour.scale(w, n)), H0)
                assert got == ray[n], (N, w, n)


def test_the_flavoured_constraint_is_the_unfolded_bps_quiver_constraint():
    """`χ_{r_a}(μ) X_{γ_a} = Σ_{w∈r_a} X_{γ_a+w}`.

    So the flavoured leading data at a node is the unflavoured leading data of
    the unfolded quiver, node by node — which is why flavoured uniqueness is
    inherited rather than new, and why the unfolded `S` is legitimate ground
    truth for the flavoured one.
    """
    for entry in CORPUS:
        Q, D = _quiver(entry)
        eng = FlavouredFactorSpectrum(Q, D)
        _, _, labels = Q.unfold()
        want = {}
        for a, w in labels:                     # one unfolded node per weight
            k = tuple(1 if i == a else 0 for i in range(Q.rank))
            want.setdefault(k, {})[w] = want.setdefault(k, {}).get(w, 0) - 1
        for k, block in want.items():
            assert eng.target(k) == block, (entry[0], k)


