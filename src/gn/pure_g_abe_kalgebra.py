class NonPointedMonoid(Exception):
    """The dominant cocharacter monoid contains a line, so it has no finite
    generating set as a monoid.

    Raised by `cone_generators` when `G` has a **central torus**: the central
    direction is a *group* (`det^{±1}` and its cousins), not a monoid, and
    belongs with the invertible generators — which is exactly how the type-A
    `PureUNKAlgebra` (retired 2026-09-19) carried `det`.  The exception reports the
    lineality space so a caller can split
    `M(G) = (pointed part) ⊕ (central lattice)`."""

    def __init__(self, datum, lineality):
        self.lineality = tuple(tuple(v) for v in lineality)
        super().__init__(
            f"{datum.name}: the dominant cocharacter monoid is not pointed — "
            f"it contains the {len(self.lineality)}-dimensional central "
            f"direction {self.lineality}.  A central torus needs INVERTIBLE "
            f"generators (det^{{±1}}), not cone generators; see "
            f"the design notes.")


