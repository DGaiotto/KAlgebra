class FlavourSpace:
    """`G = ∏_i SU(N_i)`, with weights in concatenated torus coordinates.

    A weight of `SU(N)` is written in the coordinates `SUNZPlusRing.to_abelian`
    uses — `(w_1 - w_N, …, w_{N-1} - w_N)` for a `U(N)` weight `w` — so it is an
    element of `Z^{N-1}` and weights add componentwise.  **These coordinates are
    integral**: the half-integers that appear when a flavour direction is kept
    inside `Γ` and the node charges are averaged (the `(a, b, s)` labels of
    the `D_n`-chamber torus, the archived tree) never arise
    here, because `Γ` is the gauge lattice alone and the weights are carried
    separately.

    A weight of the product is the concatenation, so it lies in
    `Z^{Σ_i (N_i - 1)}`.  A factor with `N_i = 1` is trivial and contributes no
    coordinates, which is how an unflavoured node is expressed.
    """

    def __init__(self, factors: Sequence[int]):
        factors = tuple(int(n) for n in factors)
        if any(n < 1 for n in factors):
            raise ValueError(f"FlavourSpace: each SU(N) needs N >= 1, got {factors}")
        self.factors = factors
        self.rings = tuple(SUNZPlusRing(n) for n in factors)
        widths = [max(n - 1, 0) for n in factors]
        self.widths = tuple(widths)
        offs, acc = [], 0
        for w in widths:
            offs.append(acc)
            acc += w
        self.offsets = tuple(offs)
        self.dim = acc

    def __repr__(self) -> str:
        return f"FlavourSpace({list(self.factors)})"

    def is_trivial(self) -> bool:
        return self.dim == 0

    def zplus_ring(self):
        """`R(G) = ⊗_a R(SU(N_a))` as the repo's own `Z₊`-ring object.

        The canonical product ring, built with `zplus_ring.TensorZPlusRing`'s
        **n-ary** constructor — there is one product-ring object for a given
        flavour group, and consumers take it from here rather than assembling
        their own.  Trivial factors contribute nothing, so an unflavoured datum
        gives `TrivialZPlusRing` and a single non-trivial factor gives that
        factor itself rather than a one-term tensor product.
        """
        cached = getattr(self, "_zplus_ring", None)
        if cached is not None:
            return cached
        from zplus_ring import TensorZPlusRing, TrivialZPlusRing
        live = [r for r, n in zip(self.rings, self.factors) if n > 1]
        if not live:
            ring = TrivialZPlusRing()
        elif len(live) == 1:
            ring = live[0]
        else:
            ring = TensorZPlusRing(live)
        self._zplus_ring = ring
        return ring

    def _live_slots(self) -> tuple:
        """Indices of the factors that `zplus_ring()` keeps (those with `N > 1`)."""
        return tuple(i for i, n in enumerate(self.factors) if n > 1)

    def irrep_to_ring_key(self, rep: Irrep):
        """An `Irrep` (one partition per factor) ↦ a `zplus_ring()` basis key.

        The two are **not** the same object, and conflating them is a silent
        error rather than a loud one: `zplus_ring()` drops the trivial factors,
        so its keys are bare partitions (one live factor) or tuples over the
        live factors only (several), whereas an `Irrep` always carries one slot
        per factor.  `KAlgebra.r_label_decompose`'s second component is
        contractually a **basis element of `coefficient_ring()`**, so it is this
        key that must be handed back — an `Irrep` there passes
        `verify_section_is_single_irrep` (which only counts terms) while making
        `R.dim` and `forget()` raise and `to_R_form` emit ring-invalid data.
        """
        rep = self._normalise(rep)
        live = self._live_slots()
        if not live:
            return ()
        if len(live) == 1:
            return rep[live[0]]
        return tuple(rep[i] for i in live)

    def ring_key_to_irrep(self, key) -> Irrep:
        """Inverse of `irrep_to_ring_key`: re-insert the trivial factors."""
        live = self._live_slots()
        if not live:
            return self.trivial_irrep()
        if len(live) == 1:
            parts = {live[0]: tuple(key)}
        else:
            if len(key) != len(live):
                raise ValueError(
                    f"ring_key_to_irrep: expected {len(live)} live slots, "
                    f"got {key!r}")
            parts = {slot: tuple(k) for slot, k in zip(live, key)}
        return self._normalise(
            tuple(parts.get(i, ()) for i in range(len(self.factors))))

    @property
    def zero(self) -> Weight:
        return (0,) * self.dim

    def add(self, u: Weight, v: Weight) -> Weight:
        return tuple(a + b for a, b in zip(u, v))

    def scale(self, u: Weight, n: int) -> Weight:
        return tuple(n * a for a in u)

    # ----- irreps -------------------------------------------------------
    def trivial_irrep(self) -> Irrep:
        return tuple(() for _ in self.factors)

    def fundamental(self, index: int) -> Irrep:
        """The `N_index`-dimensional irrep of the `index`-th factor."""
        return tuple((1,) if i == index and self.factors[i] > 1 else ()
                     for i in range(len(self.factors)))

    def irrep_weights(self, rep: Irrep) -> dict[Weight, int]:
        """Weight diagram of `⊗_i χ_{λ_i}`, as `{weight: multiplicity}`."""
        rep = self._normalise(rep)
        per: list[dict[tuple[int, ...], int]] = []
        for ring, lam in zip(self.rings, rep):
            if ring.N == 1:
                per.append({(): 1})
                continue
            elt = RElement(ring, {ring.reduce(lam): 1})
            ab = ring.to_abelian(elt)
            per.append({tuple(int(x) for x in k): int(v)
                        for k, v in ab.terms.items() if v})
        out: dict[Weight, int] = {}
        for combo in itertools.product(*[sorted(d.items()) for d in per]):
            key = tuple(x for w, _ in combo for x in w)
            mult = 1
            for _, m in combo:
                mult *= m
            out[key] = out.get(key, 0) + mult
        return {k: v for k, v in out.items() if v}

    def irrep_dim(self, rep: Irrep) -> int:
        """`dim r` — from the `Z₊`-ring, which multiplies the per-factor dims.

        Delegated rather than computed by summing `irrep_weights`, which
        materialises the whole product weight diagram to add it up.
        """
        return self.zplus_ring().dim(self.irrep_to_ring_key(rep))

    def _normalise(self, rep: Irrep) -> Irrep:
        rep = tuple(tuple(int(x) for x in lam) for lam in rep)
        if len(rep) != len(self.factors):
            raise ValueError(
                f"irrep needs one partition per factor "
                f"({len(self.factors)}), got {len(rep)}: {rep}")
        return tuple(ring.reduce(lam) if ring.N > 1 else ()
                     for ring, lam in zip(self.rings, rep))

    # ----- the Weyl group ----------------------------------------------
    def weyl_images(self, w: Weight) -> list[Weight]:
        """The `W = ∏_i S_{N_i}` orbit of a weight, in these coordinates.

        A coordinate vector `(w_1-w_N, …, w_{N-1}-w_N)` lifts to the `U(N)`
        weight `(w_1-w_N, …, w_{N-1}-w_N, 0)`; `S_N` permutes the `N` entries;
        the result is projected back.  Exact, and independent of the lift.
        """
        per: list[list[tuple[int, ...]]] = []
        for i, n in enumerate(self.factors):
            if n <= 1:
                per.append([()])
                continue
            lo = self.offsets[i]
            piece = tuple(w[lo:lo + n - 1]) + (0,)
            seen = set()
            for perm in itertools.permutations(piece):
                proj = tuple(perm[j] - perm[n - 1] for j in range(n - 1))
                seen.add(proj)
            per.append(sorted(seen))
        return [tuple(x for p in combo for x in p)
                for combo in itertools.product(*per)]

    def is_weyl_invariant(self, fn: dict[Weight, int]) -> bool:
        """Is `fn` (a finitely-supported weight function) `W`-invariant?

        Equivalently — and this is why the test is stated this way — is `fn` the
        weight-multiplicity function of a **virtual character** of `G`?  For a
        finitely-supported function on the weight lattice the two are the same
        condition.
        """
        fn = {k: v for k, v in fn.items() if v}
        for w, v in fn.items():
            for u in self.weyl_images(w):
                if fn.get(u, 0) != v:
                    return False
        return True

    # ----- weights -> characters ---------------------------------------
    def decompose(self, fn: dict[Weight, int]) -> dict[Irrep, int]:
        """A `W`-invariant weight function as a virtual character of `G`.

        Factor by factor, through the certified `SUNZPlusRing.from_abelian`
        (which un-branches a Weyl-symmetric μ-Laurent into characters and
        accepts **signed** multiplicities).  Raises if `fn` is not `W`-invariant
        — an honest failure, never a silent projection.
        """
        fn = {k: int(v) for k, v in fn.items() if v}
        if not fn:
            return {}
        if not self.is_weyl_invariant(fn):
            raise ValueError(
                "decompose: weight function is not Weyl-invariant, so it is "
                "not the weight diagram of any virtual character of "
                f"{self!r}")
        return self._decompose_from(fn, 0)

    def _decompose_from(self, fn: dict[Weight, int], i: int) -> dict[Irrep, int]:
        if i == len(self.factors):
            assert set(fn) <= {()}
            c = fn.get((), 0)
            return {(): c} if c else {}
        ring = self.rings[i]
        # Factors `< i` have already been peeled off the front of every key, so
        # this factor's coordinates are the LEADING `widths[i]` of what is left
        # — not `offsets[i]` into the original key.  (Using the original offset
        # is silently right whenever at most one factor is non-trivial, and
        # wrong as soon as two are; it was caught by SU(2)xSU(2).)
        wd = self.widths[i]
        rest_of: dict[Weight, dict[tuple[int, ...], int]] = {}
        for w, c in fn.items():
            head = tuple(w[:wd])
            tail = tuple(w[wd:])
            rest_of.setdefault(tail, {})[head] = \
                rest_of.setdefault(tail, {}).get(head, 0) + c
        # For each irrep of this factor, the residual function on the rest.
        residual: dict[tuple[int, ...], dict[Weight, int]] = {}
        for tail, head_fn in rest_of.items():
            for lam, mult in self._factor_decompose(ring, head_fn).items():
                residual.setdefault(lam, {})[tail] = \
                    residual.setdefault(lam, {}).get(tail, 0) + mult
        out: dict[Irrep, int] = {}
        for lam, rest_fn in residual.items():
            for sub, c in self._decompose_from(
                    {k: v for k, v in rest_fn.items() if v}, i + 1).items():
                key = (lam,) + sub
                out[key] = out.get(key, 0) + c
        return {k: v for k, v in out.items() if v}

    @staticmethod
    def _factor_decompose(ring: SUNZPlusRing,
                          head_fn: dict[tuple[int, ...], int]
                          ) -> dict[tuple[int, ...], int]:
        head_fn = {k: v for k, v in head_fn.items() if v}
        if not head_fn:
            return {}
        if ring.N == 1:
            return {(): head_fn.get((), 0)} if head_fn.get((), 0) else {}
        ab = AbelianZPlusRing(rank=ring.N - 1)
        elt = RElement(ab, dict(head_fn))
        got = ring.from_abelian(elt, allow_virtual=True)
        return {tuple(k): int(v) for k, v in got.terms.items() if v}


