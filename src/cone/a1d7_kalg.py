class A1D7KAlg(KAlgebra):
    """[A_1, D_7] K-algebra, SU(2)-flavoured, Z_7-symmetric.

    Standalone implementation: multiplication is driven by the
    precomputed `_PLUCKER_BASE_I0` table (i=0 row) plus Z_7 shift
    via `_RHO_TABLE`.  No BPS or external-oracle dependency.

    Native label = lattice tuple in ℤ^7, canonicalised under the
    SU(2) Weyl involution (last coord ≤ 0; |last coord| = χ-shift
    index).
    """

    _RANK = 7
    _GAUGE_RANK = 6

    def __init__(self):
        self._R = SU2ZPlusRing()

    @property
    def rank(self) -> int:
        return self._RANK

    @property
    def gauge_rank(self) -> int:
        return self._GAUGE_RANK

    # -- generators -------------------------------------------------------

    def T(self, i: int) -> tuple:
        return _T_ORBIT[i % 7]

    def D(self, i: int) -> tuple:
        return _D_ORBIT[i % 7]

    def V(self, i: int) -> tuple:
        return _V_ORBIT[i % 7]

    def W(self, i: int) -> tuple:
        return _W_ORBIT[i % 7]

    def chi(self, k: int) -> tuple:
        if k < 0:
            raise ValueError(f"chi(k): k must be >= 0, got {k}")
        return (0, 0, 0, 0, 0, 0, -k)

    # -- KAlgebra primitives ---------------------------------------------

    def coefficient_ring(self) -> ZPlusRing:
        return self._R

    def identity(self) -> tuple:
        return _IDENTITY_LABEL

    def canonicalise(self, label) -> tuple:
        """SU(2)-Weyl canonical rep: flip last coord if > 0."""
        lab = tuple(int(x) for x in label)
        if lab[-1] > 0:
            return lab[:-1] + (-lab[-1],)
        return lab

    def multiply(self, a, b) -> Element:
        """Multiplication via Z_7-rotated lookup in `_PLUCKER_BASE_I0`."""
        a = self.canonicalise(a)
        b = self.canonicalise(b)
        if a == _IDENTITY_LABEL:
            return Element({b: LaurentPoly({0: 1})})
        if b == _IDENTITY_LABEL:
            return Element({a: LaurentPoly({0: 1})})
        if a not in _LATTICE_TO_MULTGEN or b not in _LATTICE_TO_MULTGEN:
            raise NotImplementedError(
                f"A1D7KAlg.multiply: standalone table only covers "
                f"mult-gen × mult-gen and identity * X; got "
                f"a = {a!r}, b = {b!r}."
            )
        kind_a, ia = _LATTICE_TO_MULTGEN[a]
        kind_b, ib = _LATTICE_TO_MULTGEN[b]
        j = (ib - ia) % 7
        entry = _PLUCKER_BASE_I0[(kind_a, kind_b, j)]
        out: dict[tuple, LaurentPoly] = {}
        for coef, q_exp, out_label_i0 in entry:
            out_label = _rho_n_apply(out_label_i0, ia)
            poly = LaurentPoly({q_exp: coef})
            if out_label in out:
                out[out_label] = out[out_label] + poly
            else:
                out[out_label] = poly
        return Element({lab: p for lab, p in out.items() if not p.is_zero()})

    def rho(self, a) -> tuple:
        return _rho_apply(self.canonicalise(a))

    def rho_inverse(self, a) -> tuple:
        return _rho_inverse_apply(self.canonicalise(a))

    def trace(self, a, K: int = 20, **kwargs):
        raise NotImplementedError(
            "A1D7KAlg.trace: not wired into this class; for [A_1, D_7] traces "
            "use A1DnKAlg(7) (or the zoo's FiniteA1D7KAlgebra, whose "
            "closed-form sl(2)_{-12/7} traces are in a1d7_layer2.py)."
        )

    def trace_layer1(self, label):
        raise NotImplementedError("A1D7KAlg.trace_layer1: TODO")

    def trace_layer2(self, K: int = 20):
        raise NotImplementedError("A1D7KAlg.trace_layer2: TODO")

    def r_label_decompose(self, label):
        """SU(2) flavour-lift coordinate (single irrep).  Canonical γ has
        γ[-1] ≤ 0; let k = -γ[-1] ≥ 0.  Section = γ with last coord zeroed
        (∈ Γ^w); single irrep key = k (the χ_k ∈ R(SU(2)) basis label)."""
        a = self.canonicalise(label)
        return a[:-1] + (0,), -a[-1]

    def r_label_compose(self, section, r_basis_label):
        # Re-dress the w-fixed section: γ[-1] = -k.
        return tuple(section[:-1]) + (-r_basis_label,)

    def embed_R(self, r: RElement) -> Element:
        """Central embedding `R(SU(2)) ↪ A_𝖖`: each character `χ_k` maps
        to the central canonical basis element `L_{(0,…,0,−k)}`, extended
        Z-linearly.  Inverse-compatible with `_label_section_decompose`:
        `embed_R(χ_k) · L_{section} == L_γ` for `γ[-1] = −k`."""
        R = self.coefficient_ring()
        if not isinstance(r, RElement) or r.ring != R:
            raise TypeError(
                "embed_R: argument must be an RElement over coefficient_ring()"
            )
        rank = len(self.identity())
        out = Element.zero()
        for k, coeff in r.terms.items():
            if coeff == 0:
                continue
            central = self.canonicalise((0,) * (rank - 1) + (-k,))
            out = out + Element.basis(central) * coeff
        return out

    def __repr__(self) -> str:
        return "A1D7KAlg()"


