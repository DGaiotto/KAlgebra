def test_S_equals_the_unfolded_S_on_every_flavoured_quiver():
    """`S ∈ \\cE_G` computed on the reduced cone equals the `S` of the unfolded
    BPS quiver, pushed forward to `(gauge charge, flavour weight)`.

    INDEPENDENT: the unfolded side has no notion of flavour at all — it is an
    ordinary BPS quiver whose nodes happen to be the weights, run through the
    unflavoured engine.  Exact equality of every coefficient, not agreement to
    some order.
    """
    for entry in CORPUS:
        Q, D = _quiver(entry)
        assert Q.unfoldable(), entry[0]
        S = build_flavoured_spectrum_generator(Q, D)
        gt = unfolded_spectrum_generator(Q, D)
        assert set(S) == set(gt), entry[0]
        assert _same(S, gt), entry[0]


