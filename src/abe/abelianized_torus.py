"""
Abelianized quantum torus: the ring the UV monopole operators of 3d N=4 /
4d N=2 linear quivers live in, in the abelianized chart.

This module is the ambient ring D_rat for the canonical-surface
abelianized presentations.  It lives on the canonical surface so the
canonical-surface abelianized realisations can import it directly.

Scope
-----

Everything is over the scalar ring ``Z[q, q^{-1}]`` (= ``LaurentPoly``).
Habiro-style localization at ``(1 - q^{2n})`` is a future extension.

Flavour fugacities ``mu_r`` are first-class but live as **flavour
colors** in the v-grading: a ``DOp`` of ``n`` total colors and
``n_gauge`` gauge colors treats indices ``0..n_gauge-1`` as gauge (with
matching ``u_k`` shift operators) and indices ``n_gauge..n-1`` as
flavour (no matching ``u_k``).  ``mu_r`` is then
``v_{n_gauge + r}`` (0-indexed; helpers ``DOp.mu`` and ``VLaurent.mu``
are provided).  This keeps the algebra of the ring identical to the
pure-gauge case: ``u_k`` simply doesn't shift the flavour ``v``s, which
falls out for free since the corresponding entries of the shift vector
are zero.

Rings
-----

* ``VLaurent`` -- multivariate Laurent polynomial in ``(v_0, ..., v_{n-1})``
  with ``LaurentPoly`` (i.e.  ``Z[q^+/-1]``) coefficients.
  Stored as ``dict[tuple[int, ...], LaurentPoly]``: v-exponent tuple ->
  scalar coefficient, zeros dropped.

* ``VRational`` -- elements of ``VLaurent[Delta^{-1}]`` where ``Delta`` is
  the multiplicative monoid generated by the elementary root-like factors

        (v_i - q^m v_j)      for  0 <= i < j < n,   m in Z.

  These are the only allowed denominator factors.  The monoid is closed
  under the ``v_k -> q^{2 c_k} v_k`` substitution induced by ``u^c``:
  a factor ``(v_i - q^m v_j)`` becomes

        q^{2 c_i}  ( v_i - q^{m + 2(c_j - c_i)} v_j )

  -- same monoid, plus a ``q^{2 c_i}`` scalar that absorbs into the
  numerator.  This is the key property that lets ``DOp`` multiply without
  leaving the ring.

  Denominator stored as ``dict[(i, j, m): int]`` with ``i < j`` canonical.
  Equality is by cross-multiplication.

  By convention the ``(v_i - q^m v_j)`` denom factors only ever involve
  gauge colors in physical formulas, but the ring imposes no restriction.

* ``DOp`` -- normal-ordered difference operator

        F = sum_{a in Z^n}  f_a(v) * u^a,     f_a in VRational.

  Multiplication is governed by the abelianized q-Weyl relation

        u_k * v_l = q^{2 delta_{kl}} * v_l * u_k.

  Stored as ``dict[tuple[int, ...], VRational]``: u-exponent tuple ->
  rational-in-v coefficient.  When ``n_gauge < n``, slots
  ``[n_gauge, n)`` are flavour: ``u`` operators are not allowed there
  (``DOp.u(k)`` raises for ``k >= n_gauge``), and the corresponding
  entries of the u-exponent tuple are forced to zero.  Left-ordered
  form (coefficients multiply on the left).

Conventions
-----------

* Variables are indexed ``0..n-1``.  ``n`` is fixed per ``VLaurent`` /
  ``VRational`` / ``DOp`` instance; arithmetic checks matching ``n``.
  For ``DOp`` instances built with ``n_gauge < n``, the additional
  invariant is that u-exponent tuples are zero on the flavour slots.
* ``q`` lives in the scalar coefficient ring and is exactly the
  ``LaurentPoly`` ``q`` from ``laurent_poly``.
"""

from __future__ import annotations

from functools import lru_cache
from typing import Iterable, Mapping
from laurent_poly import LaurentPoly


# ============================================================================
# VLaurent: Z[q^+/-1][v_1^+/-1, ..., v_n^+/-1]
# ============================================================================


def _lp_is_zero(lp: LaurentPoly) -> bool:
    return lp.is_zero()


class VLaurent:
    """Multivariate Laurent polynomial in v_0, ..., v_{n-1} over Z[q^+/-1].

    Stored as ``dict[tuple[int, ...], LaurentPoly]``: the key is the
    v-exponent tuple, the value is the scalar coefficient (a ``LaurentPoly``
    in ``q``).  Zero coefficients are dropped at construction.
    """

    __slots__ = ("_terms", "_n")

    def __init__(self,
                 terms: Mapping[tuple[int, ...], LaurentPoly] | None = None,
                 n: int = 1):
        if n < 0:
            raise ValueError("VLaurent needs n >= 0")
        self._n = int(n)
        self._terms: dict[tuple[int, ...], LaurentPoly] = {}
        if terms:
            for e, c in terms.items():
                if len(e) != n:
                    raise ValueError(
                        f"v-exponent {e} has length {len(e)} != n {n}"
                    )
                if not isinstance(c, LaurentPoly):
                    raise TypeError(
                        f"coefficient for {e} is {type(c).__name__}, not LaurentPoly"
                    )
                if not c.is_zero():
                    self._terms[tuple(int(x) for x in e)] = c

    @classmethod
    def _from_clean_terms(cls, terms: dict, n: int) -> "VLaurent":
        """Fast-path constructor.  Caller MUST ensure:
          - terms is a dict[tuple[int, ...], LaurentPoly]
          - all exponent tuples have length n
          - no zero coefficients

        Skips iteration + validation in __init__.  Used in hot inner
        arithmetic loops (mul, add, q_shift) where invariants hold."""
        out = cls.__new__(cls)
        out._n = n
        out._terms = terms
        return out

    # --- constructors ---

    @staticmethod
    def zero(n: int) -> "VLaurent":
        return VLaurent(None, n=n)

    @staticmethod
    def one(n: int) -> "VLaurent":
        return VLaurent({tuple([0] * n): LaurentPoly.one()}, n=n)

    @staticmethod
    def from_scalar(s: "LaurentPoly | int", n: int) -> "VLaurent":
        if isinstance(s, int):
            s = LaurentPoly.from_int(s)
        if s.is_zero():
            return VLaurent.zero(n)
        return VLaurent({tuple([0] * n): s}, n=n)

    @staticmethod
    def v_pow(k: int, exp: int = 1, n: int | None = None) -> "VLaurent":
        """Return v_k^exp, where k is 0-based."""
        if n is None:
            n = k + 1
        if not (0 <= k < n):
            raise ValueError(f"v index {k} out of range for n {n}")
        e = [0] * n
        e[k] = int(exp)
        return VLaurent({tuple(e): LaurentPoly.one()}, n=n)

    @staticmethod
    def monomial(v_exps: Iterable[int],
                 coeff: "LaurentPoly | int" = 1,
                 n: int | None = None) -> "VLaurent":
        e = tuple(int(x) for x in v_exps)
        if n is None:
            n = len(e)
        if len(e) != n:
            raise ValueError("monomial: v_exps length != n")
        if isinstance(coeff, int):
            coeff = LaurentPoly.from_int(coeff)
        if coeff.is_zero():
            return VLaurent.zero(n)
        return VLaurent({e: coeff}, n=n)

    # --- accessors ---

    @property
    def n(self) -> int:
        return self._n

    def is_zero(self) -> bool:
        return not self._terms

    def items(self):
        return self._terms.items()

    def coeff(self, v_exp: Iterable[int]) -> LaurentPoly:
        key = tuple(int(x) for x in v_exp)
        return self._terms.get(key, LaurentPoly.zero())

    # --- arithmetic ---

    def _check_n(self, other: "VLaurent") -> None:
        if self._n != other._n:
            raise ValueError(f"VLaurent n mismatch: {self._n} vs {other._n}")

    def _coerce(self, other) -> "VLaurent | None":
        if isinstance(other, VLaurent):
            self._check_n(other)
            return other
        if isinstance(other, LaurentPoly):
            return VLaurent.from_scalar(other, n=self._n)
        if isinstance(other, int):
            return VLaurent.from_scalar(other, n=self._n)
        return None

    def __neg__(self) -> "VLaurent":
        return VLaurent._from_clean_terms(
            {e: -c for e, c in self._terms.items()}, self._n)

    def __add__(self, other) -> "VLaurent":
        o = self._coerce(other)
        if o is None:
            return NotImplemented
        out = dict(self._terms)
        for e, c in o._terms.items():
            nc = out.get(e, LaurentPoly.zero()) + c
            if nc.is_zero():
                out.pop(e, None)
            else:
                out[e] = nc
        return VLaurent._from_clean_terms(out, self._n)

    def __radd__(self, other):
        return self.__add__(other)

    def __sub__(self, other) -> "VLaurent":
        o = self._coerce(other)
        if o is None:
            return NotImplemented
        return self + (-o)

    def __rsub__(self, other):
        o = self._coerce(other)
        if o is None:
            return NotImplemented
        return o - self

    def __mul__(self, other) -> "VLaurent":
        o = self._coerce(other)
        if o is None:
            return NotImplemented
        if self.is_zero() or o.is_zero():
            return VLaurent.zero(self._n)
        a = self._terms
        b = o._terms
        n = self._n
        la = len(a)
        lb = len(b)
        # Fast-path: monomial * polynomial.
        if la == 1:
            e1, c1 = next(iter(a.items()))
            out = {}
            for e2, c2 in b.items():
                e = tuple(e1[i] + e2[i] for i in range(n))
                nc = c1 * c2
                if not nc.is_zero():
                    out[e] = nc
            return VLaurent._from_clean_terms(out, n)
        if lb == 1:
            e2, c2 = next(iter(b.items()))
            out = {}
            for e1, c1 in a.items():
                e = tuple(e1[i] + e2[i] for i in range(n))
                nc = c1 * c2
                if not nc.is_zero():
                    out[e] = nc
            return VLaurent._from_clean_terms(out, n)
        # General polynomial multiplication.  Accumulate the q-Laurent
        # coefficients into RAW {q-exp: coeff} dicts keyed by v-exponent,
        # convolving c1*c2 directly into the accumulator.  This skips the
        # per-product LaurentPoly object + the per-collision LaurentPoly
        # __add__ that dominated this path; one LaurentPoly is built per
        # output v-monomial at the end.
        out_raw: dict[tuple[int, ...], dict[int, int]] = {}
        for e1, c1 in a.items():
            a1 = c1._coeffs
            for e2, c2 in b.items():
                e = tuple(x + y for x, y in zip(e1, e2))
                d = out_raw.get(e)
                if d is None:
                    out_raw[e] = d = {}
                for q1, k1 in a1.items():
                    for q2, k2 in c2._coeffs.items():
                        qe = q1 + q2
                        nv = d.get(qe, 0) + k1 * k2
                        if nv:
                            d[qe] = nv
                        else:
                            d.pop(qe, None)
        out: dict[tuple[int, ...], LaurentPoly] = {}
        for e, d in out_raw.items():
            if d:
                out[e] = LaurentPoly._from_clean_dict(d)
        return VLaurent._from_clean_terms(out, n)

    __rmul__ = __mul__

    def __pow__(self, k: int) -> "VLaurent":
        if k < 0:
            raise ValueError("VLaurent: negative powers require inversion")
        if k == 0:
            return VLaurent.one(self._n)
        out = VLaurent.one(self._n)
        base = self
        while k > 0:
            if k & 1:
                out = out * base
            k >>= 1
            if k:
                base = base * base
        return out

    def q_shift(self, c: Iterable[int]) -> "VLaurent":
        """Substitute v_k -> q^{2 c_k} v_k.

        On a monomial ``lp(q) * prod v_k^{e_k}`` this produces
        ``lp(q) * q^{2 sum_k c_k e_k} * prod v_k^{e_k}``.
        """
        c = tuple(int(x) for x in c)
        if len(c) != self._n:
            raise ValueError(f"q_shift vector length {len(c)} != n {self._n}")
        out: dict[tuple[int, ...], LaurentPoly] = {}
        for e, lp in self._terms.items():
            shift = 2 * sum(ck * ek for ck, ek in zip(c, e))
            if shift == 0:
                out[e] = lp
            else:
                out[e] = LaurentPoly({k + shift: v for k, v in lp._coeffs.items()})
        return VLaurent(out, n=self._n)

    def __eq__(self, other) -> bool:
        if isinstance(other, (int, LaurentPoly)):
            return self == VLaurent._coerce_static(other, self._n)
        if not isinstance(other, VLaurent):
            return NotImplemented
        return self._n == other._n and self._terms == other._terms

    @staticmethod
    def _coerce_static(x, n: int) -> "VLaurent":
        if isinstance(x, VLaurent):
            if x._n != n:
                raise ValueError("VLaurent n mismatch")
            return x
        if isinstance(x, LaurentPoly):
            return VLaurent.from_scalar(x, n)
        if isinstance(x, int):
            return VLaurent.from_scalar(x, n)
        raise TypeError(f"cannot coerce {type(x).__name__} to VLaurent")

    def __hash__(self):
        return hash((self._n,
                     tuple(sorted((e, tuple(sorted(lp._coeffs.items())))
                                  for e, lp in self._terms.items()))))

    def __repr__(self) -> str:
        if not self._terms:
            return "0"
        parts = []
        for e in sorted(self._terms):
            lp = self._terms[e]
            vsym = _v_monomial_str(e)
            if vsym == "":
                parts.append(repr(lp))
            else:
                # stringify coefficient
                lp_str = repr(lp)
                if lp_str == "1":
                    parts.append(vsym)
                elif lp_str == "-1":
                    parts.append("-" + vsym)
                elif " + " in lp_str or " - " in lp_str:
                    parts.append(f"({lp_str})*{vsym}")
                else:
                    parts.append(f"{lp_str}*{vsym}")
        s = parts[0]
        for p in parts[1:]:
            if p.startswith("-"):
                s += " - " + p[1:]
            else:
                s += " + " + p
        return s


def _v_monomial_str(e: tuple[int, ...]) -> str:
    if all(x == 0 for x in e):
        return ""
    parts = []
    for k, x in enumerate(e):
        if x == 0:
            continue
        if x == 1:
            parts.append(f"v_{k}")
        else:
            parts.append(f"v_{k}^{x}")
    return "*".join(parts)


