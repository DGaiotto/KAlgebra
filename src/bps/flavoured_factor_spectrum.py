def build_flavoured_spectrum_generator(
    quiver: FlavouredQuiver, cutoff: int, *,
    leading_data: Callable[[Vec], dict[Weight, int]] | None = None,
    piece_key: Callable[[Vec, int, Weight], object] | None = None,
    with_multiplicities: bool = False,
):
    """`S ∈ \\cE_G` for a flavoured BPS quiver, from the flavoured constraint."""
    eng = FlavouredFactorSpectrum(quiver, cutoff, leading_data=leading_data,
                                  piece_key=piece_key)
    eng.run()
    S = eng.spectrum_generator()
    return (S, eng.multiplicities_by_spin()) if with_multiplicities else S


def canonical_spectrum_generator(quiver: FlavouredQuiver, cutoff: int):
    """`S` in the flavoured quiver's CANONICAL node coordinates.

    The dictionary-facing readout: two flavoured quivers related by a node
    relabelling give the identical dict, so entries can be compared without
    carrying a witness permutation.  Both the reduced charge and the flavour
    weight are transported, the weight because the torus coordinates are
    concatenated in node order.

    Requires `canonical_key`'s precondition (no shared flavour factor), since
    it uses the same node colouring.
    """
    from quiver_enumeration import canonical_form
    if quiver.shares_a_flavour_factor():
        raise NotImplementedError(
            "canonical_spectrum_generator: see FlavouredQuiver.canonical_key")
    F = quiver.flavour
    cf = canonical_form(quiver.pairing, colours=quiver.node_colours())
    eng = FlavouredFactorSpectrum(quiver, cutoff)
    eng.run()
    out: dict[tuple[Vec, Weight], HabiroElement] = {}
    for (k, w), h in eng.spectrum_generator().items():
        ck = tuple(k[cf.perm[i]] for i in range(quiver.rank))
        cw: Weight = ()
        for i in range(quiver.rank):
            src, wd = F.offsets[cf.perm[i]], F.widths[cf.perm[i]]
            cw += tuple(w[src:src + wd])
        out[(ck, cw)] = h
    return out


def unfolded_spectrum_generator(quiver: FlavouredQuiver, cutoff: int):
    """`S` of the **unfolded** quiver, relabelled onto `(reduced charge, weight)`.

    The independent ground truth: this runs the unflavoured engine
    (`BPSFactorSpectrum`) on the ordinary BPS quiver whose nodes are the
    weights of the node reps, then pushes each enlarged charge forward to its
    `(gauge charge, flavour weight)` pair.  The two engines share the ray
    arithmetic and nothing else — the flavoured one runs its recursion on the
    reduced cone with a weight grading, this one on the enlarged cone with no
    flavour notion at all.
    """
    F = quiver.flavour
    B, charges, labels = quiver.unfold()
    eng = BPSFactorSpectrum(B, charges, cutoff, order="lex")
    eng.run()
    out: dict[tuple[Vec, Weight], HabiroElement] = {}
    for k, h in eng.spectrum_generator().items():
        if h.is_zero():
            continue
        gauge = [0] * quiver.rank
        weight = F.zero
        for i, n in enumerate(k):
            if not n:
                continue
            a, w = labels[i]
            gauge[a] += n
            weight = F.add(weight, F.scale(w, n))
        key = (tuple(gauge), weight)
        prev = out.get(key)
        out[key] = h if prev is None else prev + h
    return {k: v for k, v in out.items() if not v.is_zero()}
