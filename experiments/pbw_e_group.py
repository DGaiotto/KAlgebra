"""Exact arithmetic in the pro-nilpotent group `G` and its subgroup `E`.

This module is a *deliberately independent* implementation of the objects in
the paper's "Seiberg-Witten RG flows" section, written so that the PBW
factorization conjecture can be tested without reusing the repo machinery
whose correctness that conjecture underwrites (`bps_factor_spectrum`).  The
repo engine is used only as a cross-check, in the driver.

Objects (paper definitions, verbatim in content):

    Q_q(G)      quantum torus of a lattice G with antisymmetric pairing B,
                X_g X_g' = q^{<g,g'>} X_{g+g'},  <g,g'> = sum_ij B_ij g_i g'_j

    G-group     elements  1 + sum_{g in Gplus} c_g(q) X_g  with
                c_g(q) in Z[q, q^{-1}, (1-q^{2n})^{-1} | n>0]

    E_q(x)      = (-q x; q^2)_inf^{-1} = sum_n (-q)^n / (q^2)_n x^n

    E^{(s)}(x)  = prod_{j=-s}^{s} E_q((-1)^{2s} q^{2j} x)^{(-1)^{2s}},
                  s in (1/2)N, j stepping by 1

    E-group     the subgroup of the G-group generated by E^{(s)}(X_g)^{+-1}

`Gplus` is the cone generated by the simple charges, taken to be the standard
basis, so `Gplus = Z_{>=0}^r` and the cone degree of a charge is the sum of its
coordinates.  Everything is truncated by cone degree only -- never by a power
of `q` (the design notes "Exact arithmetic until the very end"; a negative bracket
would shift high-q terms down into the visible window).

Coefficient representation.  A coefficient is a pair `(num, den)` where `num`
is a Laurent polynomial over Z (a dict `exponent -> int`) and `den` is a dict
`n -> multiplicity` standing for `prod_n (1 - q^{2n})^{mult}`.  This is exact,
needs no gcd, and makes the one predicate the conjecture turns on -- "is this
coefficient actually in Z[q, q^{-1}]?" -- an exact polynomial division.
"""

from __future__ import annotations


# --------------------------------------------------------------------------
# Laurent polynomials over Z: dict {exponent: coefficient}, no zero values.
# --------------------------------------------------------------------------

ZERO_LP: dict[int, int] = {}
ONE_LP: dict[int, int] = {0: 1}


def lp_add(a: dict[int, int], b: dict[int, int]) -> dict[int, int]:
    c = dict(a)
    for e, v in b.items():
        w = c.get(e, 0) + v
        if w:
            c[e] = w
        else:
            c.pop(e, None)
    return c


def lp_neg(a: dict[int, int]) -> dict[int, int]:
    return {e: -v for e, v in a.items()}


def lp_mul(a: dict[int, int], b: dict[int, int]) -> dict[int, int]:
    if not a or not b:
        return {}
    c: dict[int, int] = {}
    for e1, v1 in a.items():
        for e2, v2 in b.items():
            e = e1 + e2
            w = c.get(e, 0) + v1 * v2
            if w:
                c[e] = w
            else:
                c.pop(e, None)
    return c


def lp_pow(a: dict[int, int], n: int) -> dict[int, int]:
    r = dict(ONE_LP)
    base = dict(a)
    while n:
        if n & 1:
            r = lp_mul(r, base)
        base = lp_mul(base, base)
        n >>= 1
    return r


def lp_bar(a: dict[int, int]) -> dict[int, int]:
    """The bar involution q -> q^{-1} on a Laurent polynomial."""
    return {-e: v for e, v in a.items()}


def lp_is_palindromic(a: dict[int, int]) -> bool:
    return lp_bar(a) == a


def _one_minus_q2n(n: int) -> dict[int, int]:
    return {0: 1, 2 * n: -1}


def lp_div_1mq2n(p: dict[int, int], n: int) -> dict[int, int] | None:
    """Exact division of `p` by `(1 - q^{2n})`; None if it does not divide.

    Peels from the bottom: the lowest term of `(1-q^m) h` is the lowest term of
    `h`, so peeling lowest terms reconstructs the quotient, whose support is
    confined to `[min(p), max(p) - m]`.
    """
    if not p:
        return {}
    m = 2 * n
    lo0, hi0 = min(p), max(p)
    span = hi0 - lo0
    if span < m:
        return None            # a nonzero multiple of (1-q^m) spans >= m
    # Dense left-to-right sweep.  Peeling always takes the lowest surviving
    # term and deposits at +m, i.e. strictly to the right, so one pass suffices
    # and no `min()` is needed -- which is what made the sparse version 77% of
    # this module's runtime (2.9M `min` calls in one profile).
    arr = [0] * (span + 1)
    for e, v in p.items():
        arr[e - lo0] = v
    top = span - m           # quotient support is [0, top] in these indices
    q: dict[int, int] = {}
    for i in range(span + 1):
        c = arr[i]
        if not c:
            continue
        if i > top:
            return None
        q[lo0 + i] = c
        arr[i] = 0
        arr[i + m] += c
    return q


# --------------------------------------------------------------------------
# Coefficients: num / prod_n (1 - q^{2n})^{den[n]}
# --------------------------------------------------------------------------

Coeff = tuple  # (num: dict[int,int], den: dict[int,int])

CF_ZERO: Coeff = ({}, {})
CF_ONE: Coeff = (dict(ONE_LP), {})


def cf_from_lp(num: dict[int, int]) -> Coeff:
    return (dict(num), {})


def cf_is_zero(c: Coeff) -> bool:
    return not c[0]


def _cf_simplify(num: dict[int, int], den: dict[int, int]) -> Coeff:
    """Cancel whatever `(1-q^{2n})` factors divide `num`, exactly."""
    if not num:
        return ({}, {})
    den = {n: e for n, e in den.items() if e > 0}
    # Loop to a fixpoint: cancelling a (1-q^{2n}) can expose divisibility by a
    # (1-q^{2m}) already passed over, so one sweep is not enough.
    progress = True
    while progress and den:
        progress = False
        for n in sorted(den):
            while den.get(n, 0) > 0:
                d = lp_div_1mq2n(num, n)
                if d is None:
                    break
                num = d
                den[n] -= 1
                progress = True
                if den[n] == 0:
                    del den[n]
    return (num, den)


def _den_expand(den: dict[int, int]) -> dict[int, int]:
    r = dict(ONE_LP)
    for n, e in den.items():
        if e:
            r = lp_mul(r, lp_pow(_one_minus_q2n(n), e))
    return r


def cf_add(a: Coeff, b: Coeff) -> Coeff:
    if cf_is_zero(a):
        return b
    if cf_is_zero(b):
        return a
    na, da = a
    nb, db = b
    if da == db:
        return _cf_simplify(lp_add(na, nb), dict(da))
    keys = set(da) | set(db)
    dc = {n: max(da.get(n, 0), db.get(n, 0)) for n in keys}
    fa = _den_expand({n: dc[n] - da.get(n, 0) for n in keys})
    fb = _den_expand({n: dc[n] - db.get(n, 0) for n in keys})
    return _cf_simplify(lp_add(lp_mul(na, fa), lp_mul(nb, fb)), dc)


def cf_mul(a: Coeff, b: Coeff) -> Coeff:
    if cf_is_zero(a) or cf_is_zero(b):
        return CF_ZERO
    na, da = a
    nb, db = b
    dc = dict(da)
    for n, e in db.items():
        dc[n] = dc.get(n, 0) + e
    return _cf_simplify(lp_mul(na, nb), dc)


def cf_neg(a: Coeff) -> Coeff:
    return (lp_neg(a[0]), dict(a[1]))


def cf_bar(a: Coeff) -> Coeff:
    """q -> q^{-1}.  bar(1/(1-q^{2n})) = -q^{2n}/(1-q^{2n}), same denominator."""
    num = lp_bar(a[0])
    for n, e in a[1].items():
        num = lp_mul(num, lp_pow({2 * n: -1}, e))
    return _cf_simplify(num, dict(a[1]))


def lp_exact_div(p: dict[int, int], d: dict[int, int]) -> dict[int, int] | None:
    """Exact division of Laurent polynomials, `p / d`; None if it does not divide.

    Requires `d`'s LOWEST coefficient to be a unit (+-1), which every product
    `prod (1 - q^{2n})^e` satisfies (its lowest term is `1` at exponent 0).
    Greedy from the bottom, entirely in integer arithmetic.
    """
    if not d:
        raise ZeroDivisionError("division by the zero polynomial")
    if not p:
        return {}
    lo_d, hi_d = min(d), max(d)
    if abs(d[lo_d]) != 1:
        raise ValueError("lowest coefficient of the divisor must be a unit")
    p = dict(p)
    lo_p, hi_p = min(p), max(p)
    q: dict[int, int] = {}
    # quotient support is contained in [lo_p - lo_d, hi_p - hi_d]
    for _ in range(max(0, (hi_p - hi_d) - (lo_p - lo_d) + 2)):
        if not p:
            break
        lo = min(p)
        c, r = divmod(p[lo], d[lo_d])
        if r:
            return None
        e = lo - lo_d
        q[e] = q.get(e, 0) + c
        for de, dv in d.items():
            k = e + de
            v = p.get(k, 0) - c * dv
            if v:
                p[k] = v
            else:
                p.pop(k, None)
    if p:
        return None
    return {e: v for e, v in q.items() if v}


def cf_to_lp(a: Coeff) -> dict[int, int] | None:
    """Return `a` as a Laurent polynomial over Z, or None if it is not one.

    NOTE the representation `num / prod (1-q^{2n})^e` is NOT canonical --
    `1/(1-q^2)` and `(1+q^2)/(1-q^4)` are the same number with different
    `(num, den)` -- so this must divide, not merely test `den == {}`.  Reading
    it off the representation returns None for coefficients that ARE Laurent
    polynomials, i.e. it manufactures false counterexamples to the conjecture.
    """
    num, den = a
    if not num:
        return {}
    if not den:
        return dict(num)
    return lp_exact_div(num, _den_expand(den))


def cf_eq(a: Coeff, b: Coeff) -> bool:
    """Exact equality, by cross-multiplication (the representation is not
    canonical -- see `cf_to_lp`)."""
    na, da = a
    nb, db = b
    if not na or not nb:
        return (not na) and (not nb)
    if da == db:
        return na == nb
    return lp_mul(na, _den_expand(db)) == lp_mul(nb, _den_expand(da))


# --------------------------------------------------------------------------
# Elements of the G-group: dict {charge tuple: Coeff}, cone-degree truncated.
# --------------------------------------------------------------------------

Charge = tuple  # tuple[int, ...] with non-negative entries


def deg(g: Charge) -> int:
    return sum(g)


def elt_one(rank: int) -> dict[Charge, Coeff]:
    return {(0,) * rank: CF_ONE}


def elt_add(a: dict, b: dict) -> dict:
    c = dict(a)
    for g, v in b.items():
        w = cf_add(c.get(g, CF_ZERO), v)
        if cf_is_zero(w):
            c.pop(g, None)
        else:
            c[g] = w
    return c


def elt_neg(a: dict) -> dict:
    return {g: cf_neg(v) for g, v in a.items()}


def bracket(B, g1: Charge, g2: Charge) -> int:
    t = 0
    for i, x in enumerate(g1):
        if not x:
            continue
        row = B[i]
        for j, y in enumerate(g2):
            if y:
                t += row[j] * x * y
    return t


def elt_mul(a: dict, b: dict, B, D: int) -> dict:
    """Product in Q_q(G), truncated to cone degree <= D."""
    c: dict[Charge, Coeff] = {}
    for g1, v1 in a.items():
        d1 = deg(g1)
        if d1 > D:
            continue
        for g2, v2 in b.items():
            if d1 + deg(g2) > D:
                continue
            g = tuple(x + y for x, y in zip(g1, g2))
            ph = bracket(B, g1, g2)
            coeff = cf_mul(cf_mul(v1, v2), cf_from_lp({ph: 1}))
            w = cf_add(c.get(g, CF_ZERO), coeff)
            if cf_is_zero(w):
                c.pop(g, None)
            else:
                c[g] = w
    return c


def elt_inv(a: dict, B, D: int, rank: int) -> dict:
    """Inverse of `1 + h` with `h` supported in cone degree >= 1."""
    zero = (0,) * rank
    assert a.get(zero) == CF_ONE, "not a G-group element (constant term != 1)"
    h = {g: v for g, v in a.items() if g != zero}
    assert all(deg(g) >= 1 for g in h), "support must lie in the positive cone"
    res = elt_one(rank)
    term = elt_one(rank)
    minus_h = elt_neg(h)
    for _ in range(D):
        term = elt_mul(term, minus_h, B, D)
        if not term:
            break
        res = elt_add(res, term)
    return res


def elt_bar(a: dict) -> dict:
    return {g: cf_bar(v) for g, v in a.items()}


def elt_truncate(a: dict, D: int) -> dict:
    return {g: v for g, v in a.items() if deg(g) <= D}


def elt_eq(a: dict, b: dict, D: int) -> bool:
    """Exact equality up to cone degree `D`, coefficient by coefficient.

    Uses `cf_eq`, not dict equality: the coefficient representation is not
    canonical, so dict equality gives false NEGATIVES.
    """
    a = elt_truncate(a, D)
    b = elt_truncate(b, D)
    for g in set(a) | set(b):
        if not cf_eq(a.get(g, CF_ZERO), b.get(g, CF_ZERO)):
            return False
    return True


# --------------------------------------------------------------------------
# The generators E^{(s)}_q(x) as power series in x.
# --------------------------------------------------------------------------


def _series_mul(a: list[Coeff], b: list[Coeff], N: int) -> list[Coeff]:
    c = [CF_ZERO] * (N + 1)
    for i, ai in enumerate(a):
        if cf_is_zero(ai):
            continue
        for j, bj in enumerate(b):
            if i + j > N:
                break
            if cf_is_zero(bj):
                continue
            c[i + j] = cf_add(c[i + j], cf_mul(ai, bj))
    return c


def _series_inv(a: list[Coeff], N: int) -> list[Coeff]:
    assert a[0] == CF_ONE
    c = [CF_ZERO] * (N + 1)
    c[0] = CF_ONE
    for n in range(1, N + 1):
        acc = CF_ZERO
        for k in range(1, n + 1):
            if k < len(a) and not cf_is_zero(a[k]):
                acc = cf_add(acc, cf_mul(a[k], c[n - k]))
        c[n] = cf_neg(acc)
    return c


def _series_pow(a: list[Coeff], p: int, N: int) -> list[Coeff]:
    if p < 0:
        a = _series_inv(a, N)
        p = -p
    r = [CF_ZERO] * (N + 1)
    r[0] = CF_ONE
    base = list(a)
    while p:
        if p & 1:
            r = _series_mul(r, base, N)
        base = _series_mul(base, base, N)
        p >>= 1
    return r


def E_series(N: int, sign: int = 1, two_j: int = 0) -> list[Coeff]:
    """Series of `E_q(sign * q^{two_j} * x)` in x, to order N.

    Coefficient of x^n is `(-q)^n / (q^2)_n * sign^n * q^{two_j * n}`.
    """
    out = [CF_ZERO] * (N + 1)
    for n in range(N + 1):
        s = (-1) ** n * (sign ** n)
        num = {n + two_j * n: s}
        den = {k: 1 for k in range(1, n + 1)}
        out[n] = _cf_simplify(num, den)
    return out


def E_spin_series(two_s: int, N: int) -> list[Coeff]:
    """Series of `E^{(s)}_q(x)` in x, to order N, for `s = two_s / 2`."""
    assert two_s >= 0
    sign = 1 if two_s % 2 == 0 else -1          # (-1)^{2s}
    res = [CF_ZERO] * (N + 1)
    res[0] = CF_ONE
    for two_j in range(-two_s, two_s + 1, 2):   # j = -s .. s, step 1
        f = E_series(N, sign=sign, two_j=two_j)
        if sign == -1:
            f = _series_inv(f, N)
        res = _series_mul(res, f, N)
    return res


_SPIN_CACHE: dict[tuple[int, int], list[Coeff]] = {}


def E_spin_series_cached(two_s: int, N: int) -> list[Coeff]:
    key = (two_s, N)
    s = _SPIN_CACHE.get(key)
    if s is None:
        s = E_spin_series(two_s, N)
        _SPIN_CACHE[key] = s
    return s


_ELT_CACHE: dict[tuple, dict] = {}


def E_spin_element_cached(gamma: Charge, two_s: int, power: int, D: int) -> dict:
    key = (gamma, two_s, power, D)
    e = _ELT_CACHE.get(key)
    if e is None:
        e = E_spin_element(gamma, two_s, power, D)
        _ELT_CACHE[key] = e
    return e


def E_spin_element(gamma: Charge, two_s: int, power: int, D: int) -> dict:
    """`E^{(s)}_q(X_gamma)^power` as a G-group element, cone-truncated at D.

    All the `X_{n gamma}` commute (`<gamma, gamma> = 0`), so this is just the
    scalar power series substituted at `x = X_gamma`.
    """
    dg = deg(gamma)
    assert dg >= 1, "generators are indexed by nonzero charges in the cone"
    N = D // dg
    ser = _series_pow(E_spin_series_cached(two_s, N), power, N)
    rank = len(gamma)
    out = {(0,) * rank: CF_ONE}
    for n in range(1, N + 1):
        if not cf_is_zero(ser[n]):
            out[tuple(n * x for x in gamma)] = ser[n]
    return out


def chi(two_s: int) -> dict[int, int]:
    """The spin character `chi_s = sum_{j=-s}^{s} q^{2j}` as a Laurent poly."""
    return {tj: 1 for tj in range(-two_s, two_s + 1, 2)}


def E_spin_linear_coeff(two_s: int) -> Coeff:
    """The x-linear coefficient of `E^{(s)}`: `-q * chi_s / (1 - q^2)`.

    Verified against the series construction in `pbw_controls`.
    """
    num = lp_mul({1: -1}, chi(two_s))
    return _cf_simplify(num, {1: 1})


# --------------------------------------------------------------------------
# Cone enumeration and total orders on Gplus x (1/2)N.
# --------------------------------------------------------------------------


def cone_points(rank: int, d: int) -> list[Charge]:
    """All charges in `Gplus` of cone degree exactly `d`."""
    if rank == 1:
        return [(d,)]
    out = []
    for head in range(d + 1):
        for tail in cone_points(rank - 1, d - head):
            out.append((head,) + tail)
    return out


def decompose_into_chi(lp: dict[int, int]) -> dict[int, int] | None:
    """Write an integral palindromic Laurent poly as `sum_s Omega_s chi_s`.

    Returns `{two_s: Omega}` or None if `lp` is not such a combination.
    Greedy from the top: `chi_s` has top exponent `2s`, so the top coefficient
    of the remainder *is* `Omega_s`.  Integrality of the output is automatic
    once the input has integer coefficients; what can fail is palindromicity.
    """
    if not lp:
        return {}
    if not lp_is_palindromic(lp):
        return None
    rem = dict(lp)
    out: dict[int, int] = {}
    while rem:
        top = max(rem)
        if top < 0:
            return None
        om = rem[top]
        out[top] = out.get(top, 0) + om
        rem = lp_add(rem, lp_neg({e: om * v for e, v in chi(top).items()}))
    return {k: v for k, v in out.items() if v}


# --------------------------------------------------------------------------
# The PBW factorization algorithm, for an ARBITRARY total order.
# --------------------------------------------------------------------------


class PBWFailure(Exception):
    """Raised when a coefficient is not of the form `-q/(1-q^2) * (element of P)`.

    `P` = the integral palindromic Laurent polynomials = `Z`-span of the spin
    characters.  This is exactly the failure the conjecture forbids.
    """

    def __init__(self, gamma, reason, detail=None):
        super().__init__(f"charge {gamma}: {reason}")
        self.gamma = gamma
        self.reason = reason
        self.detail = detail


def ordered_product(factors, B, D, rank, gen=None):
    """`prod (gamma, two_s, Omega)` in the given (already sorted) list order.

    `gen(gamma, two_s, power)` supplies the generator; the default is the
    quantum-torus one, `E^{(s)}(X_gamma)^power`.  Passing a different `gen` is
    what lets the same read-off run over a different filtered algebra -- e.g.
    with `E^{(s)}(L_a)^power` on a `K_q`-algebra's canonical basis.
    """
    if gen is None:
        def gen(gm, ts, p):
            return E_spin_element_cached(gm, ts, p, D)
    out = elt_one(rank)
    for (gamma, two_s, om) in factors:
        out = elt_mul(out, gen(gamma, two_s, om), B, D)
    return out


def pbw_factorize(g, B, D, key, *, check_prefix=True, gen=None):
    """Read off `Omega(gamma, s)` for `g`, in the total order given by `key`.

    `key(gamma, two_s)` returns a sort key: any total order on `Gplus x (1/2)N`.

    Returns `(factors, omega)` where `factors` is the order-sorted list of
    `(gamma, two_s, Omega)` and `omega` maps `(gamma, two_s) -> Omega`.

    Why this is well defined for an ARBITRARY order (not only a cone-compatible
    one): a factor at charge `gamma` of degree `d` is `1 + Omega*c_s*X_gamma`
    plus terms at `2*gamma, 3*gamma, ...`, all of degree `> d`.  Writing the
    ordered product as `U * (1 + A) * V` with `U, V` starting at 1 and `A` of
    degree exactly `d`, we get `U*A*V = A` modulo degree `> d`.  So placement
    of the degree-`d` factors does not affect the degree-`d` coefficients, and
    modulo degree `> d` the product is `P_{<d} + A`.  Hence
    `P_{<d}^{-1} * g = 1 + A + (degree > d)` and each `Omega(gamma, .)` is read
    off the coefficient of `X_gamma` alone.  The order enters only through the
    arrangement of the strictly-lower-degree factors inside `P_{<d}`.
    """
    rank = len(B)
    zero = (0,) * rank
    assert g.get(zero) == CF_ONE, "not a G-group element"
    if gen is None:
        def gen(gm, ts, p):
            return E_spin_element_cached(gm, ts, p, D)
    factors: list[tuple] = []
    omega: dict[tuple, int] = {}
    inv_q_times_1mq2 = cf_from_lp(lp_mul({0: 1, 2: -1}, {-1: -1}))  # (1-q^2)/(-q)
    # prefix[i] = product of factors[:i], cached so that an order which appends
    # (any cone-compatible one) rebuilds nothing, and one which inserts rebuilds
    # only past the earliest insertion point.
    prefix: list[dict] = [elt_one(rank)]

    for d in range(1, D + 1):
        P = prefix[len(factors)]
        Pinv = elt_inv(P, B, D, rank)
        R = elt_mul(Pinv, g, B, D)
        if check_prefix:
            for gg, vv in R.items():
                if 1 <= deg(gg) < d and not cf_is_zero(vv):
                    raise PBWFailure(gg, "prefix not cleared below its degree")
        new = []
        for gamma in cone_points(rank, d):
            c = R.get(gamma, CF_ZERO)
            if cf_is_zero(c):
                continue
            t = cf_mul(c, inv_q_times_1mq2)
            lp = cf_to_lp(t)
            if lp is None:
                raise PBWFailure(gamma, "coefficient not in L*Z[q,q^-1] "
                                        "(a (1-q^{2n}) denominator survives)",
                                 detail=t)
            dec = decompose_into_chi(lp)
            if dec is None:
                raise PBWFailure(gamma, "coefficient not palindromic — "
                                        "no integral spin decomposition",
                                 detail=lp)
            for two_s, om in dec.items():
                new.append((gamma, two_s, om))
                omega[(gamma, two_s)] = om
        if new:
            merged = sorted(factors + new, key=lambda f: key(f[0], f[1]))
            fc = 0
            while fc < len(factors) and factors[fc] == merged[fc]:
                fc += 1
            factors = merged
            del prefix[fc + 1:]
            for i in range(fc, len(factors)):
                gm, ts, om = factors[i]
                prefix.append(elt_mul(prefix[i], gen(gm, ts, om), B, D))
    return factors, omega


