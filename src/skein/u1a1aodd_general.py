def _build_bps(k: int) -> BPSKAlgebra:
    """gauged-A_{2k+1} quiver: 2k+1 dynamical + 1 flavour = 2k+2 nodes."""
    n = 2 * k + 2
    B = [[0] * n for _ in range(n)]
    for i in range(n - 1):
        B[i][i+1] = 1; B[i+1][i] = -1
    node_charges = [tuple(1 if k_==i else 0 for k_ in range(n)) for i in range(2*k+1)]
    return BPSKAlgebra(pairing=B, node_charges=node_charges, verify="off")


def _canonical_seeds(k: int) -> list[tuple]:
    """The known canonical seeds for k = 1, 2, 3.  Higher k needs iteration."""
    n = 2 * k + 2  # BPS lattice dim
    seeds = []
    # L_1: alternating (0,1,0,1,...,0,1) — length n
    L_1_seed = tuple(0 if i % 2 == 0 else 1 for i in range(n))
    seeds.append(L_1_seed)
    # L_2: single 1 at start
    L_2_seed = tuple(1 if i == 0 else 0 for i in range(n))
    seeds.append(L_2_seed)
    if k >= 2:
        # L_3: zeros at odd positions, -1 at even positions (except 0),
        # +1 at F (last coord, position n-1).
        # F-direction (position n-1) ALWAYS gets +1 regardless of parity.
        def _l3_entry(i):
            if i == n - 1: return 1   # F direction always
            if i % 2 == 1: return 0
            if i == 0:     return 0
            return -1                  # even, positive, not n-1
        L_3_seed = tuple(_l3_entry(i) for i in range(n))
        seeds.append(L_3_seed)
    # L_4 (k ≥ 3): e_0 + e_{n-2}.  Pattern verified at k=3 (period 5,
    # the "last family" with -1E cocycle for k=3) and k=4 (period 12, the
    # "intermediate non-magnetic-pair family" for k=4).
    if k >= 3:
        L_4_seed = tuple(1 if i in (0, n-2) else 0 for i in range(n))
        seeds.append(L_4_seed)
    # L_5 (k ≥ 4): L_3 + e_{n-3}.  Discovered at k=4: the "last family"
    # with period k+2 and -1E cocycle.
    if k >= 4:
        L_3_seed_again = seeds[2]  # the L_3 we just built
        L_5_seed = tuple(
            L_3_seed_again[i] + (1 if i == n - 3 else 0)
            for i in range(n)
        )
        seeds.append(L_5_seed)
    return seeds


def _ρ_orbit_length(bps: BPSKAlgebra, seed: tuple, E_charge: tuple,
                    max_iters: int = 20) -> int:
    """Determine ρ-orbit length mod E for a seed."""
    n = len(seed)
    cur = seed; seen = [seed]
    for step in range(max_iters):
        cur = tuple(bps.rho(cur))
        for j, prev in enumerate(seen):
            d = tuple(cur[k_] - prev[k_] for k_ in range(n))
            for ke in range(-5, 6):
                if d == tuple(ke * E_charge[k_] for k_ in range(n)):
                    return step + 1 - j  # period
        seen.append(cur)
    raise RuntimeError(f"ρ-orbit didn't close in {max_iters} steps")


def _bootstrap_chord_charges(k: int) -> tuple[dict, tuple, BPSKAlgebra]:
    """Compute primitive chord charges for U1A1AoddKAlg(k).
    Returns (chord_charges dict {(a, i): charge_tuple}, E_charge, bps).

    SCOPE: k ∈ {1, 2, 3, 4}.  Higher k raises NotImplementedError —
    new primitive seeds must be hand-discovered (see module docstring)."""
    if k < 1:
        raise ValueError(f"k must be >= 1, got {k}")
    if k > 4:
        raise NotImplementedError(
            f"U1A1AoddKAlg bootstrap not implemented for k={k}: "
            f"_canonical_seeds only knows k <= 4 (seeds hand-discovered "
            f"from BPS exploration).  Higher k needs new seeds, ideally "
            f"derived from an RGKAlgebra presentation since the auxiliary "
            f"BPSKAlgebra becomes too slow at k >= 5."
        )
    bps = _build_bps(k)
    n = 2 * k + 2
    # E: alternating (1,0,1,0,...,1,0)
    E_charge = tuple(1 if i % 2 == 0 else 0 for i in range(n))

    seeds = _canonical_seeds(k)
    chord_charges = {}
    family_periods = {}
    for a, seed in enumerate(seeds, start=1):
        period = _ρ_orbit_length(bps, seed, E_charge)
        family_periods[a] = period
        # Build the ρ-orbit
        cur = seed
        chord_charges[(a, 0)] = seed
        for i in range(1, period):
            cur = tuple(bps.rho(cur))
            chord_charges[(a, i)] = cur
    return chord_charges, E_charge, bps, family_periods


