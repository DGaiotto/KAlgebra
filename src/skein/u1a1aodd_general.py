"""
u1a1aodd_general.py
===================

General U1A1AoddKAlg(k) — u(1)-gauged [A_1, A_{2k+1}] AD theory for any k ≥ 1.

VALIDATED for k = 1, 2, 3, 4.  Bootstrap output:
  k=1: H=6,  primitive periods {L_1: 6,  L_2: 3},                              9 chord-gens, 28 cones
  k=2: H=8,  primitive periods {L_1: 8,  L_2: 8,  L_3: 4},                    20 chord-gens, 264 cones
  k=3: H=10, primitive periods {L_1: 10, L_2: 10, L_3: 10, L_4: 5},           35 chord-gens, 2860 cones
  k=4: H=12, primitive periods {L_1: 12, L_2: 12, L_3: 12, L_4: 12, L_5: 6},  54 chord-gens, 33592 cones

UNIVERSAL PATTERN: k+1 primitive chord families.  LAST family has period
k+2 (mod E with -1E cocycle).  Other families have period 2k+4 = H.

ARCHITECTURE:
  - k-universal: FiniteConeData framework, derived_multiply, trace_layer1
  - k-specific data: chord_charges + MULT_TABLE generated by bootstrap

BOOTSTRAP SCOPE — k ∈ {1, 2, 3, 4} ONLY (hand-discovered seeds):
  1. Build BPSKAlgebra for gauged-A_{2k+1} quiver
  2. Use the **hand-discovered** canonical seeds in `_canonical_seeds`:
       L_1: alternating (0,1,0,1,...,0,1)
       L_2: single 1 at start (1,0,...,0)
       L_3: zeros at odd, -1 at even (except 0), +1 at F (k ≥ 2)
       L_4: e_0 + e_{n-2}                  (k ≥ 3)
       L_5: L_3 + e_{n-3}                  (k ≥ 4)
  3. Generate MULT_TABLE via `_decompose` (greedy q-commuting search,
     `max_factors=4`).  At k ≤ 4 every Plücker daughter decomposes.

For k ≥ 5 the bootstrap WILL fail at `_bootstrap_chord_charges` /
`_decompose`: new primitive seed patterns must be discovered by hand
(or by an automated discovery loop — NOT IMPLEMENTED).  As k grows,
the auxiliary BPSKAlgebra becomes too slow to enumerate; an
RGKAlgebra-presented path is the planned route to higher k.

PATTERN OBSERVED (k=1, 2, 3, 4): k+1 primitive chord families.

USAGE:
  A = U1A1AoddKAlg(k=2)   # = U1OctaKAlg
  A = U1A1AoddKAlg(k=3)   # = U1DecagonKAlg
  A.multiply(label_a, label_b)
  A.trace_layer1(label)
"""
