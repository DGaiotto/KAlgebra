def test_the_strip_order_gives_one_generator_per_node_on_an_acyclic_quiver():
    """**The flavoured spec of an acyclic quiver is its node data.**

    On an acyclic flavoured quiver the source/sink strip order gives

        S  =  ∏_a E^{(0;r_a)}_\\fq(X_{γ_a}) ,

    exactly `rank` factors — one per REDUCED node, at spin `0`, carrying
    precisely that node's own rep `r_a` and nothing else.  This is the flavoured
    form of the repo's mantle statement (acyclic ⇒ topological product spec),
    and it is a spec in the working sense: finite, spin-`0`, positive.

    It also attains the floor.  At cone degree `1` the accumulated product is
    still empty, so every node must carry a factor in every order; `rank` is
    therefore the minimum and the strip reaches it.
    """
    acyclic = [e for e in CORPUS if e[0] != "3-cycle, SU(2)"]
    assert acyclic
    for name, B, fac, D in acyclic:
        Q = FlavouredQuiver(B, fac)
        n = Q.rank
        charges = [tuple(1 if j == i else 0 for j in range(n)) for i in range(n)]
        order = acyclic_node_order(B, charges)
        assert order is not None, name
        key = mean_rank_key(order)
        eng = FlavouredFactorSpectrum(
            Q, D, piece_key=lambda k, two_s, r, key=key: (key(k), k, two_s, r))
        eng.run()
        want = {tuple(1 if i == a else 0 for i in range(n)):
                {(Q.node_reps[a], 0): 1} for a in range(n)}
        assert eng.multiplicities_by_spin() == want, name
        assert eng.verify_omega_is_a_character() == [], name


def test_the_strip_honest_fails_on_a_quiver_that_is_not_acyclic():
    """Where the strip leaves a core it determines nothing, and says so.

    The flavoured mantle statement is about acyclic quivers; it is not silently
    extended to the rest.
    """
    B = [[0, 1, -1], [-1, 0, 1], [1, -1, 0]]
    charges = [(1, 0, 0), (0, 1, 0), (0, 0, 1)]
    assert acyclic_node_order(B, charges) is None


def test_the_flavoured_factorisation_is_shorter_than_the_unfolded_one():
    """`\\cE_G` packs each group of `N_a` unfolded factors into one generator.

    On an acyclic quiver both routes attain their own floor — one factor per
    node — so the counts are the number of REDUCED nodes against the number of
    UNFOLDED ones, `g` against `Σ_a dim r_a`.  This is where the flavoured
    construction is genuinely more economical; it is NOT more economical in the
    cone (see `flavoured_s_axioms.md` §7, where that claim is retracted).
    """
    for name, B, fac, D in (("A2, SU(2)", [[0, 1], [-1, 0]], [2, 1], 5),
                            ("A2, SU(3)", [[0, 1], [-1, 0]], [3, 1], 5),
                            ("A2, SU(2)xSU(3)", [[0, 1], [-1, 0]], [2, 3], 4)):
        Q = FlavouredQuiver(B, fac)
        n = Q.rank
        charges = [tuple(1 if j == i else 0 for j in range(n)) for i in range(n)]
        key = mean_rank_key(acyclic_node_order(B, charges))
        eng = FlavouredFactorSpectrum(
            Q, D, piece_key=lambda k, two_s, r, key=key: (key(k), k, two_s, r))
        eng.run()
        flavoured = sum(len(v) for v in eng.multiplicities_by_spin().values())

        Bu, chu, _ = Q.unfold()
        ref = BPSFactorSpectrum(Bu, chu, D, order="strip")
        ref.run()
        unfolded = sum(len(v) for v in ref.multiplicities().values())

        assert flavoured == n, (name, flavoured)
        assert unfolded == len(chu), (name, unfolded)
        assert flavoured < unfolded, (name, flavoured, unfolded)


