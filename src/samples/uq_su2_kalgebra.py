def _q(n: int) -> LaurentPoly:
    return LaurentPoly({n: 1})


def _add(out: dict, key, coeff: LaurentPoly) -> None:
    if coeff.is_zero():
        return
    cur = out.get(key)
    s = coeff if cur is None else cur + coeff
    if s.is_zero():
        out.pop(key, None)
    else:
        out[key] = s


# ---------------------------------------------------------------------------
# The straightening engine (PBW normal form of the central quotient)
# ---------------------------------------------------------------------------
#
# Internal monomial key: (side, p, k, w)
#   side 'K':  K^k                 (p stored as 0)
#   side 'E':  K^k E^p   (p ≥ 1)
#   side 'F':  F^p K^k   (p ≥ 1)
#   w:         the flavour-ring key of the character multiplying the monomial
# value: LaurentPoly in 𝖖.
#
# The relations used: KE = 𝖖⁻²EK (so EK = 𝖖²KE, K⁻¹E = 𝖖²EK⁻¹), KF = 𝖖²FK,
# EF = χ₁ + 𝖖K + 𝖖⁻¹K⁻¹, FE = χ₁ + 𝖖⁻¹K + 𝖖K⁻¹; whence
#   E F^p = χ₁ F^{p−1} + 𝖖^{2p−1} F^{p−1} K + 𝖖^{1−2p} F^{p−1} K⁻¹ ,
#   F E^p = χ₁ E^{p−1} + 𝖖^{1−2p} E^{p−1} K + 𝖖^{2p−1} E^{p−1} K⁻¹ .
# χ₁ is central and is FUSED into the ring key through `multiply_basis`.


class _Engine:
    """Left multiplication by the generators on internal monomials, with the
    Casimir `χ₁` fused into the flavour-ring key."""

    def __init__(self, ring: ZPlusRing, chi1) -> None:
        self.R = ring
        self.chi1 = chi1
        self._fuse_cache: dict = {}

    def fuse_chi1(self, w) -> dict:
        """`χ₁ · χ_w` as `{key: multiplicity}` (Clebsch–Gordan through the ring)."""
        got = self._fuse_cache.get(w)
        if got is None:
            got = dict(self.R.multiply_basis(w, self.chi1))
            self._fuse_cache[w] = got
        return got

    def _add_chi1(self, out: dict, side, p, k, w, coeff: LaurentPoly) -> None:
        for w2, m in self.fuse_chi1(w).items():
            _add(out, (side, p, k, w2), coeff * m if m != 1 else coeff)

    def lm_K(self, sign: int, mono, coeff: LaurentPoly) -> dict:
        """Left-multiply `K^{sign}` (sign = ±1)."""
        side, p, k, w = mono
        out: dict = {}
        if side == 'K':
            _add(out, ('K', 0, k + sign, w), coeff)
        elif side == 'E':                        # K^{±1}·K^k E^p
            _add(out, ('E', p, k + sign, w), coeff)
        else:                                    # K^{±1}·F^p K^k = 𝖖^{±2p} F^p K^{k±1}
            _add(out, ('F', p, k + sign, w), _q(sign * 2 * p) * coeff)
        return out

    def lm_E(self, mono, coeff: LaurentPoly) -> dict:
        side, p, k, w = mono
        out: dict = {}
        if side == 'K':                          # E·K^k = 𝖖^{2k} K^k E
            _add(out, ('E', 1, k, w), _q(2 * k) * coeff)
        elif side == 'E':                        # E·K^k E^p = 𝖖^{2k} K^k E^{p+1}
            _add(out, ('E', p + 1, k, w), _q(2 * k) * coeff)
        else:                                    # E·F^p K^k
            if p == 1:
                self._add_chi1(out, 'K', 0, k, w, coeff)                    # χ₁ K^k
                _add(out, ('K', 0, k + 1, w), _q(1) * coeff)                # 𝖖 K^{k+1}
                _add(out, ('K', 0, k - 1, w), _q(-1) * coeff)               # 𝖖⁻¹ K^{k−1}
            else:
                self._add_chi1(out, 'F', p - 1, k, w, coeff)                # χ₁ F^{p−1} K^k
                _add(out, ('F', p - 1, k + 1, w), _q(2 * p - 1) * coeff)    # 𝖖^{2p−1} F^{p−1} K^{k+1}
                _add(out, ('F', p - 1, k - 1, w), _q(1 - 2 * p) * coeff)    # 𝖖^{1−2p} F^{p−1} K^{k−1}
        return out

    def lm_F(self, mono, coeff: LaurentPoly) -> dict:
        side, p, k, w = mono
        out: dict = {}
        if side == 'K':                          # F·K^k
            _add(out, ('F', 1, k, w), coeff)
        elif side == 'F':                        # F·F^p K^k
            _add(out, ('F', p + 1, k, w), coeff)
        else:                                    # F·K^k E^p = 𝖖^{−2k} K^k (F E^p)
            base = _q(-2 * k) * coeff
            if p == 1:
                self._add_chi1(out, 'K', 0, k, w, base)                     # χ₁ K^k
                _add(out, ('K', 0, k + 1, w), _q(-1) * base)                # 𝖖⁻¹ K^{k+1}
                _add(out, ('K', 0, k - 1, w), _q(1) * base)                 # 𝖖 K^{k−1}
            else:
                # K^k E^{p−1} K = 𝖖^{2(p−1)} K^{k+1} E^{p−1};  … K⁻¹ = 𝖖^{−2(p−1)} K^{k−1} E^{p−1}
                self._add_chi1(out, 'E', p - 1, k, w, base)
                _add(out, ('E', p - 1, k + 1, w), _q(1 - 2 * p + 2 * (p - 1)) * base)
                _add(out, ('E', p - 1, k - 1, w), _q(2 * p - 1 - 2 * (p - 1)) * base)
        return out

    def left_mult_gen(self, g: str, X: dict) -> dict:
        out: dict = {}
        for mono, coeff in X.items():
            if g == 'K':
                part = self.lm_K(+1, mono, coeff)
            elif g == 'Ki':
                part = self.lm_K(-1, mono, coeff)
            elif g == 'E':
                part = self.lm_E(mono, coeff)
            else:
                part = self.lm_F(mono, coeff)
            for kk, cc in part.items():
                _add(out, kk, cc)
        return out

    @staticmethod
    def word(mono) -> list:
        """Generator word (left to right) of the monomial, flavour key aside."""
        side, p, k, _w = mono
        kw = (['K'] * k) if k >= 0 else (['Ki'] * (-k))
        if side == 'K':
            return kw
        if side == 'E':
            return kw + ['E'] * p
        return ['F'] * p + kw

    def mono_mult(self, m1, c1: LaurentPoly, m2, c2: LaurentPoly) -> dict:
        """`(χ_{w1} M1) · (χ_{w2} M2)`: apply M1's word onto `{M2: c1 c2}`, then
        fuse the two flavour keys (both central)."""
        X = {(m2[0], m2[1], m2[2], m2[3]): c1 * c2}
        for g in reversed(self.word(m1)):
            X = self.left_mult_gen(g, X)
        w1 = m1[3]
        if w1 == self.R.one_basis():
            return X
        out: dict = {}
        for (s, p, k, w2), c in X.items():
            for w3, m in self.R.multiply_basis(w1, w2).items():
                _add(out, (s, p, k, w3), c * m if m != 1 else c)
        return out


